    private static bool AlliancePending(CompanyManagementUiState state, string companyId, CompanyRelationKind kind)
    {
        if (kind != CompanyRelationKind.Neutral)
            return false;

        var terms = RelationWith(state, companyId);
        return (terms?.WeOfferAlliance ?? false) || (terms?.TheyOfferAlliance ?? false);
    }

    private static int RelationRank(CompanyManagementUiState state, string companyId, CompanyRelationKind kind)
    {
        if (kind == CompanyRelationKind.War)
            return 0;
        if (kind == CompanyRelationKind.Alliance)
            return 1;
        if (AlliancePending(state, companyId, kind))
            return 2;
        return 3;
    }

    private static Color RelationColor(CompanyRelationKind kind)
    {
        return kind switch
        {
            CompanyRelationKind.War => Color.FromHex("#e06060"),
            CompanyRelationKind.Alliance => Color.FromHex("#5dba8c"),
            _ => Color.FromHex("#9a9a9a"),
        };
    }

    private static string Display(string? text)
    {
        if (string.IsNullOrWhiteSpace(text))
            return string.Empty;
        return Loc.TryGetString(text, out var localized) && !string.IsNullOrWhiteSpace(localized)
            ? localized
            : text;
    }

    private bool TryGetCompanyIcon(string? iconId, out Texture texture)
    {
        texture = default!;
        if (string.IsNullOrWhiteSpace(iconId))
            return false;
        if (!_proto.TryIndex<CompanyIconPrototype>(iconId, out var icon))
            return false;

        texture = _sprite.Frame0(icon.Icon);
        return true;
    }

