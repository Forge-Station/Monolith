namespace Content.Client.Options.UI.Tabs;

[GenerateTypedNameReferences]
public sealed partial class MiscTab : Control
{
    [Dependency] private IPlayerManager _playerManager = default!;
    [Dependency] private IPrototypeManager _prototypeManager = default!;
    [Dependency] private IConfigurationManager _cfg = default!; // Forge-Change

    private readonly OptionDropDownCVar<string> _hudThemeOption; // Forge-Change

    public MiscTab()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        var themes = _prototypeManager.EnumeratePrototypes<HudThemePrototype>().ToList();
        themes.Sort();
        var themeEntries = new List<OptionDropDownCVar<string>.ValueOption>();
        foreach (var gear in themes)
        {
            themeEntries.Add(new OptionDropDownCVar<string>.ValueOption(gear.ID, Loc.GetString(gear.Name)));
        }

        var layoutEntries = new List<OptionDropDownCVar<string>.ValueOption>();
        foreach (var layout in Enum.GetValues(typeof(ScreenType)))
        {
            layoutEntries.Add(new OptionDropDownCVar<string>.ValueOption(layout.ToString()!, Loc.GetString($"ui-options-hud-layout-{layout.ToString()!.ToLower()}")));
        }

        // Channel can be null in replays so.
        // ReSharper disable once ConditionalAccessQualifierIsNonNullableAccordingToAPIContract
        ShowOocPatronColor.Visible = _playerManager.LocalSession?.Channel?.UserData.PatronTier is { };

        _hudThemeOption = Control.AddOptionDropDown(CVars.InterfaceTheme, DropDownHudTheme, themeEntries); // Forge-Change: kept to reload it when a skin swaps the theme
        Control.AddOptionDropDown(CCVars.UILayout, DropDownHudLayout, layoutEntries);
        // Forge-Change-Start: the Wolfgate skin picker and the simplified interface option. Apply saves options in the
        // order they are added, and saving a skin switches the HUD theme to its pair, so the skin goes after the theme:
        // the other way round the theme drop-down would write its stale selection back over the paired theme.
        var styleEntries = WolfgateSkins.All
            .Select(skin => new OptionDropDownCVar<string>.ValueOption(skin.Id, Loc.GetString(skin.Name)))
            .ToList();
        Control.AddOptionDropDown(WolfgateCVars.UiStyle, DropDownWolfgateStyle, styleEntries);
        Control.AddOptionCheckBox(ForgeCCVars.UiSimplified, SimplifiedUiCheckBox);
        // Forge-Change-End
        Control.AddOptionCheckBox(WolfgateCVars.CockpitAutoEnter, CockpitAutoEnterCheckBox); // WOLFGATE(Cockpit): option to open the cockpit view automatically

        Control.AddOptionCheckBox(CVars.DiscordEnabled, DiscordRich);
        Control.AddOptionCheckBox(CCVars.ShowOocPatronColor, ShowOocPatronColor);
        Control.AddOptionCheckBox(CCVars.LoocAboveHeadShow, ShowLoocAboveHeadCheckBox);
        Control.AddOptionCheckBox(CCVars.HudHeldItemShow, ShowHeldItemCheckBox);
        Control.AddOptionCheckBox(CCVars.CombatModeIndicatorsPointShow, ShowCombatModeIndicatorsCheckBox);
        Control.AddOptionCheckBox(CCVars.OpaqueStorageWindow, OpaqueStorageWindowCheckBox);
        Control.AddOptionCheckBox(CCVars.ChatEnableFancyBubbles, FancySpeechBubblesCheckBox);
        Control.AddOptionCheckBox(CCVars.ChatFancyNameBackground, FancyNameBackgroundsCheckBox);
        Control.AddOptionCheckBox(CCVars.LogInChat, LogInChatCheckBox);
        Control.AddOptionCheckBox(CCVars.CoalesceIdenticalMessages, CoalesceIdenticalMessagesCheckBox);
        Control.AddOptionCheckBox(CCVars.StaticStorageUI, StaticStorageUI);
        Control.AddOptionCheckBox(CCVars.DetailedExamine, DetailedExamineCheckBox); // Goobstation Change
        Control.AddOptionCheckBox(MonoCVars.RadioNoiseEnabled, RadioNoiseCheckBox); // Mono
        Control.AddOptionCheckBox(MonoCVars.AreaEchoEnabled, AreaEchoCheckBox); // Mono
        Control.AddOptionCheckBox(MonoCVars.AreaEchoHighResolution, AreaEchoHighResolutionCheckBox); // Mono

        Control.Initialize();
    }

    // Forge-Change-Start: a skin change switches the HUD theme behind this tab's back; show the theme that is now
    // active instead of leaving the old selection pending.
    protected override void EnteredTree()
    {
        base.EnteredTree();
        _cfg.OnValueChanged(CVars.InterfaceTheme, OnHudThemeChanged);
    }

    protected override void ExitedTree()
    {
        _cfg.UnsubValueChanged(CVars.InterfaceTheme, OnHudThemeChanged);
        base.ExitedTree();
    }

    private void OnHudThemeChanged(string _)
    {
        _hudThemeOption.LoadValue();
        Control.ValueChanged();
    }
    // Forge-Change-End
}
