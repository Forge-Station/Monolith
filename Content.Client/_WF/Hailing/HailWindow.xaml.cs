using Content.Client.UserInterface.Controls;
using Content.Shared._WF.Hailing;
using Robust.Client.AutoGenerated;
using Robust.Client.Player;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._WF.Hailing;

/// <summary>
/// The hail window beside the shuttle console: a screen showing the other pilot, the ships in range to
/// hail, and the chat once a channel is open. The hail itself is a component on the console, which the
/// window polls.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class HailWindow : FancyWindow
{
    [Dependency] private IEntityManager _entManager = default!;
    [Dependency] private IPlayerManager _player = default!;

    /// <summary>Seconds between asking for the ships in range while the list is up.</summary>
    private const float TargetInterval = 2f;

    private static readonly Color OwnColor = Color.FromHex("#6fc3ff");
    private static readonly Color PeerColor = Color.FromHex("#ffbf40");
    private static readonly Color SystemColor = Color.FromHex("#8a8a8a");

    /// <summary>The window wants a fresh list of ships.</summary>
    public event Action? TargetsRequested;

    /// <summary>The pilot hailed a ship from the list.</summary>
    public event Action<NetEntity>? HailRequested;

    /// <summary>The pilot answered or declined the incoming hail.</summary>
    public event Action<bool>? AnswerRequested;

    /// <summary>The pilot cancelled their hail or closed the channel.</summary>
    public event Action? EndRequested;

    /// <summary>The pilot sent a line.</summary>
    public event Action<string>? SayRequested;

    private readonly Dictionary<NetEntity, ContactRow> _rows = new();
    private readonly HashSet<NetEntity> _listed = new();
    private readonly List<NetEntity> _gone = new();

    private EntityUid? _console;
    private NetEntity? _netConsole;
    private bool _standalone;
    private HailState? _state;
    private bool _transmit;
    private NetEntity? _person;
    private string _personName = string.Empty;
    private string _ship = string.Empty;
    private bool _callView;
    private int _nextLine;
    private float _targetAccumulator = TargetInterval;

    public HailWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        ChatEntry.IsValid = text => text.Length <= HailConsoleComponent.MaxLineLength;
        ChatEntry.OnTextEntered += _ => Send();
        SendButton.OnPressed += _ => Send();
        AnswerButton.OnPressed += _ => AnswerRequested?.Invoke(true);
        EndButton.OnPressed += _ => EndRequested?.Invoke();

        DeclineButton.OnPressed += _ =>
        {
            if (_state == HailState.Ringing)
                AnswerRequested?.Invoke(false);
            else
                EndRequested?.Invoke();
        };

        BackButton.OnPressed += _ =>
        {
            _callView = false;
            StatusLabel.Text = string.Empty;
            Apply(null);
        };

        Apply(null);
    }

    /// <summary>
    /// Points the window at a console, or nothing.
    /// </summary>
    public void SetConsole(EntityUid? console)
    {
        if (_console == console)
            return;

        _console = console;
        Refresh();
    }

    /// <summary>
    /// Points the window at an entity that may not have reached this client yet.
    /// </summary>
    public void SetConsole(NetEntity console)
    {
        _netConsole = console;
        _console = null;
        Refresh();
    }

    /// <summary>
    /// Makes this a window onto one hail with no console behind it: no contact list to go back to, and
    /// whoever has the window may transmit.
    /// </summary>
    public void SetStandalone()
    {
        _standalone = true;
        _callView = true;
        Apply(null);
    }

    /// <summary>
    /// Replaces the list of ships in range, keeping the rows that are still on it.
    /// </summary>
    public void UpdateTargets(List<HailTarget> targets)
    {
        _listed.Clear();

        foreach (var target in targets)
        {
            _listed.Add(target.Ship);

            if (!_rows.TryGetValue(target.Ship, out var row))
            {
                var ship = target.Ship;
                row = new ContactRow();
                row.Hail.OnPressed += _ => HailRequested?.Invoke(ship);
                _rows.Add(ship, row);
                ContactList.AddChild(row);
            }

            row.Update(target);
        }

        foreach (var ship in _rows.Keys)
        {
            if (!_listed.Contains(ship))
                _gone.Add(ship);
        }

        foreach (var ship in _gone)
        {
            ContactList.RemoveChild(_rows[ship]);
            _rows.Remove(ship);
        }

        _gone.Clear();
        NoContactsLabel.Visible = targets.Count == 0;
    }

    /// <summary>
    /// Says why a hail or call stopped.
    /// </summary>
    public void ShowEnded(HailEndReason reason, string ship)
    {
        var text = EndText(reason, ship);
        StatusLabel.Text = text;

        if (_callView)
            AddSystemLine(text);
    }

    /// <summary>The line shown for each way a hail can stop.</summary>
    public static string EndText(HailEndReason reason, string ship)
    {
        var key = reason switch
        {
            HailEndReason.Closed => "hail-ended-closed",
            HailEndReason.PeerClosed => "hail-ended-peer-closed",
            HailEndReason.Declined => "hail-ended-declined",
            HailEndReason.NoAnswer => "hail-ended-no-answer",
            HailEndReason.Busy => "hail-ended-busy",
            HailEndReason.Lost => "hail-ended-lost",
            HailEndReason.Cooldown => "hail-ended-cooldown",
            _ => "hail-ended-unavailable",
        };

        return Loc.GetString(key, ("ship", ship));
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        Refresh();

        if (_callView)
            return;

        _targetAccumulator += args.DeltaSeconds;

        if (_targetAccumulator < TargetInterval)
            return;

        _targetAccumulator = 0f;
        TargetsRequested?.Invoke();
    }

    private void Refresh()
    {
        HailConsoleComponent? hail = null;

        if (_console == null && _netConsole is { } pending && _entManager.TryGetEntity(pending, out var arrived))
            _console = arrived;

        if (_console != null)
            _entManager.TryGetComponent(_console, out hail);

        var state = hail?.State;
        var transmit = hail != null &&
                       (_standalone || hail.Operator != null && _entManager.GetNetEntity(_player.LocalEntity) == hail.Operator);

        if (state != _state || transmit != _transmit || hail?.PeerOperator != _person || (hail != null && hail.PeerName != _personName))
        {
            // A fresh hail starts on a clean log; the last call's stays up until then.
            if (_state == null && state != null)
            {
                ChatLog.Clear();
                _nextLine = 0;
                _callView = true;
            }

            if (state == HailState.Connected && _state != HailState.Connected)
                AddSystemLine(Loc.GetString("hail-log-open", ("ship", hail!.PeerShip)));

            // A hail that stops ringing was cancelled or taken at another console; nobody tells this one.
            if (state == null && _state == HailState.Ringing)
            {
                StatusLabel.Text = Loc.GetString("hail-ended-ringing", ("ship", _ship));
                AddSystemLine(StatusLabel.Text);
            }

            _ship = hail?.PeerShip ?? _ship;

            _state = state;
            _transmit = transmit;
            _person = hail?.PeerOperator;
            _personName = hail?.PeerName ?? string.Empty;
            Apply(hail);
        }

        if (hail == null)
            return;

        foreach (var line in hail.Log)
        {
            if (line.Sequence < _nextLine)
                continue;

            _nextLine = line.Sequence + 1;
            AddLine(line);
        }
    }

    /// <summary>
    /// Lays the window out for what the console is doing.
    /// </summary>
    private void Apply(HailConsoleComponent? hail)
    {
        ContactsBox.Visible = !_callView;
        CallBox.Visible = _callView;

        if (!_callView)
        {
            Viewscreen.ShowStatic(Loc.GetString("hail-screen-no-signal"));
            _targetAccumulator = TargetInterval;
            return;
        }

        PendingRow.Visible = hail != null && hail.State != HailState.Connected;
        ChatRow.Visible = hail?.State == HailState.Connected;
        BackButton.Visible = hail == null && !_standalone;

        if (hail == null)
        {
            Viewscreen.ShowStatic(Loc.GetString("hail-screen-closed"));
            return;
        }

        switch (hail.State)
        {
            case HailState.Calling:
                StatusLabel.Text = Loc.GetString("hail-banner-calling", ("ship", hail.PeerShip));
                Viewscreen.ShowStatic(Loc.GetString("hail-screen-calling"), hail.PeerShip);
                AnswerButton.Visible = false;
                DeclineButton.Text = Loc.GetString("hail-cancel");
                break;

            case HailState.Ringing:
                StatusLabel.Text = Loc.GetString("hail-banner-incoming", ("ship", hail.PeerShip));
                Viewscreen.ShowStatic(Loc.GetString("hail-screen-incoming"), hail.PeerShip);
                AnswerButton.Visible = true;
                DeclineButton.Text = Loc.GetString("hail-decline");
                break;

            case HailState.Connected:
                StatusLabel.Text = Loc.GetString("hail-banner-open", ("ship", hail.PeerShip));
                if (hail.Divine)
                    Viewscreen.ShowDivine(hail.PeerName);
                else
                    Viewscreen.ShowFeed(hail.PeerOperator, hail.PeerShip, hail.PeerName, Loc.GetString("hail-screen-no-visual"));

                ChatEntry.Editable = _transmit;
                SendButton.Disabled = !_transmit;
                ChatEntry.PlaceHolder = Loc.GetString(_transmit ? "hail-chat-placeholder" : "hail-chat-listening");
                break;
        }
    }

    private void Send()
    {
        var text = ChatEntry.Text.Trim();

        if (text.Length == 0 || !_transmit)
            return;

        SayRequested?.Invoke(text);
        ChatEntry.Clear();
    }

    private void AddLine(HailLine line)
    {
        var message = new FormattedMessage();
        message.PushColor(line.Own ? OwnColor : PeerColor);
        message.AddText(Loc.GetString("hail-chat-sender", ("name", line.Sender)));
        message.Pop();
        message.AddText(line.Text);
        ChatLog.AddMessage(message);
    }

    private void AddSystemLine(string text)
    {
        var message = new FormattedMessage();
        message.PushColor(SystemColor);
        message.AddText(text);
        message.Pop();
        ChatLog.AddMessage(message);
    }

    /// <summary>One ship on the contact list.</summary>
    private sealed class ContactRow : BoxContainer
    {
        public readonly Button Hail;

        private readonly Label _name;
        private readonly Label _distance;

        public ContactRow()
        {
            Orientation = LayoutOrientation.Horizontal;
            HorizontalExpand = true;
            SeparationOverride = 6;
            Margin = new Thickness(4, 1);

            AddChild(_name = new Label { HorizontalExpand = true, ClipText = true });
            AddChild(_distance = new Label { StyleClasses = { "LabelSubText" } });
            AddChild(Hail = new Button { StyleClasses = { "ButtonSquare" }, MinWidth = 70 });
        }

        public void Update(HailTarget target)
        {
            _name.Text = target.Name;
            _distance.Text = Loc.GetString("hail-contact-distance", ("distance", MathF.Round(target.Distance / 10f) * 10f));
            Hail.Text = Loc.GetString(target.Busy ? "hail-contact-busy" : "hail-contact-hail");
            Hail.Disabled = target.Busy;
        }
    }
}
