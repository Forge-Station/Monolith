    private void AddSpendSection(string titleId, string kind, CompanyManagementUiState state)
    {
        var entries = state.Spends.Where(entry => entry.Kind == kind).ToList();
        if (entries.Count == 0)
            return;

        _developmentTab.AddChild(_styles.MakeSection(Loc.GetString(titleId)));
        if (kind == CompanySpendKind.Research)
        {
            _developmentTab.AddChild(_styles.MakeText(Loc.GetString("company-research-intro"), _styles.Theme.SubText));
            _developmentTab.AddChild(_styles.MakeText(Loc.GetString("company-research-archive-now", ("points", Money(state.ResearchPoints)))));
        }
        foreach (var entry in entries)
            _developmentTab.AddChild(kind == CompanySpendKind.Contract
                ? BuildContractCard(entry, state)
                : BuildSpendCard(entry, state));
    }

    private Control BuildSpendCard(CompanySpendEntry entry, CompanyManagementUiState state)
    {
        var root = new BoxContainer { Orientation = LayoutOrientation.Vertical, SeparationOverride = 3 };
        root.AddChild(_styles.MakeHeading(Display(entry.Title)));

        var purpose = Loc.GetString(entry.Purpose, ("amount", entry.Arg1), ("next", entry.Arg2), ("refund", entry.Arg1));
        if (entry.Kind == CompanySpendKind.Ship && !string.IsNullOrWhiteSpace(entry.Detail))
            purpose = Display(entry.Detail) + "\n" + purpose;
        root.AddChild(_styles.MakeText(purpose, _styles.Theme.SubText));
        if (entry.Kind == CompanySpendKind.Research)
        {
            root.AddChild(_styles.MakeText(Loc.GetString("company-research-need", ("cost", Money(entry.Cost)))));
            if (entry.Owned)
                root.AddChild(_styles.MakeText(Loc.GetString("company-research-opened")));
            else
            {
                var left = entry.Cost - state.ResearchPoints;
                if (left < 0)
                    left = 0;
                root.AddChild(_styles.MakeText(Loc.GetString("company-research-left", ("amount", Money(left)))));
            }

            return _styles.MakeCard(root);
        }

        if (entry.Kind is CompanySpendKind.Supply or CompanySpendKind.Ship)
            root.AddChild(_styles.MakeText(Loc.GetString("company-spend-cargo-only")));
        root.AddChild(_styles.MakeText(Loc.GetString("company-spend-cost", ("cost", Money(entry.Cost)))));
        root.AddChild(_styles.MakeText(Loc.GetString("company-spend-balance", ("balance", Money(state.BankBalance)))));
        if (state.AtWar)
            root.AddChild(_styles.MakeText(Loc.GetString("company-war-spendable", ("spendable", Money(state.SpendableBalance)))));
        if (entry.Discounted)
            root.AddChild(_styles.MakeText(Loc.GetString("company-spend-discounted")));
        if (entry.Owned)
            root.AddChild(_styles.MakeText(Loc.GetString("company-spend-owned")));
        else if (state.SpendableBalance < entry.Cost)
            root.AddChild(_styles.MakeText(Loc.GetString("company-spend-short", ("amount", Money(entry.Cost - state.SpendableBalance)))));
        if (!entry.CanBuy)
            root.AddChild(_styles.MakeText(Loc.GetString("company-spend-no-permission")));

        if (entry.CanBuy && !entry.Owned)
        {
            var action = entry.Kind switch
            {
                CompanySpendKind.Supply => CompanyManagementUiAction.BuySupply,
                CompanySpendKind.Ship => CompanyManagementUiAction.BuyShip,
                _ => CompanyManagementUiAction.BuyProject,
            };
            var button = _styles.MakeButton(Loc.GetString(entry.Kind == CompanySpendKind.Project
                ? "company-spend-buy"
                : "company-spend-order"));
            button.Disabled = state.SpendableBalance < entry.Cost;
            var id = entry.Id;
            button.OnPressed += _ => Send(new CompanyManagementUiMessageEvent { Action = action, Text = id });
            root.AddChild(button);
        }

        return _styles.MakeCard(root);
    }

    private Control BuildContractCard(CompanySpendEntry entry, CompanyManagementUiState state)
    {
        var root = new BoxContainer { Orientation = LayoutOrientation.Vertical, SeparationOverride = 3 };
        root.AddChild(_styles.MakeHeading(Display(entry.Title)));
        root.AddChild(_styles.MakeText(Loc.GetString(entry.Purpose), _styles.Theme.SubText));
        root.AddChild(_styles.MakeText(Loc.GetString("company-spend-contract-market",
            ("member", Money(entry.Arg1)),
            ("treasury", Money(entry.Cost - entry.Arg1)))));
        root.AddChild(_styles.MakeText(Loc.GetString("company-spend-contract-funded",
            ("escrow", Money(entry.Cost)),
            ("member", Money(entry.Arg2)),
            ("treasury", Money(entry.Cost - entry.Arg2)))));
        root.AddChild(_styles.MakeText(Loc.GetString("company-spend-balance", ("balance", Money(state.BankBalance)))));
        if (state.AtWar)
            root.AddChild(_styles.MakeText(Loc.GetString("company-war-spendable", ("spendable", Money(state.SpendableBalance)))));

        var busy = !string.IsNullOrEmpty(state.ActiveContractId);
        if (busy)
            root.AddChild(_styles.MakeText(Loc.GetString("company-spend-contract-busy")));

        var market = _styles.MakeButton(Loc.GetString("company-spend-contract-take"));
        market.Disabled = busy;
        var id = entry.Id;
        market.OnPressed += _ => Send(new CompanyManagementUiMessageEvent
        {
            Action = CompanyManagementUiAction.AcceptContract,
            Text = id,
        });
        root.AddChild(market);

        if (entry.CanFund)
        {
            if (state.SpendableBalance < entry.Cost)
                root.AddChild(_styles.MakeText(Loc.GetString("company-spend-short", ("amount", Money(entry.Cost - state.SpendableBalance)))));
            var fund = _styles.MakeButton(Loc.GetString("company-spend-contract-fund"));
            fund.Disabled = busy || state.SpendableBalance < entry.Cost;
            fund.OnPressed += _ => Send(new CompanyManagementUiMessageEvent
            {
                Action = CompanyManagementUiAction.FundContract,
                Text = id,
            });
            root.AddChild(fund);
        }
        else
        {
            root.AddChild(_styles.MakeText(Loc.GetString("company-spend-no-fund-permission")));
        }

        return _styles.MakeCard(root);
    }

