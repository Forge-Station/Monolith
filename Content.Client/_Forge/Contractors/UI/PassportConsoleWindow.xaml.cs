// Forge-Change-full
using System.Numerics;
using Content.Shared._Forge.Contractors;
using Content.Shared.Roles;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Forge.Contractors.UI;

[GenerateTypedNameReferences]
public sealed partial class PassportConsoleWindow : BaseWindow
{
    [Dependency] private IPrototypeManager _prototypes = default!;

    public event Action<Guid>? OnRecordSelected;
    public event Action<Guid>? OnPrintPressed;

    private readonly List<PassportConsoleListEntry> _allEntries = new();
    private Guid? _selectedId;
    private bool _suppressListSelect;

    public PassportConsoleWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        CloseButton.OnPressed += _ => Close();
        RecordList.OnItemSelected += args =>
        {
            if (_suppressListSelect)
                return;

            if (RecordList[args.ItemIndex].Metadata is not Guid id)
                return;

            _selectedId = id;
            OnRecordSelected?.Invoke(id);
        };
        SearchEdit.OnTextChanged += _ => RebuildList();
        PrintButton.OnPressed += _ =>
        {
            if (_selectedId is { } id)
                OnPrintPressed?.Invoke(id);
        };
    }

    public void UpdateState(PassportConsoleBoundUserInterfaceState state)
    {
        _selectedId = state.SelectedId;
        _allEntries.Clear();
        _allEntries.AddRange(state.Entries);

        CoverPanel.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex("#0D1824"),
            BorderColor = Color.FromHex("#51D1C5"),
            BorderThickness = new Thickness(3),
        };
        HeaderLabel.FontColorOverride = Color.FromHex("#51D1C5");

        RebuildList();

        if (state.SelectedProfile != null)
            PdaDocument.UpdateFromProfile(state.SelectedProfile, state.SelectedPid);
        else
            PdaDocument.Clear();

        PrintButton.Disabled = state.SelectedId == null;
    }

    private void RebuildList()
    {
        _suppressListSelect = true;
        RecordList.Clear();
        var filter = SearchEdit.Text.Trim();
        var visible = string.IsNullOrEmpty(filter)
            ? _allEntries
            : _allEntries.FindAll(e =>
                e.Name.Contains(filter, StringComparison.CurrentCultureIgnoreCase) ||
                e.Pid.Contains(filter, StringComparison.CurrentCultureIgnoreCase));

        EmptyLabel.Visible = visible.Count == 0;
        RecordList.Visible = visible.Count > 0;

        var selectedIndex = -1;
        for (var i = 0; i < visible.Count; i++)
        {
            var entry = visible[i];
            var job = GetJobName(entry.JobId);
            var item = RecordList.AddItem($"{entry.Name}  —  {job}");
            item.Metadata = entry.Id;
            if (entry.Id == _selectedId)
                selectedIndex = i;
        }

        if (selectedIndex >= 0)
            RecordList[selectedIndex].Selected = true;

        _suppressListSelect = false;
    }

    private string GetJobName(string jobId)
    {
        if (string.IsNullOrEmpty(jobId))
            return Loc.GetString("passport-console-job-unknown");

        if (_prototypes.TryIndex<JobPrototype>(jobId, out var job))
            return Loc.GetString(job.Name);

        return jobId;
    }

    protected override DragMode GetDragModeFor(Vector2 relativeMousePos)
    {
        return DragMode.Move;
    }
}
