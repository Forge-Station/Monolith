        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("plant-analyzer-field-weed-tol"), $"{msg.WeedTolerance:F1}"));
    }

    private void ShowMutations(PlantAnalyzerScannedSeedPlantInformation msg)
    {
        DetailHeader.Text = Loc.GetString("plant-analyzer-section-mutations");

        var flags = new List<(string Name, bool On)>();
        flags.Add((Loc.GetString("plant-analyzer-mutation-turnintokudzu"), msg.Mutations.HasFlag(MutationFlags.TurnIntoKudzu)));
        flags.Add((Loc.GetString("plant-analyzer-mutation-seedless"), msg.Mutations.HasFlag(MutationFlags.Seedless)));
        flags.Add((Loc.GetString("plant-analyzer-mutation-ligneous"), msg.Mutations.HasFlag(MutationFlags.Ligneous)));
        flags.Add((Loc.GetString("plant-analyzer-mutation-canscream"), msg.Mutations.HasFlag(MutationFlags.CanScream)));
        flags.Add((Loc.GetString("plant-analyzer-mutation-unviable"), msg.Mutations.HasFlag(MutationFlags.Unviable)));
        flags.Add((Loc.GetString("plant-analyzer-mutation-radioactive"), msg.Mutations.HasFlag(MutationFlags.Radioactive)));
        flags.Add((Loc.GetString("plant-analyzer-mutation-grabber"), msg.Mutations.HasFlag(MutationFlags.CarnivorousGrab)));
        flags.Add((Loc.GetString("plant-analyzer-mutation-pest-eater"), msg.Mutations.HasFlag(MutationFlags.CarnivorousPestEater)));
        flags.Add((Loc.GetString("plant-analyzer-mutation-gene-locked"), msg.Mutations.HasFlag(MutationFlags.GeneLocked)));

        var any = false;
        foreach (var (name, on) in flags)
        {
            if (!on)
                continue;
            any = true;
            var color = name == Loc.GetString("plant-analyzer-mutation-radioactive")
                        || name == Loc.GetString("plant-analyzer-mutation-grabber")
                        || name == Loc.GetString("plant-analyzer-mutation-unviable")
                ? BotanyUiTheme.Danger
                : BotanyUiTheme.Ok;
            DetailContainer.AddChild(_styles.Body("·  " + name, 12, color));
        }

        if (msg.MutationNames is { Length: > 0 })
        {
            foreach (var name in msg.MutationNames)
            {
                any = true;
                DetailContainer.AddChild(_styles.Body("·  " + name, 12, BotanyUiTheme.Harvest));
            }
        }

        if (!any)
            DetailContainer.AddChild(_styles.Body("—", 12, BotanyUiTheme.Empty));

        DetailContainer.AddChild(_styles.Section(Loc.GetString("plant-analyzer-section-speciation")));
        if (msg.Speciation is not { Length: > 0 })
        {
            DetailContainer.AddChild(_styles.Body("—", 12, BotanyUiTheme.Empty));
        }
        else
        {
            foreach (var species in msg.Speciation)
                DetailContainer.AddChild(_styles.Body("·  " + Loc.GetString(species), 12));
        }
    }

    private void ShowNoData()
    {
        DetailHeader.Text = Loc.GetString("plant-analyzer-detail-header");
        DetailContainer.DisposeAllChildren();
        DetailContainer.AddChild(_styles.Sub(Loc.GetString("plant-analyzer-window-no-seed-information-text")));
    }

    private string FormatGases(GasFlags flags)
    {
        var output = new StringBuilder();
        AppendGas(output, flags, GasFlags.Nitrogen, "gases-nitrogen");
        AppendGas(output, flags, GasFlags.Oxygen, "gases-oxygen");
        AppendGas(output, flags, GasFlags.CarbonDioxide, "gases-co2");
        AppendGas(output, flags, GasFlags.Plasma, "gases-plasma");
        AppendGas(output, flags, GasFlags.Tritium, "gases-tritium");
        AppendGas(output, flags, GasFlags.WaterVapor, "gases-water-vapor");
        AppendGas(output, flags, GasFlags.Ammonia, "gases-ammonia");
        AppendGas(output, flags, GasFlags.NitrousOxide, "gases-n2o");
        AppendGas(output, flags, GasFlags.Frezon, "gases-frezon");
        AppendGas(output, flags, GasFlags.BZ, "gases-bz");
        AppendGas(output, flags, GasFlags.Healium, "gases-healium");
        AppendGas(output, flags, GasFlags.Nitrium, "gases-nitrium");
        AppendGas(output, flags, GasFlags.Pluoxium, "gases-pluoxium");
        return output.Length == 0 ? Loc.GetString("plant-analyzer-plant-gases-none") : output.ToString();
    }

    private static void AppendGas(StringBuilder output, GasFlags flags, GasFlags flag, string loc)
    {
        if (!flags.HasFlag(flag))
            return;
        if (output.Length > 0)
            output.Append(", ");
        output.Append(Loc.GetString(loc));
    }

    private static Color HealthColor(float health, float endurance)
    {
        if (endurance <= 0)
            return BotanyUiTheme.Danger;
        var ratio = health / endurance;
        if (ratio <= 0.25f)
            return BotanyUiTheme.Danger;
        if (ratio <= 0.5f)
            return BotanyUiTheme.Warning;
        return BotanyUiTheme.Ok;
    }

    private void ApplyChrome()
    {
        Background.ModulateSelfOverride = BotanyUiTheme.WindowBackground;
        Border.ModulateSelfOverride = BotanyUiTheme.WindowBorder;
        CloseButton.ModulateSelfOverride = BotanyUiTheme.CloseButton;
        ContentBorder.ModulateSelfOverride = BotanyUiTheme.ContentBorder;
        ContentBackground.ModulateSelfOverride = BotanyUiTheme.ContentBackground;

        TitleLabel.FontOverride = _styles.GetBoldFont(18);
        TitleLabel.FontColorOverride = BotanyUiTheme.Heading;
        PlantNameLabel.FontOverride = _styles.GetRegularFont(12);
        PlantNameLabel.FontColorOverride = BotanyUiTheme.SubText;
        StatusLabel.FontOverride = _styles.GetBoldFont(12);
        StatusLabel.FontColorOverride = BotanyUiTheme.Text;
        DetailHeader.FontOverride = _styles.GetBoldFont(13);
        DetailHeader.FontColorOverride = BotanyUiTheme.Heading;
        ListHeader.FontOverride = _styles.GetBoldFont(13);
        ListHeader.FontColorOverride = BotanyUiTheme.Heading;
        OsLabel.FontOverride = _styles.GetRegularFont(11);
        OsLabel.FontColorOverride = BotanyUiTheme.SubText;

        BotanyUiStyles.ApplyPanel(MainDivider, BotanyUiTheme.Divider, BotanyUiTheme.Divider, 0);
        BotanyUiStyles.ApplyPanel(DetailPanel, BotanyUiTheme.ListBackground, BotanyUiTheme.ListBorder);
        BotanyUiStyles.ApplyPanel(ListPanel, BotanyUiTheme.ListBackground, BotanyUiTheme.ListBorder);
    }
