    private Control BuildEditRole(CompanyRoleData role, CompanyPermission grantable)
    {
        var body = new BoxContainer { Orientation = LayoutOrientation.Vertical, SeparationOverride = 4, Margin = new Thickness(4) };
        body.AddChild(_styles.MakeHeading(RoleLabel(role.Name)));
        body.AddChild(_styles.MakeText(DescribePermissions(role.Permissions)));
        var editor = BuildRoleEditor(RoleLabel(role.Name), role.AccessTier, role.Permissions, grantable);
        body.AddChild(editor.Root);

        var actions = new BoxContainer { Orientation = LayoutOrientation.Horizontal, SeparationOverride = 4 };
        var save = _styles.MakeButton(Loc.GetString("company-pda-save-role"));
        var roleId = role.RoleId;
        save.OnPressed += _ =>
        {
            Send(new CompanyManagementUiMessageEvent
            {
                Action = CompanyManagementUiAction.UpdateRole,
                GuidValue = roleId,
                Text = RoleNameToSave(role.Name, editor.NameEdit.Text),
                AccessTier = editor.GetTier(),
                Permissions = editor.GetPermissions(),
            });
        };
        actions.AddChild(save);

        if (!role.IsDefault && !CompanyRolePresets.IsPreset(role.Name))
        {
            var del = _styles.MakeButton(Loc.GetString("company-pda-delete-role"));
            del.OnPressed += _ => Send(new CompanyManagementUiMessageEvent
            {
                Action = CompanyManagementUiAction.DeleteRole,
                GuidValue = roleId,
            });
            actions.AddChild(del);
        }

        body.AddChild(actions);
        return _styles.MakeCard(body);
    }

    private static string DescribePermissions(CompanyPermission permissions)
    {
        var flags = string.Join(", ",
            EditablePermissions
                .Where(perm => (permissions & perm) != 0)
                .Select(perm => Loc.GetString($"company-pda-perm-{perm.ToString().ToLowerInvariant()}")));
        return string.IsNullOrEmpty(flags)
            ? Loc.GetString("company-pda-perm-none")
            : flags;
    }

    private RoleEditor BuildRoleEditor(
        string name,
        CompanyAccessTier tier,
        CompanyPermission permissions,
        CompanyPermission grantable)
    {
        var root = new BoxContainer { Orientation = LayoutOrientation.Vertical, Margin = new Thickness(0, 0, 0, 2), SeparationOverride = 3 };
        var nameEdit = _styles.MakeLineEdit(text: name);
        root.AddChild(nameEdit);

        root.AddChild(_styles.MakeText(Loc.GetString("company-pda-role-tier")));
        var selectedTier = tier < CompanyAccessTier.Low ? CompanyAccessTier.Low : tier;
        var tierButtons = new Dictionary<CompanyAccessTier, Button>();
        var tierRow = new BoxContainer { Orientation = LayoutOrientation.Horizontal, SeparationOverride = 4 };
        foreach (var choice in new[] { CompanyAccessTier.Low, CompanyAccessTier.Medium, CompanyAccessTier.High })
        {
            var choiceTier = choice;
            var button = _styles.MakeButton(Loc.GetString($"company-pda-access-{choice.ToString().ToLowerInvariant()}"));
            button.HorizontalExpand = true;
            tierButtons[choice] = button;
            button.OnPressed += _ =>
            {
                selectedTier = choiceTier;
                foreach (var (value, tierButton) in tierButtons)
                    tierButton.Disabled = value == selectedTier;
            };
            tierRow.AddChild(button);
        }

        foreach (var (value, tierButton) in tierButtons)
            tierButton.Disabled = value == selectedTier;
        root.AddChild(tierRow);

        var checks = new Dictionary<CompanyPermission, CheckBox>();
        var grid = new GridContainer { Columns = 2, HorizontalExpand = true };
        foreach (var perm in EditablePermissions)
        {
            if ((grantable & perm) == 0)
                continue;

            var box = new CheckBox
            {
                Text = Loc.GetString($"company-pda-perm-{perm.ToString().ToLowerInvariant()}"),
                Pressed = (permissions & perm) != 0,
            };
            _styles.StyleCheckBox(box);
            checks[perm] = box;
            grid.AddChild(box);
        }

        if (grid.ChildCount > 0)
            root.AddChild(grid);

        return new RoleEditor(root, nameEdit, () => selectedTier, checks);
    }

    private sealed class RoleEditor
    {
        public BoxContainer Root { get; }
        public LineEdit NameEdit { get; }
        private readonly Func<CompanyAccessTier> _tier;
        private readonly Dictionary<CompanyPermission, CheckBox> _checks;

        public RoleEditor(
            BoxContainer root,
            LineEdit nameEdit,
            Func<CompanyAccessTier> tier,
            Dictionary<CompanyPermission, CheckBox> checks)
        {
            Root = root;
            NameEdit = nameEdit;
            _tier = tier;
            _checks = checks;
        }

        public CompanyAccessTier GetTier() => _tier();

        public CompanyPermission GetPermissions()
        {
            var result = CompanyPermission.None;
            foreach (var (perm, box) in _checks)
            {
                if (box.Pressed)
                    result |= perm;
            }

            return result;
        }
    }

    private static string RoleLabel(string? name)
    {
        if (string.IsNullOrWhiteSpace(name))
            return string.Empty;

        return Loc.TryGetString(name, out var localized) && !string.IsNullOrWhiteSpace(localized)
            ? localized
            : name;
    }

    private static string RoleNameToSave(string stored, string? edited)
    {
        var text = edited?.Trim() ?? string.Empty;
        if (CompanyRolePresets.IsPreset(stored) && text == RoleLabel(stored))
            return stored;

        return text;
    }

