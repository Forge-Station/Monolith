    public void UpdatePanels(Dictionary<string, ResearchAvailability> dict, Dictionary<string, byte> progress)
    {
        var sameTechnologies = List.Count == dict.Count && List.Keys.All(dict.ContainsKey);
        var firstLayout = _visibleTechnologyItems.Count == 0 && dict.Count > 0;

        List = dict;
        Progress = progress;
        var supportedDisciplines = GetSupportedDisciplineIds();

        // Point ticks update progress every second. Recentering on those updates
        // snaps the tree back to the middle while the console is open.
        if (firstLayout)
            _pendingRecenter = true;

        EnsureSelectedDiscipline(supportedDisciplines);
        BuildDisciplineTabs(supportedDisciplines);

        if (!sameTechnologies || !TryRefreshTechnologyItemsInPlace())
            RefreshTechnologyGrid();

        RefreshCurrentInfoPanel();

        if (!sameTechnologies)
            RebuildSearchResults();
    }

    /// <summary>
    /// Keeps the current pan when only research points or availability changed.
    /// </summary>
    private bool TryRefreshTechnologyItemsInPlace()
    {
        if (_selectedDiscipline == null || _visibleTechnologyItems.Count == 0)
            return false;

        foreach (var (id, availability) in List)
        {
            if (!_prototype.TryIndex(id, out TechnologyPrototype? proto) || proto.Hidden)
                continue;

            if (proto.Discipline != _selectedDiscipline)
                continue;

            if (!_visibleTechnologyItems.ContainsKey(id))
                return false;

            _visibleTechnologyItems[id].RefreshState(availability, Progress.GetValueOrDefault(id, (byte) 0));
        }

        UpdateSelectedTechVisuals();
        return true;
    }

    private void RefreshTechnologyGrid()
    {
        DragContainer.RemoveAllChildren();
        _visibleTechnologyItems.Clear();
        _crossDisciplinePreviewItem = null;

        var supportedDisciplines = GetSupportedDisciplineIds();
        RebuildCompactLayouts(supportedDisciplines);

        foreach (var tech in List)
        {
            var proto = _prototype.Index<TechnologyPrototype>(tech.Key);

            if (!IsTechnologyVisibleInCurrentTab(proto))
                continue;

            var unlockProgress = Progress.GetValueOrDefault(tech.Key, (byte) 0);
            var control = new FancyResearchConsoleItem(proto, _sprite, tech.Value, unlockProgress);
            DragContainer.AddChild(control);
            _visibleTechnologyItems[proto.ID] = control;

            // Set position for all tech, relating to _position
            var uiPosition = _position + GetTechnologyGridPosition(proto) * GridSize;
            LayoutContainer.SetPosition(control, uiPosition);
            control.SelectAction += SelectTech;
        }

        AddCrossDisciplinePreviewGhost();
        UpdateSelectedTechVisuals();

        if (_pendingRecenter
            && _visibleTechnologyItems.Count > 0
            && ResearchesContainer.Size.X > 1
            && ResearchesContainer.Size.Y > 1)
        {
            Recenter();
        }
    }

    public void UpdateInformationPanel(int points)
    {
        Points = points;

        var amountMsg = new FormattedMessage();
        amountMsg.AddMarkupOrThrow(Loc.GetString("research-console-menu-research-points-text",
            ("points", points)));
        ResearchAmountLabel.SetMessage(amountMsg);

        if (!_entity.TryGetComponent(Entity, out TechnologyDatabaseComponent? database))
            return;

        var previousDiscipline = _selectedDiscipline;
        var supportedDisciplines = GetSupportedDisciplineIds();
        EnsureSelectedDiscipline(supportedDisciplines);
        BuildDisciplineTabs(supportedDisciplines);

        if (previousDiscipline != _selectedDiscipline)
            RefreshTechnologyGrid();

        TierDisplayContainer.RemoveAllChildren();
        foreach (var disciplineId in database.SupportedDisciplines)
        {
            var discipline = _prototype.Index<TechDisciplinePrototype>(disciplineId);
            var tier = _research.GetTierCompletionPercentage(database, discipline, _prototype);

            // i'm building the small-ass control here to spare me some mild annoyance in making a new file
            var texture = new TextureRect
            {
                TextureScale = new Vector2(2, 2),
                VerticalAlignment = VAlignment.Center
            };
            var label = new RichTextLabel();
            texture.Texture = _sprite.Frame0(discipline.Icon);
            label.SetMessage(Loc.GetString("research-console-tier-percentage", ("perc", tier)));

            var control = new BoxContainer
            {
                Children =
                {
                    texture,
                    label,
                    new Control
                    {
                        MinWidth = 10
                    }
                }
            };
            TierDisplayContainer.AddChild(control);
        }
    }

    #region Drag handle
    protected override void MouseMove(GUIMouseMoveEventArgs args)
    {
        base.MouseMove(args);

        if (!_draggin)
            return;

        // Frontier: bound motion to a box
        var originalPosition = _position;
        _position += args.Relative;
        CacheCurrentDisciplinePosition();

        var diff = _position - originalPosition;
        // End Frontier: bound motion to a box

        // Move all tech
        foreach (var child in DragContainer.Children)
        {
            LayoutContainer.SetPosition(child, child.Position + diff); // Frontier: args.Relative<diff
        }
    }

