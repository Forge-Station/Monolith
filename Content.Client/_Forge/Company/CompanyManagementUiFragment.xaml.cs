            return;

        var createBody = new BoxContainer { Orientation = LayoutOrientation.Vertical, SeparationOverride = 4, Margin = new Thickness(4) };
        createBody.AddChild(_styles.MakeHeading(Loc.GetString("company-pda-create-role")));
