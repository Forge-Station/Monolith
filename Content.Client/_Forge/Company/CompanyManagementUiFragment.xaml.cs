    private void AddPeacePanel(BoxContainer actions, CompanyPickerEntry company, CompanyRelationData? terms, CompanyManagementUiState state, Func<string?> words)
    {
        var other = Display(company.Name);
        var max = CompanyOrgLimits.MaxPeaceRansomPercent;
        actions.AddChild(_styles.MakeText(Loc.GetString("company-peace-intro", ("max", max))));

        var weOffer = terms?.WeOfferFreePeace ?? false;
        var theyOffer = terms?.TheyOfferFreePeace ?? false;
        var ourPercent = terms?.OurRansomPercent ?? 0;
        var theirPercent = terms?.TheirRansomPercent ?? 0;
        var theirAmount = terms?.TheirRansomAmount ?? 0;

        if (theyOffer)
            actions.AddChild(_styles.MakeText(Loc.GetString("company-peace-they-offer", ("other", other))));
        if (weOffer && !theyOffer)
            actions.AddChild(_styles.MakeText(Loc.GetString("company-peace-waiting")));
        if (ourPercent > 0)
            actions.AddChild(_styles.MakeText(Loc.GetString("company-peace-our-ransom", ("percent", ourPercent), ("other", other))));
        if (theirPercent > 0)
            actions.AddChild(_styles.MakeText(Loc.GetString("company-peace-their-ransom", ("other", other), ("percent", theirPercent), ("amount", Money(theirAmount)))));

        var canWar = state.IsOwner || (state.Permissions & CompanyPermission.DeclareWar) != 0;
        if (!canWar)
            return;

        actions.AddChild(RelationButton(
            Loc.GetString(theyOffer ? "company-peace-agree" : "company-peace-offer"),
            weOffer && !theyOffer,
            () => Send(new CompanyManagementUiMessageEvent
            {
                Action = CompanyManagementUiAction.OfferFreePeace,
                CompanyId = company.Id,
                Text = words(),
            })));

        if (theirPercent > 0)
        {
            actions.AddChild(RelationButton(
                Loc.GetString("company-peace-accept-defeat", ("amount", Money(theirAmount))),
                false,
                () => Send(new CompanyManagementUiMessageEvent
                {
                    Action = CompanyManagementUiAction.AcceptPeaceRansom,
                    CompanyId = company.Id,
                    Text = words(),
                })));
        }

        var percent = _styles.MakeLineEdit(Loc.GetString("company-peace-ransom-field", ("max", max)));
        actions.AddChild(percent);
        actions.AddChild(_styles.MakeText(Loc.GetString("company-peace-ransom-purpose", ("max", max))));
        actions.AddChild(RelationButton(
            Loc.GetString("company-peace-set-ransom"),
            false,
            () =>
            {
                if (!int.TryParse(percent.Text, out var value))
                    return;
                Send(new CompanyManagementUiMessageEvent
                {
                    Action = CompanyManagementUiAction.SetPeaceRansom,
                    CompanyId = company.Id,
                    Amount = value,
                });
            }));
    }

