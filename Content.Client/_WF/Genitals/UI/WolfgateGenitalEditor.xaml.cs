    /// <summary>Segmented choice: a row of CreatorToggle buttons with one lit, like WolfgateSexSelector.</summary>
    private sealed class Segmented<T> : BoxContainer where T : struct, Enum
    {
        private readonly ButtonGroup _group = new();
        private readonly Dictionary<T, Button> _buttons = new();
        private readonly Dictionary<T, string?> _tooltips = new();

        /// <summary>Raised when the player picks an option; not raised by Select.</summary>
        public event Action<T>? OnSelected;

        public Segmented()
        {
            Orientation = LayoutOrientation.Horizontal;
            SeparationOverride = 4;
        }

        public void Add(T value, string text, string? tooltip = null)
        {
            var button = new Button
            {
                Text = text,
                ToolTip = tooltip,
                Group = _group,
                StyleClasses = { StyleWolfgate.StyleClassCreatorToggle },
            };
            button.OnPressed += _ => OnSelected?.Invoke(value);
            _buttons[value] = button;
            _tooltips[value] = tooltip;
            AddChild(button);
        }

        /// <summary>Lights an option without raising OnSelected.</summary>
        public void Select(T value)
        {
            if (_buttons.TryGetValue(value, out var button))
                button.Pressed = true;
        }

        /// <summary>Enables or disables an option; a disabled option explains itself in its tooltip.</summary>
        public void SetEnabled(T value, bool enabled, string disabledTooltip)
        {
            if (!_buttons.TryGetValue(value, out var button))
                return;

            button.Disabled = !enabled;
            button.ToolTip = enabled ? _tooltips[value] : disabledTooltip;
        }
    }

    /// <summary>Colour of one organ part: a match-skin check box, and a colour picker while the colour is custom.</summary>
    private sealed class ColourRow : BoxContainer
    {
        private readonly CheckBox _match;
        private readonly WolfgateColorPicker _picker;

        public event Action<bool>? OnMatchChanged;
        public event Action<Color>? OnColorPicked;

        public ColourRow(string caption)
        {
            Orientation = LayoutOrientation.Vertical;
            SeparationOverride = 4;

            _match = new CheckBox
            {
                Text = Loc.GetString("wf-genitals-match-skin"),
                VerticalAlignment = VAlignment.Center,
            };
            _match.OnToggled += args => OnMatchChanged?.Invoke(args.Pressed);

            _picker = new WolfgateColorPicker { HorizontalExpand = true };
            _picker.OnColorChanged += color => OnColorPicked?.Invoke(color);

            AddChild(new BoxContainer
            {
                Orientation = LayoutOrientation.Horizontal,
                SeparationOverride = 8,
                Children =
                {
                    new Label
                    {
                        Text = caption,
                        MinWidth = LabelWidth,
                        VerticalAlignment = VAlignment.Center,
                        StyleClasses = { StyleWolfgate.StyleClassCreatorFieldLabel },
                    },
                    _match,
                },
            });
            AddChild(_picker);
        }

        /// <summary>Shows the setting without raising events.</summary>
        public void Set(bool matchSkin, Color color)
        {
            _match.Pressed = matchSkin;
            _picker.Color = color;
            _picker.Visible = !matchSkin;
        }
    }
