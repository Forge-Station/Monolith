def main():
    ids = {line_id for line_id, _, _, _ in LINES}
    for _, variants in EVENTS:
        for variant in variants:
            if variant not in ids:
                raise SystemExit("event names a line with no file: " + variant)

    os.makedirs(os.path.dirname(PROTO), exist_ok=True)
    out = ["# Generated by Tools/_WF/Wolfmed/gen_autodoc_voice_protos.py. Edit the script, not this file.",
           "- type: autodocVoice",
           "  id: WFWolfmedAutodocVoiceSam",
           "  lines:"]
    for line_id, _, _, priority in LINES:
        out.append("    " + line_id + ":")
        out.append("      sound:")
        out.append("        path: " + AUDIO + "/" + line_id + ".ogg")
        out.append("      message: " + PREFIX + line_id)
        out.append("      priority: " + priority)
    out.append("  events:")
    for event, variants in EVENTS:
        out.append("    " + event + ": [" + ", ".join(variants) + "]")

    with open(PROTO, "w", newline="\n") as handle:
        handle.write("\n".join(out) + "\n")

    print("wrote", len(LINES), "lines and", len(EVENTS), "events")


if __name__ == "__main__":
    main()
