    private GridContainer[] ShapeGrids()
    {
        return new[] { PenisShapes, VaginaShapes, BreastShapes };
    }

    /// <summary>Builds the shape tiles once the gates pass.</summary>
    private void EnsureTiles()
    {
        if (_tilesBuilt)
            return;

        _tilesBuilt = true;
        BuildTiles(PenisShapes, _penisTiles, GenitalSlot.Penis, OnPenisShapePicked);
        BuildTiles(VaginaShapes, _vaginaTiles, GenitalSlot.Vagina, shape => EditVagina(v => v.With(shape: shape)));
        BuildTiles(BreastShapes, _breastTiles, GenitalSlot.Breasts, shape => EditBreasts(b => b.With(shape: shape)));
        UpdateColumns();
    }

    private void BuildTiles(GridContainer grid, ButtonGroup group, GenitalSlot slot, Action<ProtoId<GenitalShapePrototype>> picked)
    {
        foreach (var shape in SortedShapes(slot))
        {
            var art = shape.Preview is { } previewId && _proto.TryIndex(previewId, out var previewShape) ? previewShape : shape;
            var tile = new WolfgateGenitalShapeTile(shape, art, _direction) { Group = group };
            if (shape.ID == UddersShape.Id)
                tile.ToolTip = Loc.GetString(shape.Name) + "\n" + Loc.GetString("wf-genitals-udders-note");

            ProtoId<GenitalShapePrototype> id = shape.ID;
            tile.OnPressed += _ =>
            {
                if (!_syncing)
                    picked(id);
            };
            grid.AddChild(tile);
        }
    }

    private void DisposeTiles()
    {
        // Disposed rather than removed: a ButtonGroup only lets go of disposed buttons.
        foreach (var grid in ShapeGrids())
        {
            grid.DisposeAllChildren();
        }

        _tilesBuilt = false;
    }

    /// <summary>Lights the selected shape and tints every tile with the colour the organ would be drawn in.</summary>
    private static void SyncTiles(GridContainer grid, ProtoId<GenitalShapePrototype>? selected, Color tint)
    {
        foreach (var child in grid.Children)
        {
            if (child is not WolfgateGenitalShapeTile tile)
                continue;

            tile.Pressed = selected == tile.Shape;
            tile.Tint = tint;
        }
    }

    private void UpdateColumns()
    {
        // The cards and the tab add about 48 px of margin around the grids.
        var columns = Math.Max(1, (int) ((Width - 48) / WolfgateGenitalShapeTile.TileWidth));
        foreach (var grid in ShapeGrids())
        {
            if (grid.Columns != columns)
                grid.Columns = columns;
        }
    }

    private IEnumerable<GenitalShapePrototype> SortedShapes(GenitalSlot slot)
    {
        return _proto.EnumeratePrototypes<GenitalShapePrototype>()
            .Where(s => s.Slot == slot)
            .OrderBy(s => s.SortOrder)
            .ThenBy(s => s.ID, StringComparer.Ordinal);
    }

    /// <summary>The first shape in tile order; empty when the slot has none, which the validator then drops.</summary>
    private ProtoId<GenitalShapePrototype> FirstShape(GenitalSlot slot)
    {
        return SortedShapes(slot).FirstOrDefault()?.ID ?? string.Empty;
    }

