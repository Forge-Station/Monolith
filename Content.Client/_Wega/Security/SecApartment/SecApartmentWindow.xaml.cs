        {
            "TSF" => "TSF",
            "NanoTrasen" => "NanoTrasen",
            "Empire" => "Empire",
            "UnionOfSovietSocialistPlanets" => "USSP",
            "Renegates" => "Renegates",
            _ => "Security"
        };
        var isFactionTablet = department != "Security";

        Logo.Visible = !isFactionTablet;
        Footer.Visible = !isFactionTablet;

        if (_activeTheme == theme)
            return;

        _activeTheme = theme;

        switch (theme)
        {
            case "TSF":
                ApplyBlueStylesheet();
                RecolorControl(this);
                Tabs.TabFontColorOverride = Color.FromHex("#44aaff");
                Tabs.TabFontColorInactiveOverride = Color.FromHex("#88ccff");
                break;
            case "Renegates":
                ApplyOrangeStylesheet();
                RecolorControl(this);
                Tabs.TabFontColorOverride = Color.FromHex("#ff9a3c");
                Tabs.TabFontColorInactiveOverride = Color.FromHex("#d8955d");
                break;
            case "NanoTrasen":
                ApplyNanoTrasenStylesheet();
                RecolorControl(this);
                Tabs.TabFontColorOverride = Color.FromHex("#00b7ff");
                Tabs.TabFontColorInactiveOverride = Color.FromHex("#6bdcff");
                break;
            case "Empire":
                ApplyEmpireStylesheet();
                RecolorControl(this);
                Tabs.TabFontColorOverride = Color.FromHex("#c89a5a");
                Tabs.TabFontColorInactiveOverride = Color.FromHex("#d8b98a");
                break;
            case "USSP":
                ApplyUsspStylesheet();
                RecolorControl(this);
                Tabs.TabFontColorOverride = Color.FromHex("#d2b48c");
                Tabs.TabFontColorInactiveOverride = Color.FromHex("#e0c7a1");
                break;
        }
    }

