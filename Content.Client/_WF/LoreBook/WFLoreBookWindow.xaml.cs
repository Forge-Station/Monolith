/// <summary>
/// The lore book: a leather-bound two-page spread with the contents on the left and the open page on the right.
/// Pages are guide entries marked as lore, numbered in reading order.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class WFLoreBookWindow : BaseWindow, ILinkClickHandler
{
    [Dependency] private DocumentParsingManager _parsing = default!;
    [Dependency] private IPrototypeManager _proto = default!;
    [Dependency] private IResourceCache _cache = default!;
    [Dependency] private IResourceManager _res = default!;
    [Dependency] private IEntityManager _entMan = default!;

    public static readonly Color Gold = Color.FromHex("#c9a45c");
    public static readonly Color GoldBright = Color.FromHex("#f0d48a");
    public static readonly Color Cream = Color.FromHex("#e3d3b0");
    public static readonly Color Faded = Color.FromHex("#9c8a6a");

    private const int DragMargin = 7;
    private const string FontPath = "/Fonts/Fondamento-Regular.ttf";

    private readonly List<Page> _pages = new();
    private readonly Dictionary<string, int> _index = new();
    private readonly Dictionary<string, string> _searchText = new();
    private int _current = -1;

    /// <summary>The page open now, if any.</summary>
    public ProtoId<GuideEntryPrototype>? Current => _current >= 0 ? _pages[_current].Entry.ID : null;

    public WFLoreBookWindow()
    {
        RobustXamlLoader.Load(this);
        WFWindowBranding.Apply(this);
        IoCManager.InjectDependencies(this);

        Cover.PanelOverride = Tiled("/Textures/_WF/LoreBook/leather.png", Color.White);
        var trim = new PanelContainer
        {
            Margin = new Thickness(5),
            MouseFilter = MouseFilterMode.Ignore,
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = Color.Transparent,
                BorderColor = Gold.WithAlpha(0.55f),
                BorderThickness = new Thickness(2),
            },
        };
        AddChild(trim);
        trim.SetPositionInParent(1);

        LeftPage.PanelOverride = Tiled("/Textures/_WF/LoreBook/page.png", Color.White);
        RightPage.PanelOverride = Tiled("/Textures/_WF/LoreBook/page.png", Color.White);
        Spine.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex("#160e08"),
            BorderColor = Color.FromHex("#3a2615"),
            BorderThickness = new Thickness(3, 0),
        };
        ContentsRule.PanelOverride = new StyleBoxFlat { BackgroundColor = Gold.WithAlpha(0.6f) };
        PageRule.PanelOverride = new StyleBoxFlat { BackgroundColor = Gold.WithAlpha(0.6f) };

        TitleIcon.Texture = _cache.GetTexture(WFLoreBookSystem.IconPath);
        TitleIcon.ModulateSelfOverride = Gold;
        BookTitle.FontOverride = _cache.GetFont(FontPath, 24);
        BookTitle.FontColorOverride = GoldBright;
        BookSubtitle.FontOverride = _cache.GetFont(FontPath, 14);
        BookSubtitle.FontColorOverride = Faded;
        ContentsHeading.FontOverride = _cache.GetFont(FontPath, 20);
        ContentsHeading.FontColorOverride = Gold;
        ChapterTrail.FontOverride = _cache.GetFont(FontPath, 14);
        ChapterTrail.FontColorOverride = Faded;
        Folio.FontOverride = _cache.GetFont(FontPath, 14);
        Folio.FontColorOverride = Faded;
        LeftFolio.FontOverride = _cache.GetFont(FontPath, 13);
        LeftFolio.FontColorOverride = Faded;

        CloseBookButton.OnPressed += _ => Close();
        SearchBar.OnTextChanged += _ => ApplySearch();

        BuildPages();
        LeftFolio.Text = Loc.GetString("wf-lore-book-page-count", ("count", _pages.Count));
    }

    /// <summary>Turns to a page, or to the first page if it isn't in the book.</summary>
    public void Show(ProtoId<GuideEntryPrototype>? entry)
    {
        if (_pages.Count == 0)
        {
            ChapterTrail.Text = string.Empty;
            Folio.Text = string.Empty;
            PageBody.RemoveAllChildren();
            PageBody.AddChild(new Label { Text = Loc.GetString("wf-lore-book-empty"), FontColorOverride = Faded });
            return;
        }

        var index = entry is { } id && _index.TryGetValue(id, out var found) ? found : 0;
        TurnTo(index);
    }

    public void HandleClick(string link)
    {
        if (_index.TryGetValue(link, out var index))
        {
            TurnTo(index);
            return;
        }

        if (_proto.HasIndex<GuideEntryPrototype>(link))
            UserInterfaceManager.GetUIController<GuidebookUIController>().OpenGuidebook(selected: link);
    }

    private void TurnTo(int index)
    {
        if (index < 0 || index >= _pages.Count)
            return;

        if (_current >= 0)
        {
            StyleRow(_pages[_current], false);
            if (_current != index)
                PlayPageTurn();
        }

        _current = index;
        var page = _pages[index];
        StyleRow(page, true);

        ChapterTrail.Text = string.Join("  ·  ", Trail(index).Select(i => Loc.GetString(_pages[i].Entry.Name)));
        Folio.Text = Loc.GetString("wf-lore-book-folio", ("page", index + 1));

        PageScroll.SetScrollValue(default);
        PageBody.RemoveAllChildren();
        using (var file = _res.ContentFileReadText(page.Entry.Text))
        {
            if (!_parsing.TryAddMarkup(PageBody, Unsettle(file.ReadToEnd(), page.Entry)))
                Logger.GetSawmill("lorebook").Error($"Failed to parse lore page {page.Entry.ID}.");
        }

        GatherGlyphs();

        PrevSlot.RemoveAllChildren();
        NextSlot.RemoveAllChildren();
        if (index > 0)
            PrevSlot.AddChild(TurnLink(Loc.GetString("wf-lore-book-previous", ("name", Loc.GetString(_pages[index - 1].Entry.Name))), index - 1, HAlignment.Left));
        if (index < _pages.Count - 1)
            NextSlot.AddChild(TurnLink(Loc.GetString("wf-lore-book-next", ("name", Loc.GetString(_pages[index + 1].Entry.Name))), index + 1, HAlignment.Right));
    }

    /// <summary>The page's chapter path, root first.</summary>
    private List<int> Trail(int index)
    {
        var trail = new List<int>();
        for (var i = index; i >= 0; i = _pages[i].Parent)
            trail.Insert(0, i);
        return trail;
    }

    private void BuildPages()
    {
        var lore = _entMan.System<WFLoreBookSystem>();
        var entries = _proto.EnumeratePrototypes<GuideEntryPrototype>().Where(e => lore.IsLore(e.ID)).ToList();
        var children = entries.SelectMany(e => e.Children).Select(c => c.Id).ToHashSet();
        var roots = entries
            .Where(e => !children.Contains(e.ID))
            .OrderBy(e => e.Priority)
            .ThenBy(e => Loc.GetString(e.Name));

        foreach (var root in roots)
            AddPage(root, 0, -1);

        foreach (var page in _pages)
            Contents.AddChild(page.Row);
    }

    private void AddPage(GuideEntryPrototype entry, int depth, int parent)
    {
        if (_index.ContainsKey(entry.ID))
            return;

        var index = _pages.Count;
        _index[entry.ID] = index;
        var page = new Page(entry, depth, parent);
        BuildRow(page, index);
        _pages.Add(page);

        foreach (var child in entry.Children)
        {
            if (_proto.TryIndex(child, out var childEntry))
                AddPage(childEntry, depth + 1, index);
        }
    }

    private void BuildRow(Page page, int index)
    {
        page.Name.Text = Loc.GetString(page.Entry.Name);
        page.Name.HorizontalExpand = true;
        page.Name.ClipText = true;
        page.Number.Text = (index + 1).ToString();
        page.Number.FontColorOverride = Faded;
        page.Number.Margin = new Thickness(8, 0, 0, 0);

        if (page.Depth == 0)
        {
            page.Name.FontOverride = _cache.GetFont(FontPath, 16);
            page.Row.Margin = new Thickness(0, 8, 0, 1);
        }
        else
        {
            page.Row.Margin = new Thickness(16 * page.Depth, 1, 0, 1);
        }

        page.Row.AddChild(page.Name);
        page.Row.AddChild(page.Number);
        page.Row.MouseFilter = MouseFilterMode.Stop;
        page.Row.DefaultCursorShape = CursorShape.Hand;
        page.Row.OnMouseEntered += _ => page.Name.FontColorOverride = GoldBright;
        page.Row.OnMouseExited += _ => StyleRow(page, _current >= 0 && _pages[_current] == page);
        page.Row.OnKeyBindDown += args =>
        {
            if (args.Function != EngineKeyFunctions.UIClick)
                return;

            TurnTo(index);
            args.Handle();
        };
        StyleRow(page, false);
    }

    private static void StyleRow(Page page, bool selected)
    {
        var name = Loc.GetString(page.Entry.Name);
        page.Name.Text = selected ? $"» {name}" : name;
        page.Name.FontColorOverride = selected ? GoldBright : page.Depth == 0 ? Gold : Cream;
    }

    private Control TurnLink(string text, int index, HAlignment align)
    {
        var label = new Label
        {
            Text = text,
            Align = align == HAlignment.Left ? Label.AlignMode.Left : Label.AlignMode.Right,
            HorizontalExpand = true,
            ClipText = true,
            MouseFilter = MouseFilterMode.Stop,
            DefaultCursorShape = CursorShape.Hand,
            FontOverride = _cache.GetFont(FontPath, 14),
            FontColorOverride = Gold,
        };
        label.OnMouseEntered += _ => label.FontColorOverride = GoldBright;
        label.OnMouseExited += _ => label.FontColorOverride = Gold;
        label.OnKeyBindDown += args =>
        {
            if (args.Function != EngineKeyFunctions.UIClick)
                return;

            TurnTo(index);
            args.Handle();
        };
        return label;
    }

    /// <summary>Hides contents rows whose name and text don't hold the search words.</summary>
    private void ApplySearch()
    {
        var query = SearchBar.Text.Trim();
        foreach (var page in _pages)
        {
            page.Row.Visible = query.Length == 0
                || Loc.GetString(page.Entry.Name).Contains(query, StringComparison.OrdinalIgnoreCase)
                || SearchText(page.Entry).Contains(query, StringComparison.OrdinalIgnoreCase);
        }
    }

    private string SearchText(GuideEntryPrototype entry)
    {
        if (_searchText.TryGetValue(entry.ID, out var text))
            return text;

        using var file = _res.ContentFileReadText(entry.Text);
        text = file.ReadToEnd();
        _searchText[entry.ID] = text;
        return text;
    }

    private StyleBoxTexture Tiled(string path, Color modulate)
    {
        return new StyleBoxTexture
        {
            Texture = _cache.GetTexture(path),
            Mode = StyleBoxTexture.StretchMode.Tile,
            Modulate = modulate,
        };
    }

    protected override DragMode GetDragModeFor(Vector2 relativeMousePos)
    {
        var mode = DragMode.Move;
        if (relativeMousePos.Y < DragMargin)
            mode = DragMode.Top;
        else if (relativeMousePos.Y > Size.Y - DragMargin)
            mode = DragMode.Bottom;

        if (relativeMousePos.X < DragMargin)
            mode |= DragMode.Left;
        else if (relativeMousePos.X > Size.X - DragMargin)
            mode |= DragMode.Right;

        return mode;
    }

    private enum HAlignment : byte
    {
        Left,
        Right,
    }

    /// <summary>One page of the book and its contents row.</summary>
    private sealed class Page(GuideEntryPrototype entry, int depth, int parent)
    {
        public readonly GuideEntryPrototype Entry = entry;
        public readonly int Depth = depth;
        public readonly int Parent = parent;
        public readonly BoxContainer Row = new() { Orientation = BoxContainer.LayoutOrientation.Horizontal };
        public readonly Label Name = new();
        public readonly Label Number = new();
    }
}
