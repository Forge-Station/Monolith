        var anyOrgan = !_profile.IsEmpty;
        RevealRow.Visible = anyOrgan;
        _reveal.Select(_profile.RevealMode);

        // Species without undergarment art get a note instead of the button, since there is nothing to choose.
        SpeciesUndergarmentNote.Visible = anyOrgan && !_speciesHasUndergarments;
        UndergarmentNotice.Visible = anyOrgan
                                     && _speciesHasUndergarments
                                     && !_wearsUndergarment
                                     && _profile.RevealMode == GenitalRevealMode.UndergarmentRemoval;
        PregnancyNote.Visible = _pregnancyMarking && !_profile.Womb;
        LoadFailedWarning.Visible = _profile.LoadFailed;
        SetWarnings(GeneralWarning, GeneralIssues);
    }

    private void RefreshPenis(GenitalSettingsPrototype settings, Color? tissue)
    {
        var penis = _profile.Penis;
        PenisInclude.Pressed = penis != null;
        PenisBody.Visible = penis != null;
        SetWarnings(PenisWarning, GenitalIssue.TesticlesWithoutPenis);
        SyncTiles(PenisShapes, penis?.Shape, penis == null ? tissue ?? _skin : Shown(penis.MatchSkin, penis.Color));

        if (penis == null)
            return;

        _proto.TryIndex(penis.Shape, out var shape);

        var minLength = settings.MinLengthCm;
        LengthSlider.MinValue = minLength;
        LengthSlider.MaxValue = Math.Max(minLength, settings.MaxLengthCm);
        LengthSlider.SetValueWithoutEvent(penis.LengthCm);
        LengthValue.Text = Loc.GetString("wf-genitals-length-value",
            ("cm", penis.LengthCm),
            ("step", GenitalStateBuilder.LengthToStep(penis.LengthCm, settings)));
        SetWarnings(LengthWarning, GenitalIssue.LengthClamped);

        _sheath.Select(penis.Sheath);
        var unavailable = Loc.GetString("wf-genitals-sheath-unavailable");
        foreach (var type in SheathTypes)
        {
            var allowed = type == SheathType.None || shape != null && shape.AllowedSheaths.Contains(type);
            _sheath.SetEnabled(type, allowed, unavailable);
        }

        // The remembered choice stays suppressed until a shape that allows it is picked.
        var suppressed = _sheathChoice != SheathType.None
                         && penis.Sheath == SheathType.None
                         && shape != null
                         && !shape.AllowedSheaths.Contains(_sheathChoice);
        SheathWarning.Visible = suppressed || _issues.Contains(GenitalIssue.SheathNotAllowed);
        if (SheathWarning.Visible)
            SheathWarning.SetMessage(Loc.GetString("wf-genitals-warning-SheathNotAllowed"), WarningColor);

        _penisColour.Set(penis.MatchSkin, penis.Color);
        SheathColourRow.Visible = penis.Sheath != SheathType.None;
        _sheathColour.Set(penis.SheathMatchSkin, penis.SheathColor);
        _penisVisibility.Select(penis.Visibility);

        var testicles = _profile.Testicles;
        _testicleType.Select(testicles?.Type ?? TesticleType.None);
        TesticleInternalNote.Visible = testicles is { Type: TesticleType.Internal };
        TesticleDetails.Visible = testicles is { Type: TesticleType.External };
        if (testicles is not { Type: TesticleType.External })
            return;

        var size = Math.Clamp(testicles.Size, GenitalProfileValidator.MinTesticleSize, GenitalProfileValidator.MaxTesticleSize);
        TesticleSizeSlider.SetValueWithoutEvent(size);
        TesticleSizeValue.Text = GenitalWords.TesticleSize(size);
        SetWarnings(TesticleWarning, GenitalIssue.SizeClamped);
        _testicleColour.Set(testicles.MatchSkin, testicles.Color);
        _testicleVisibility.Select(testicles.Visibility);
    }

