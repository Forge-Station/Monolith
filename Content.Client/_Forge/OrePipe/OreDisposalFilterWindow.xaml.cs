using Content.Shared._Forge.OrePipe;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Forge.OrePipe;

[GenerateTypedNameReferences]
public sealed partial class OreDisposalFilterWindow : DefaultWindow
{
    private readonly Dictionary<string, Button> _oreButtons = new();
    private readonly HashSet<string> _selected = new();

    public event Action<HashSet<string>>? FilteredChanged;

    public OreDisposalFilterWindow()
    {
        RobustXamlLoader.Load(this);
        SelectAllButton.OnPressed += _ => SelectAll();
        DeselectAllButton.OnPressed += _ => DeselectAll();
    }

    public void Populate(IEnumerable<OreDisposalFilterOption> options)
    {
        OreContainer.RemoveAllChildren();
        _oreButtons.Clear();
        _selected.Clear();

        foreach (var option in options)
        {
            if (option.Filtered)
                _selected.Add(option.StackId);

            var button = new Button
            {
                Name = option.StackId,
                Text = option.Name,
                ToggleMode = true,
                HorizontalExpand = true,
                MinHeight = 32,
                Pressed = option.Filtered,
            };

            button.OnToggled += args =>
            {
                if (args.Pressed)
                    _selected.Add(option.StackId);
                else
                    _selected.Remove(option.StackId);

                FilteredChanged?.Invoke(new HashSet<string>(_selected));
            };

            _oreButtons[option.StackId] = button;
            OreContainer.AddChild(button);
        }
    }

    public void SetSelected(HashSet<string> selected)
    {
        _selected.Clear();
        _selected.UnionWith(selected);
        foreach (var (id, button) in _oreButtons)
            button.Pressed = selected.Contains(id);
    }

    private void SelectAll()
    {
        _selected.Clear();
        foreach (var (id, button) in _oreButtons)
        {
            button.Pressed = true;
            _selected.Add(id);
        }

        FilteredChanged?.Invoke(new HashSet<string>(_selected));
    }

    private void DeselectAll()
    {
        foreach (var button in _oreButtons.Values)
            button.Pressed = false;

        _selected.Clear();
        FilteredChanged?.Invoke(new HashSet<string>(_selected));
    }
}
