    /// <summary>Fills every control from the profile and context, or shows the gate instead.</summary>
    private void Refresh()
    {
        _syncing = true;
        try
        {
            if (UpdateGate())
                return;

            EnsureTiles();
            var settings = GenitalProfileValidator.GetSettings(_proto);
            var tissue = GenitalColorDefaults.TissueColorFor(_species, _proto);
            RefreshHeader();
            RefreshPenis(settings, tissue);
            RefreshVagina(tissue);
            RefreshBreasts();
        }
        finally
        {
            _syncing = false;
        }
    }

    /// <summary>Shows the first gate that applies instead of the controls. True while gated.</summary>
    private bool UpdateGate()
    {
        var message = GateMessage(out var optedOut, out var consentButton);
        var gated = message != null;
        GateCard.Visible = gated;
        EditorBody.Visible = !gated;
        OpenConsentButton.Visible = consentButton;

        if (!gated)
            return false;

        GateLabel.SetMessage(message!);
        HidePresetConfirm();

        // Anatomy art only exists for players who have opted in.
        if (optedOut && _tilesBuilt)
            DisposeTiles();

        return true;
    }

    /// <summary>The gate message in the order of the design: kill switch, offline, consent, age, species; null when none applies.</summary>
    /// <param name="optedOut">The gate is the kill switch, a missing connection or missing consent.</param>
    /// <param name="consentButton">The gate offers the consent settings button.</param>
    private string? GateMessage(out bool optedOut, out bool consentButton)
    {
        optedOut = true;
        consentButton = false;

        if (!_cfg.GetCVar(WolfgateCVars.AnatomyEnabled))
            return Loc.GetString("wf-genitals-gate-disabled");

        if (!_consent.HasLoaded)
            return Loc.GetString("wf-genitals-gate-offline");

        if (!_entManager.EntitySysManager.TryGetEntitySystem(out ClientGenitalConsentSystem? consent) || !consent.ViewerHasMaster())
        {
            consentButton = true;
            return Loc.GetString("wf-genitals-gate-consent");
        }

        optedOut = false;
        var settings = GenitalProfileValidator.GetSettings(_proto);
        if (GenitalProfileValidator.IsEligible(_age, _species, settings, out var reason))
            return null;

        return reason == GenitalIssue.SpeciesExcluded
            ? Loc.GetString("wf-genitals-gate-species")
            : Loc.GetString("wf-genitals-gate-age", ("age", settings.AdultAge));
    }

    private void RefreshHeader()
