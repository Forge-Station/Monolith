    /// <summary>One warning line per listed issue from the last validation; hidden when there is none.</summary>
    private void SetWarnings(RichTextLabel label, params GenitalIssue[] issues)
    {
        var lines = new List<string>();
        foreach (var issue in issues)
        {
            if (_issues.Contains(issue))
                lines.Add(Loc.GetString($"wf-genitals-warning-{issue}"));
        }

        label.Visible = lines.Count > 0;
        if (lines.Count > 0)
            label.SetMessage(string.Join("\n", lines), WarningColor);
    }

