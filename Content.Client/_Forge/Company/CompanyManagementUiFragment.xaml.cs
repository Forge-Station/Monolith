    private void RebuildJobs()
    {
        _jobsTab.RemoveAllChildren();
        if (_state is not { HasCompany: true } state)
            return;

        _jobsTab.AddChild(_styles.MakeText(Loc.GetString("company-job-intro"), _styles.Theme.SubText));
        var taken = state.Jobs.Find(job => job.TakenByUs);
        if (taken != null)
            _jobsTab.AddChild(BuildTakenJob(taken));

        var canPost = state.IsOwner || (state.Permissions & CompanyPermission.PostContracts) != 0;
        if (canPost)
            _jobsTab.AddChild(BuildJobPost(state));
        else
            _jobsTab.AddChild(_styles.MakeText(Loc.GetString("company-spend-no-fund-permission"), _styles.Theme.SubText));

        var anyOpen = false;
        foreach (var job in state.Jobs)
        {
            if (job.TakenByUs)
                continue;

            anyOpen = true;
            _jobsTab.AddChild(BuildOpenJob(job, state, taken != null));
        }

        if (!anyOpen)
            _jobsTab.AddChild(_styles.MakeText(Loc.GetString("company-job-none"), _styles.Theme.SubText));
    }

