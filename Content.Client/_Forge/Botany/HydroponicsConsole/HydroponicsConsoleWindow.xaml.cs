using System.Linq;
using System.Numerics;
using Content.Client._Forge.Botany.UI;
using Content.Client.GameTicking.Managers;
using Content.Shared._Forge.Botany;
using Content.Shared._Forge.Botany.HydroponicsConsole;
using Robust.Client.AutoGenerated;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;
using Robust.Shared.Maths;

namespace Content.Client._Forge.Botany.HydroponicsConsole;

[GenerateTypedNameReferences]
public sealed partial class HydroponicsConsoleWindow : BaseWindow
{
    [Dependency] private readonly IResourceCache _resCache = default!;
    [Dependency] private readonly IGameTiming _timing = default!;
    [Dependency] private readonly IEntitySystemManager _systems = default!;

    private readonly BotanyUiStyles _styles;
    private readonly ClientGameTicker _ticker;
    private readonly List<HydroponicsConsoleTrayEntry> _trays = new();
    private readonly List<HydroponicsCultivarRecord> _journal = new();
    private NetEntity? _selected;
    private int? _selectedCultivar;
    private TrayFilter _filter = TrayFilter.All;
    private ConsoleView _view = ConsoleView.Trays;

    public event Action<NetEntity, string>? OnSaveCultivar;
    public event Action<int, string>? OnRenameCultivar;
    public event Action<int>? OnDeleteCultivar;
    public event Action<int>? OnPrintPacket;
    public event Action<int>? OnEjectDisk;
    public event Action<NetEntity>? OnCycleLight;
    public event Action<NetEntity, string>? OnRenameTray;

    private enum ConsoleView : byte
    {
        Trays,
        Journal
    }

    private enum TrayFilter : byte
    {
        All,
        Harvest,
        LowWater,
        Radiation,
        Carnivorous
    }

    public HydroponicsConsoleWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _styles = new BotanyUiStyles(_resCache);
        _ticker = _systems.GetEntitySystem<ClientGameTicker>();

        TitleLabel.Text = Loc.GetString("hydroponics-console-title");
        SubtitleLabel.Text = Loc.GetString("hydroponics-console-subtitle");
        DetailHeader.Text = Loc.GetString("hydroponics-console-detail-header");
        ListHeader.Text = Loc.GetString("hydroponics-console-list-header");
        OsLabel.Text = Loc.GetString("hydroponics-console-os");
        LineNameEdit.PlaceHolder = Loc.GetString("hydroponics-console-journal-name-placeholder");

        CloseButton.OnPressed += _ => Close();
        ApplyChrome();
        RebuildViewBar();
        RebuildFilterBar();
        ShowEmptyDetails();
    }

    protected override DragMode GetDragModeFor(Vector2 relativeMousePos) => DragMode.Move;

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        var stationTime = _timing.CurTime.Subtract(_ticker.RoundStartTimeSpan);
        TimeLabel.Text = stationTime.ToString(@"hh\:mm\:ss");
    }

    public void Populate(HydroponicsConsoleBoundUserInterfaceState state)
    {
        _trays.Clear();
        _trays.AddRange(state.Trays);
        _journal.Clear();
        _journal.AddRange(state.Journal);

        if (_selected is { } selected && _trays.All(t => t.Entity != selected))
            _selected = null;

        if (_selected == null && _trays.Count > 0)
            _selected = _trays[0].Entity;

        if (_selectedCultivar is { } idx && _journal.All(j => j.Index != idx))
            _selectedCultivar = null;

        if (_selectedCultivar == null && _journal.Count > 0)
            _selectedCultivar = _journal[0].Index;

        RefreshStatus();
        RebuildViewBar();
        RebuildFilterBar();
        RebuildList();
        ShowSelectedDetails();
    }

    private void RefreshStatus()
    {
        var harvest = _trays.Count(t => t.Harvest);
        var water = _trays.Count(t => t.HasPlant && t.Water <= 15);
        var rad = _trays.Count(t => t.Radioactive);
        var grab = _trays.Count(t => t.CarnivorousGrab);
        AlertLabel.Text = Loc.GetString("hydroponics-console-alerts",
            ("harvest", harvest), ("water", water), ("rad", rad), ("grab", grab));

        StatusLabel.Text = _trays.Count == 0
            ? Loc.GetString("hydroponics-console-no-trays")
            : Loc.GetString("hydroponics-console-tray-count", ("count", _trays.Count));
    }

    private void RebuildViewBar()
    {
        ViewBar.DisposeAllChildren();
        ViewBar.AddChild(MakeViewChip(Loc.GetString("hydroponics-console-view-trays"), ConsoleView.Trays));
        ViewBar.AddChild(MakeViewChip(Loc.GetString("hydroponics-console-view-journal", ("count", _journal.Count)), ConsoleView.Journal));
        JournalToolbar.Visible = true;
        FilterBar.Visible = _view == ConsoleView.Trays;
        LineNameEdit.PlaceHolder = _view == ConsoleView.Journal
            ? Loc.GetString("hydroponics-console-journal-name-placeholder")
            : Loc.GetString("hydroponics-console-tray-name-placeholder");
    }

    private void RebuildFilterBar()
    {
        FilterBar.DisposeAllChildren();
        FilterBar.AddChild(MakeFilterChip(Loc.GetString("hydroponics-console-filter-all"), TrayFilter.All));
        FilterBar.AddChild(MakeFilterChip(Loc.GetString("hydroponics-console-filter-harvest"), TrayFilter.Harvest));
        FilterBar.AddChild(MakeFilterChip(Loc.GetString("hydroponics-console-filter-water"), TrayFilter.LowWater));
        FilterBar.AddChild(MakeFilterChip(Loc.GetString("hydroponics-console-filter-rad"), TrayFilter.Radiation));
        FilterBar.AddChild(MakeFilterChip(Loc.GetString("hydroponics-console-filter-grab"), TrayFilter.Carnivorous));
    }

    private BotanyChipButton MakeViewChip(string text, ConsoleView view)
    {
        var button = _styles.Chip(text, _view == view);
        button.OnPressed += _ =>
        {
            _view = view;
            RebuildViewBar();
            RebuildFilterBar();
            RebuildList();
            ShowSelectedDetails();
        };
        return button;
    }

    private BotanyChipButton MakeFilterChip(string text, TrayFilter filter)
    {
        var button = _styles.Chip(text, _filter == filter);
        button.OnPressed += _ =>
        {
            _filter = filter;
            RebuildFilterBar();
            RebuildList();
            ShowSelectedDetails();
        };
        return button;
    }

    private IEnumerable<HydroponicsConsoleTrayEntry> VisibleTrays()
    {
        return _trays.Where(tray => _filter switch
        {
            TrayFilter.Harvest => tray.Harvest,
            TrayFilter.LowWater => tray.HasPlant && tray.Water <= 15,
            TrayFilter.Radiation => tray.Radioactive,
            TrayFilter.Carnivorous => tray.CarnivorousGrab,
            _ => true
        });
    }

    private void RebuildList()
    {
        var scroll = ListScroll.VScrollTarget;
        ListContainer.DisposeAllChildren();

        if (_view == ConsoleView.Journal)
        {
            ListHeader.Text = Loc.GetString("hydroponics-console-journal-header");
            ListCountLabel.Text = _journal.Count.ToString();
            if (_journal.Count == 0)
            {
                ListContainer.AddChild(_styles.Sub(Loc.GetString("hydroponics-console-journal-empty")));
                ListScroll.VScrollTarget = scroll;
                return;
            }

            foreach (var record in _journal)
            {
                var button = new BotanyListButton(_styles) { Key = record.Index };
                var subtitle = $"{record.SpeciesName}  P{record.Potency:0}  Y{record.Yield}";
                var color = record.Radioactive || record.CarnivorousGrab ? BotanyUiTheme.Warning : BotanyUiTheme.Text;
                button.SetContent(record.LineName, subtitle, color);
                button.ApplySelected(_selectedCultivar == record.Index);
                var captured = record.Index;
                button.OnPressed += _ =>
                {
                    _selectedCultivar = captured;
                    RebuildList();
                    ShowSelectedDetails();
                };
                ListContainer.AddChild(button);
            }

            ListScroll.VScrollTarget = scroll;
            return;
        }

        ListHeader.Text = Loc.GetString("hydroponics-console-list-header");
        var visible = VisibleTrays().ToList();
        ListCountLabel.Text = $"{visible.Count}/{_trays.Count}";

        if (visible.Count == 0)
        {
            ListContainer.AddChild(_styles.Sub(Loc.GetString("hydroponics-console-list-empty")));
            ListScroll.VScrollTarget = scroll;
            return;
        }

        foreach (var tray in visible)
        {
            var button = new BotanyListButton(_styles) { Key = tray.Entity };
            var title = tray.TrayName;
            string subtitle;
            Color subtitleColor;

            if (!tray.HasPlant)
            {
                subtitle = Loc.GetString("hydroponics-console-list-empty-tray");
                subtitleColor = BotanyUiTheme.Empty;
            }
            else if (tray.Dead)
            {
                subtitle = $"{tray.PlantName} — {Loc.GetString("hydroponics-console-status-dead")}";
                subtitleColor = BotanyUiTheme.Danger;
            }
            else if (tray.Harvest)
            {
                subtitle = $"{tray.PlantName} — {Loc.GetString("hydroponics-console-status-harvest")}";
                subtitleColor = BotanyUiTheme.Harvest;
            }
            else
            {
                subtitle = $"{tray.PlantName} — {Loc.GetString("hydroponics-console-status-growing")}  HP {tray.Health:0}/{tray.Endurance:0}";
                subtitleColor = TrayHealthColor(tray);
            }

            button.SetContent(title, subtitle, subtitleColor);
            button.ApplySelected(_selected == tray.Entity);
            var captured = tray.Entity;
            button.OnPressed += _ =>
            {
                _selected = captured;
                RebuildList();
                ShowSelectedDetails();
            };
            ListContainer.AddChild(button);
        }

        ListScroll.VScrollTarget = scroll;
    }

    private void ShowSelectedDetails()
    {
        DetailContainer.DisposeAllChildren();

        if (_view == ConsoleView.Journal)
        {
            ShowJournalDetails();
            return;
        }

        JournalToolbar.Visible = true;
        DetailHeader.Text = Loc.GetString("hydroponics-console-detail-header");
        var tray = _trays.FirstOrDefault(t => t.Entity == _selected);
        if (tray == null)
        {
            ShowEmptyDetails();
            return;
        }

        if (!LineNameEdit.HasKeyboardFocus())
            LineNameEdit.Text = tray.TrayName;

        var name = tray.HasPlant ? tray.PlantName : Loc.GetString("hydroponics-console-list-empty-tray");
        DetailContainer.AddChild(_styles.Heading($"{tray.TrayName}  [{(string.IsNullOrEmpty(tray.Address) ? "-" : tray.Address)}]"));
        DetailContainer.AddChild(_styles.Body(name, 14, tray.HasPlant ? BotanyUiTheme.Ok : BotanyUiTheme.Empty));

        if (!tray.HasPlant)
        {
            DetailContainer.AddChild(_styles.Sub(Loc.GetString("hydroponics-console-detail-empty")));
            AddLightButton(tray);
            return;
        }

        var status = tray.Dead
            ? Loc.GetString("hydroponics-console-status-dead")
            : tray.Harvest
                ? Loc.GetString("hydroponics-console-status-harvest")
                : Loc.GetString("hydroponics-console-status-growing");
        var statusColor = tray.Dead ? BotanyUiTheme.Danger : tray.Harvest ? BotanyUiTheme.Harvest : BotanyUiTheme.Ok;

        DetailContainer.AddChild(_styles.Section(Loc.GetString("hydroponics-console-section-status")));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("hydroponics-console-field-status"), status, statusColor));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("hydroponics-console-field-health"), $"{tray.Health:0} / {tray.Endurance:0}", TrayHealthColor(tray)));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("hydroponics-console-field-age"), tray.Age.ToString()));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("hydroponics-console-field-water"), $"{tray.Water:0}", LevelColor(tray.Water, 15)));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("hydroponics-console-field-nutrition"), $"{tray.Nutrition:0}", LevelColor(tray.Nutrition, 8)));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("hydroponics-console-field-toxins"), $"{tray.Toxins:0}", tray.Toxins >= 40 ? BotanyUiTheme.Danger : BotanyUiTheme.Text));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("hydroponics-console-field-weeds"), $"{tray.Weeds:0.#}", tray.Weeds >= 5 ? BotanyUiTheme.Warning : BotanyUiTheme.Text));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("hydroponics-console-field-pests"), $"{tray.Pests:0.#}", tray.Pests >= 5 ? BotanyUiTheme.Warning : BotanyUiTheme.Text));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("hydroponics-console-field-light-mode"),
            Loc.GetString($"plant-holder-light-{tray.LightMode.ToString().ToLowerInvariant()}"),
            tray.ImproperLight ? BotanyUiTheme.Warning : BotanyUiTheme.Text));

        var warnings = new List<string>();
        if (tray.ImproperHeat)
            warnings.Add(Loc.GetString("hydroponics-console-warn-heat"));
        if (tray.ImproperPressure)
            warnings.Add(Loc.GetString("hydroponics-console-warn-pressure"));
        if (tray.ImproperLight)
            warnings.Add(Loc.GetString("hydroponics-console-warn-light"));
        if (tray.MissingGas)
            warnings.Add(Loc.GetString("hydroponics-console-warn-gas"));
        if (tray.Radioactive)
            warnings.Add(Loc.GetString("hydroponics-console-warn-radiation"));
        if (tray.CarnivorousGrab)
            warnings.Add(Loc.GetString("hydroponics-console-warn-grab"));
        if (tray.CarnivorousPestEater)
            warnings.Add(Loc.GetString("hydroponics-console-warn-pest-eater"));
        if (tray.GeneLocked)
            warnings.Add(Loc.GetString("hydroponics-console-warn-locked"));

        DetailContainer.AddChild(_styles.Section(Loc.GetString("hydroponics-console-section-warnings")));
        DetailContainer.AddChild(warnings.Count == 0
            ? _styles.Body(Loc.GetString("hydroponics-console-warnings-none"), 12, BotanyUiTheme.Ok)
            : _styles.Body(string.Join(" · ", warnings), 12, BotanyUiTheme.Warning));

        DetailContainer.AddChild(_styles.Section(Loc.GetString("hydroponics-console-section-atmos")));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("hydroponics-console-field-heat"), $"{tray.IdealHeat:0} K ± {tray.HeatTolerance:0.#}"));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("hydroponics-console-field-ideal-light"), $"{tray.IdealLight:0.#} ± {tray.LightTolerance:0.#}"));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("hydroponics-console-field-pressure"), $"{tray.LowPressure:0} – {tray.HighPressure:0} kPa"));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("hydroponics-console-field-consume"),
            string.IsNullOrEmpty(tray.ConsumeGases) ? Loc.GetString("plant-analyzer-plant-gases-none") : tray.ConsumeGases));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("hydroponics-console-field-exude"),
            string.IsNullOrEmpty(tray.ExudeGases) ? Loc.GetString("plant-analyzer-plant-gases-none") : tray.ExudeGases));

        DetailContainer.AddChild(_styles.Section(Loc.GetString("hydroponics-console-section-genes")));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("hydroponics-console-field-chems"),
            tray.Chemicals.Length == 0 ? "—" : string.Join(", ", tray.Chemicals)));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("hydroponics-console-field-mutations"),
            tray.Mutations.Length == 0 ? "—" : string.Join(", ", tray.Mutations)));

        var actions = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            Margin = new Thickness(0, 10, 0, 0)
        };
        var save = _styles.Action(Loc.GetString("hydroponics-console-save-line"));
        save.OnPressed += _ =>
        {
            var line = string.IsNullOrWhiteSpace(LineNameEdit.Text) ? tray.PlantName : LineNameEdit.Text;
            OnSaveCultivar?.Invoke(tray.Entity, line);
        };
        actions.AddChild(save);
        var light = _styles.Action(Loc.GetString("hydroponics-console-cycle-light"));
        light.OnPressed += _ => OnCycleLight?.Invoke(tray.Entity);
        actions.AddChild(light);
        var rename = _styles.Action(Loc.GetString("hydroponics-console-rename-tray"));
        rename.OnPressed += _ => OnRenameTray?.Invoke(tray.Entity, LineNameEdit.Text);
        actions.AddChild(rename);
        DetailContainer.AddChild(actions);
    }

    private void ShowJournalDetails()
    {
        JournalToolbar.Visible = true;
        DetailHeader.Text = Loc.GetString("hydroponics-console-journal-detail");
        var record = _journal.FirstOrDefault(r => r.Index == _selectedCultivar);
        if (record == null)
        {
            DetailContainer.AddChild(_styles.Sub(Loc.GetString("hydroponics-console-journal-none")));
            return;
        }

        if (!LineNameEdit.HasKeyboardFocus())
            LineNameEdit.Text = record.LineName;

        DetailContainer.AddChild(_styles.Heading(record.LineName));
        DetailContainer.AddChild(_styles.Body(record.SpeciesName, 14, BotanyUiTheme.Ok));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("plant-analyzer-field-potency"), $"{record.Potency:0}"));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("plant-analyzer-field-yield"), record.Yield.ToString()));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("hydroponics-console-field-heat"), $"{record.IdealHeat:0} K"));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("hydroponics-console-field-ideal-light"), $"{record.IdealLight:0.#}"));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("hydroponics-console-field-chems"),
            record.Chemicals.Length == 0 ? "—" : string.Join(", ", record.Chemicals)));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("hydroponics-console-field-mutations"),
            record.Mutations.Length == 0 ? "—" : string.Join(", ", record.Mutations)));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("hydroponics-console-field-consume"),
            string.IsNullOrEmpty(record.ConsumeGases) ? Loc.GetString("plant-analyzer-plant-gases-none") : record.ConsumeGases));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("hydroponics-console-field-exude"),
            string.IsNullOrEmpty(record.ExudeGases) ? Loc.GetString("plant-analyzer-plant-gases-none") : record.ExudeGases));

        var flags = new List<string>();
        if (record.Ligneous)
            flags.Add(Loc.GetString("plant-analyzer-mutation-ligneous"));
        if (record.Radioactive)
            flags.Add(Loc.GetString("plant-analyzer-mutation-radioactive"));
        if (record.CarnivorousGrab)
            flags.Add(Loc.GetString("plant-analyzer-mutation-grabber"));
        if (record.CarnivorousPestEater)
            flags.Add(Loc.GetString("plant-analyzer-mutation-pest-eater"));
        if (record.GeneLocked)
            flags.Add(Loc.GetString("plant-analyzer-mutation-gene-locked"));
        if (flags.Count > 0)
            DetailContainer.AddChild(_styles.Body(string.Join(" · ", flags), 12, BotanyUiTheme.Warning));

        var actions = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            Margin = new Thickness(0, 10, 0, 0)
        };
        var rename = _styles.Action(Loc.GetString("hydroponics-console-rename-line"));
        rename.OnPressed += _ => OnRenameCultivar?.Invoke(record.Index, LineNameEdit.Text);
        var print = _styles.Action(Loc.GetString("hydroponics-console-print-packet"));
        print.OnPressed += _ => OnPrintPacket?.Invoke(record.Index);
        var eject = _styles.Action(Loc.GetString("hydroponics-console-eject-disk"));
        eject.OnPressed += _ => OnEjectDisk?.Invoke(record.Index);
        var delete = _styles.Action(Loc.GetString("hydroponics-console-delete-line"));
        delete.OnPressed += _ => OnDeleteCultivar?.Invoke(record.Index);
        actions.AddChild(rename);
        actions.AddChild(print);
        actions.AddChild(eject);
        actions.AddChild(delete);
        DetailContainer.AddChild(actions);
    }

    private void AddLightButton(HydroponicsConsoleTrayEntry tray)
    {
        var light = _styles.Action(Loc.GetString("hydroponics-console-cycle-light"));
        light.OnPressed += _ => OnCycleLight?.Invoke(tray.Entity);
        var rename = _styles.Action(Loc.GetString("hydroponics-console-rename-tray"));
        rename.OnPressed += _ => OnRenameTray?.Invoke(tray.Entity, LineNameEdit.Text);
        DetailContainer.AddChild(light);
        DetailContainer.AddChild(rename);
    }

    private void ShowEmptyDetails()
    {
        DetailContainer.DisposeAllChildren();
        DetailContainer.AddChild(_styles.Sub(Loc.GetString("hydroponics-console-detail-none")));
    }

    private static Color TrayHealthColor(HydroponicsConsoleTrayEntry tray)
    {
        if (tray.Dead || tray.Endurance <= 0)
            return BotanyUiTheme.Danger;
        var ratio = tray.Health / tray.Endurance;
        if (ratio <= 0.25f)
            return BotanyUiTheme.Danger;
        if (ratio <= 0.5f)
            return BotanyUiTheme.Warning;
        return BotanyUiTheme.Ok;
    }

    private static Color LevelColor(float value, float low)
    {
        return value <= low ? BotanyUiTheme.Warning : BotanyUiTheme.Text;
    }

    private void ApplyChrome()
    {
        Background.ModulateSelfOverride = BotanyUiTheme.WindowBackground;
        Border.ModulateSelfOverride = BotanyUiTheme.WindowBorder;
        CloseButton.ModulateSelfOverride = BotanyUiTheme.CloseButton;
        ContentBorder.ModulateSelfOverride = BotanyUiTheme.ContentBorder;
        ContentBackground.ModulateSelfOverride = BotanyUiTheme.ContentBackground;

        TitleLabel.FontOverride = _styles.GetBoldFont(18);
        TitleLabel.FontColorOverride = BotanyUiTheme.Heading;
        TimeLabel.FontOverride = _styles.GetBoldFont(16);
        TimeLabel.FontColorOverride = BotanyUiTheme.Heading;
        SubtitleLabel.FontOverride = _styles.GetRegularFont(12);
        SubtitleLabel.FontColorOverride = BotanyUiTheme.SubText;
        StatusLabel.FontOverride = _styles.GetRegularFont(12);
        StatusLabel.FontColorOverride = BotanyUiTheme.Text;
        AlertLabel.FontOverride = _styles.GetBoldFont(12);
        AlertLabel.FontColorOverride = BotanyUiTheme.Harvest;
        DetailHeader.FontOverride = _styles.GetBoldFont(13);
        DetailHeader.FontColorOverride = BotanyUiTheme.Heading;
        ListHeader.FontOverride = _styles.GetBoldFont(13);
        ListHeader.FontColorOverride = BotanyUiTheme.Heading;
        ListCountLabel.FontOverride = _styles.GetRegularFont(12);
        ListCountLabel.FontColorOverride = BotanyUiTheme.Text;
        OsLabel.FontOverride = _styles.GetRegularFont(11);
        OsLabel.FontColorOverride = BotanyUiTheme.SubText;

        BotanyUiStyles.ApplyPanel(MainDivider, BotanyUiTheme.Divider, BotanyUiTheme.Divider, 0);
        BotanyUiStyles.ApplyPanel(DetailPanel, BotanyUiTheme.ListBackground, BotanyUiTheme.ListBorder);
        BotanyUiStyles.ApplyPanel(ListPanel, BotanyUiTheme.ListBackground, BotanyUiTheme.ListBorder);
    }
}
