# What Wolfgate already has

def scan_wolfgate() -> dict:
    """Component names from the C# sources, and the ids of the prototypes outside this module, by kind."""
    components = set()
    for root in ("Content.Shared", "Content.Server", "Content.Client", "RobustToolbox/Robust.Shared",
                 "RobustToolbox/Robust.Server", "RobustToolbox/Robust.Client"):
        for path in (REPO / root).rglob("*.cs"):
            parts = path.parts
            if "bin" in parts or "obj" in parts:
                continue
            text = path.read_text(encoding="utf-8", errors="ignore")
            components.update(re.findall(r"class\s+(\w+?)Component\b", text))
            components.update(re.findall(r'ComponentProtoName\("(\w+)"\)', text))
    if "Transform" not in components:
        sys.exit("RobustToolbox is empty here: the engine's components can't be read. Check out the submodule first.")

    ids = defaultdict(set)
    own = (REPO / PROTOTYPES).resolve()
    for path in (REPO / "Resources/Prototypes").rglob("*.yml"):
        if own in path.resolve().parents:
            continue
        kind = None
        for line in path.read_text(encoding="utf-8-sig", errors="ignore").splitlines():
            match = re.match(r"- type: (\S+)", line)
            if match:
                kind = match.group(1)
                continue
            match = re.match(r"  id: (\S+)", line)
            if match and kind:
                ids[kind].add(match.group(1).strip("\"'"))
    return {"components": components, "ids": ids}


