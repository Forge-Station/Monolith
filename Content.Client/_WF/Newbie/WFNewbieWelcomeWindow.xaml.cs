using Content.Client.UserInterface.Controls;
using Content.Shared._WF.Newbie;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;
using Robust.Shared.Utility;

namespace Content.Client._WF.Newbie;

/// <summary>The welcome popup a new player gets on joining, with a way to stop it.</summary>
[GenerateTypedNameReferences]
public sealed partial class WFNewbieWelcomeWindow : FancyWindow
{
    [Dependency] private IConfigurationManager _cfg = default!;

    /// <summary>The player asked to read the new player rule.</summary>
    public event Action? OnOpenRules;

    public WFNewbieWelcomeWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        WelcomeLabel.SetMessage(FormattedMessage.FromMarkupOrThrow(
            Loc.GetString("wf-newbie-welcome-text", ("hours", _cfg.GetCVar(WFNewbieCVars.Hours)))));
        RulesButton.OnPressed += _ => OnOpenRules?.Invoke();
        OkButton.OnPressed += _ => Close();
    }

    /// <summary>Whether "Don't show this again" is ticked.</summary>
    public bool DontShowAgain => DontShowAgainCheckBox.Pressed;
}
