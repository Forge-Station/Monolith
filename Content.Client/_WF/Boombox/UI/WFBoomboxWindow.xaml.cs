using Content.Client.UserInterface.Controls;
using Content.Shared._WF.Audio.InternetSound;
using Content.Shared._WF.Boombox;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Audio.Systems;
using Robust.Shared.Timing;

namespace Content.Client._WF.Boombox.UI;

/// <summary>
/// The boombox: a green display with the playing track and its progress, transport keys, a volume knob, a slot
/// for links and playlists, and the queue with per-track move up and remove.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class WFBoomboxWindow : FancyWindow
{
    [Dependency] private IEntityManager _entMan = default!;
    [Dependency] private IGameTiming _timing = default!;

    public event Action<string>? OnAdd;
    public event Action? OnSkip;
    public event Action? OnStop;
    public event Action? OnShuffle;
    public event Action<bool>? OnRepeat;
    public event Action? OnClear;
    public event Action<int>? OnRemove;
    public event Action<int>? OnMoveUp;
    public event Action<float>? OnVolume;

    private EntityUid _owner;
    private bool _reading;
    private WFBoomboxEntry? _current;

    public WFBoomboxWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        RightSpeaker.Phase = 0.5f;

        AddButton.OnPressed += _ => Submit();
        LinkEdit.OnTextEntered += _ => Submit();
        SkipButton.OnPressed += _ => OnSkip?.Invoke();
        StopButton.OnPressed += _ => OnStop?.Invoke();
        ShuffleButton.OnPressed += _ => OnShuffle?.Invoke();
        RepeatButton.OnToggled += args => OnRepeat?.Invoke(args.Pressed);
        ClearButton.OnPressed += _ => OnClear?.Invoke();
        VolumeSlider.OnReleased += slider => OnVolume?.Invoke(slider.Value);
    }

    public void SetOwner(EntityUid owner)
    {
        _owner = owner;
    }

    private void Submit()
    {
        var text = LinkEdit.Text.Trim();
        if (text.Length == 0)
            return;

        OnAdd?.Invoke(text);
        LinkEdit.Clear();
    }

    /// <summary>Redraws the queue and keys from the boombox's replicated state.</summary>
    public void UpdateState(WFBoomboxComponent box, InternetSoundSourceComponent? source)
    {
        _current = box.Current;
        _reading = box.Reading;
        RepeatButton.Pressed = box.Repeat;

        if (source != null && !VolumeSlider.Grabbed)
            VolumeSlider.SetValueWithoutEvent(source.Volume <= -79f ? 0f : Math.Clamp(SharedAudioSystem.VolumeToGain(source.Volume), 0f, 1f));

        QueueLabel.Text = Loc.GetString("wf-boombox-queue", ("count", box.Queue.Count), ("max", WFBoomboxComponent.MaxQueued));
        ClearButton.Disabled = box.Queue.Count == 0;
        ShuffleButton.Disabled = box.Queue.Count < 2;
        SkipButton.Disabled = box.Current == null && box.Queue.Count == 0;
        StopButton.Disabled = box.Current == null && box.Queue.Count == 0;

        QueueList.RemoveAllChildren();
        if (box.Queue.Count == 0)
        {
            QueueList.AddChild(new Label
            {
                Text = Loc.GetString("wf-boombox-queue-empty"),
                FontColorOverride = Color.FromHex("#6d6c75"),
            });
        }

        for (var i = 0; i < box.Queue.Count; i++)
            QueueList.AddChild(QueueRow(i, box.Queue[i]));

        UpdateDisplay();
    }

    private Control QueueRow(int index, WFBoomboxEntry entry)
    {
        var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6 };
        row.AddChild(new Label { Text = $"{index + 1:00}", FontColorOverride = Color.FromHex("#e8c25a"), MinWidth = 24 });
        row.AddChild(new Label { Text = entry.Label, ClipText = true, HorizontalExpand = true });

        if (entry.Seconds > 0)
            row.AddChild(new Label { Text = FormatTime(entry.Seconds), FontColorOverride = Color.FromHex("#8a8992") });

        var up = new Button { Text = Loc.GetString("wf-boombox-move-up"), Disabled = index == 0, StyleClasses = { "ButtonSquare" } };
        up.OnPressed += _ => OnMoveUp?.Invoke(entry.Id);
        row.AddChild(up);

        var remove = new Button { Text = Loc.GetString("wf-boombox-remove"), StyleClasses = { "ButtonSquare" } };
        remove.OnPressed += _ => OnRemove?.Invoke(entry.Id);
        row.AddChild(remove);
        return row;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateDisplay();
    }

    /// <summary>The display: title, elapsed time and progress, read live from the playing track.</summary>
    private void UpdateDisplay()
    {
        _entMan.TryGetComponent(_owner, out InternetSoundSourceComponent? source);
        var playing = source != null && source.Path != null && source.IsPlaying(_timing.CurTime);

        LeftSpeaker.Playing = playing;
        RightSpeaker.Playing = playing;

        if (playing && source != null)
        {
            var elapsed = Math.Clamp((float) (_timing.CurTime - source.Start).TotalSeconds, 0f, source.Length);
            TitleLabel.Text = source.Title ?? _current?.Label ?? string.Empty;
            TimeLabel.Text = Loc.GetString("wf-boombox-time",
                ("elapsed", FormatTime((int) elapsed)), ("total", FormatTime((int) Math.Ceiling(source.Length))));
            TrackProgress.Value = source.Length > 0f ? elapsed / source.Length : 0f;
            return;
        }

        TrackProgress.Value = 0f;
        TimeLabel.Text = string.Empty;

        if (_current is { } current)
        {
            TitleLabel.Text = current.Label;
            TimeLabel.Text = Loc.GetString("wf-boombox-loading");
        }
        else if (_reading)
        {
            TitleLabel.Text = Loc.GetString("wf-boombox-reading-playlist");
        }
        else
        {
            TitleLabel.Text = Loc.GetString("wf-boombox-idle");
        }
    }

    private static string FormatTime(int seconds)
    {
        return $"{seconds / 60}:{seconds % 60:00}";
    }
}
