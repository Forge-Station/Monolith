using System.Numerics;
using Content.Shared._Forge.CCVars;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;
using Robust.Shared.Utility;

namespace Content.Client.Lobby.UI;

[GenerateTypedNameReferences]
public sealed partial class LobbyCharacterPreviewPanel : Control
{
    [Dependency] private IEntityManager _entManager = default!;
    [Dependency] private IConfigurationManager _cfg = default!;

    public Button CharacterSetupButton => CharacterSetup;

    private EntityUid? _previewDummy;
    private bool _loaded;
    private bool _open;
    private string _chip = string.Empty;

    public LobbyCharacterPreviewPanel()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        // Forge-Change-Start: the centre stays empty until the player opens the card; the choice is remembered
        _open = _cfg.GetCVar(ForgeCCVars.LobbyCharacterOpen);
        ShowCard.OnPressed += _ => SetOpen(true);
        HideCard.OnPressed += _ => SetOpen(false);
        ApplyVisibility();
        // Forge-Change-End
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();
        RefreshChip();
    }

    public void SetLoaded(bool value)
    {
        _loaded = value;
        ApplyVisibility();
    }

    // Forge-Change-Start: the card shows the name and a short details line instead of the summary sentence
    public void SetIdentity(string name, string details)
    {
        CharacterName.Text = name;
        Details.Text = details;
        _chip = name;
        RefreshChip();
    }
    // Forge-Change-End

    // Frontier: show bank balance on character selection.
    public void SetBankBalanceText(string value)
    {
        BankBalance.Text = value;
    }
    // End Frontier

    // Company Display
    public void SetCompanyText(string value)
    {
        if (string.IsNullOrEmpty(value))
        {
            Company.SetMessage(string.Empty);
            return;
        }

        Company.SetMessage(FormattedMessage.FromMarkupPermissive(value));
    }
    // End Company Display

    public void SetSprite(EntityUid uid)
    {
        if (_previewDummy != null)
        {
            _entManager.DeleteEntity(_previewDummy);
        }

        _previewDummy = uid;

        ViewBox.RemoveAllChildren();
        var spriteView = new SpriteView
        {
            OverrideDirection = Direction.South,
            Scale = new Vector2(5f, 5f),
            MaxSize = new Vector2(160, 160),
            Stretch = SpriteView.StretchMode.Fill,
        };
        spriteView.SetEntity(uid);
        ViewBox.AddChild(spriteView);
    }

    // Forge-Change-Start
    private void SetOpen(bool open)
    {
        _open = open;
        _cfg.SetCVar(ForgeCCVars.LobbyCharacterOpen, open);
        ApplyVisibility();
    }

    private void ApplyVisibility()
    {
        ShowCard.Visible = !_open;
        Loaded.Visible = _open && _loaded;
        Unloaded.Visible = _open && !_loaded;
        RefreshChip();
    }

    private void RefreshChip()
    {
        ShowCard.Text = string.IsNullOrWhiteSpace(_chip)
            ? Loc.GetString("forge-lobby-hero-show")
            : Loc.GetString("forge-lobby-hero-show-named", ("name", _chip));
    }
    // Forge-Change-End

    protected override void Dispose(bool disposing)
    {
        base.Dispose(disposing);
        _entManager.DeleteEntity(_previewDummy);
        _previewDummy = null;
    }
}
