# The port

class Port:
    def __init__(self, config: dict, sources: dict, wolfgate: dict):
        self.config = config
        self.sources = sources
        self.components = wolfgate["components"]
        self.ids = wolfgate["ids"]
        self.files: dict[str, str] = {}           # repo-relative path -> text
        self.rsis: dict[str, tuple] = {}          # destination rsi -> (source key, source path)
        self.loose: dict[str, tuple] = {}         # destination file -> (source key, source path)
        self.dropped = Counter()                  # (component, reason) -> count
        self.notes: list[str] = []
        self.problems: list[str] = []
        self.sprites: dict[str, dict] = {}        # entity id -> {"rsi": ..., "states": [...], "parents": [...]}
        self.docs: dict[str, dict] = {}           # entity id -> translated prototype
        self.outputs: list[tuple] = []            # (path, header, prototypes), dumped once every entity is known
        self.spawned: set[tuple] = set()          # (entity id, prototype its destruction spawns)
        self.keep: dict[str, list] = {}           # destination rsi -> the only states copied
        self.ported: set[str] = set()

    # -- textures ------------------------------------------------------------------------------------------------

    def texture(self, value: str, source: str) -> str:
        """Maps a texture path of RMC or CMU to its Wolfgate copy and remembers to copy it; other paths pass through."""
        rooted = value.startswith("/Textures/")
        path = value[len("/Textures/"):] if rooted else value
        for prefix, home in (("_RMC14/", ""), ("CMU14/", "CMU/")):
            if not path.startswith(prefix):
                continue
            rest = path[len(prefix):]
            item = rest[:rest.index(".rsi") + 4] if ".rsi" in rest else rest
            origin = self.find_texture(prefix, item)
            if origin is None:
                self.problems.append(f"texture {value} is in neither source checkout")
                return value
            (self.rsis if item.endswith(".rsi") else self.loose)[f"{TEXTURES}/{home}{item}"] = origin
            mapped = f"_WF/Streets/{home}{rest}"
            return f"/Textures/{mapped}" if rooted else mapped
        if path.endswith((".rsi", ".png")) and not (REPO / "Resources/Textures" / path).exists():
            self.problems.append(f"texture {value} does not exist in Wolfgate")
        return value

    def find_texture(self, prefix: str, item: str):
        """The checkout an RSI or texture file comes from: RMC's own copy first for an RMC path, so the trail is RMC's."""
        homes = {"_RMC14/": [("rmc", "Resources/Textures/_RMC14"), ("cmu", "Resources/Textures/_RMC14")],
                 "CMU14/": [("cmu", "Content.CMU/Resources/Textures/CMU14")]}[prefix]
        for key, root in homes:
            path = Path(self.sources[key]["path"]) / root / item
            if path.exists():
                return key, path
        return None

    def walk_textures(self, value, source: str):
        if isinstance(value, Tagged):
            value.value = self.walk_textures(value.value, source)
            return value
        if isinstance(value, dict):
            return {key: self.walk_textures(item, source) for key, item in value.items()}
        if isinstance(value, list):
            return [self.walk_textures(item, source) for item in value]
        if isinstance(value, str) and (".rsi" in value or value.endswith(".png")):
            return self.texture(value, source)
        return value

    # -- entities ------------------------------------------------------------------------------------------------

    def entities(self, entry: dict) -> None:
        source = entry["source"]
        docs = load(Path(self.sources[source]["path"]) / entry["file"])
        only = set(entry.get("only") or [])
        skip = set(entry.get("skip") or [])
        kept = []
        by_id = {doc["id"]: doc for doc in docs if doc.get("type") == "entity"}

        def sprite_owner(uid: str):
            """The RSI an entity draws from in the source, and the entity that names it."""
            doc = by_id.get(uid)
            while doc is not None:
                sprite = next((comp for comp in doc.get("components") or [] if comp.get("type") == "Sprite"), None)
                if sprite and sprite.get("sprite"):
                    return sprite["sprite"], doc["id"]
                parent = doc.get("parent")
                doc = by_id.get(parent if isinstance(parent, str) else (parent or [None])[0])
            return None, None

        for doc in docs:
            if doc.get("type") != "entity":
                continue
            uid = doc["id"]
            # A child of a base Wolfgate already has would draw from that base's RSI, which may be a trimmed copy.
            rsi, owner = sprite_owner(uid)
            if owner in self.ids["entity"] and owner != uid:
                doc["components"] = [({"type": "Sprite", "sprite": rsi, **{k: v for k, v in comp.items() if k != "type"}}
                                      if comp.get("type") == "Sprite" else comp) for comp in doc.get("components") or []]
            if uid in skip or (only and uid not in only):
                continue
            if uid in self.ids["entity"]:
                self.notes.append(f"{uid} is already in Wolfgate; its copy there is kept")
                continue
            if uid in self.ported:
                self.problems.append(f"{uid} is ported twice")
                continue
            self.ported.add(uid)
            kept.append(self.entity(doc, source))
        if not kept:
            self.problems.append(f"{entry['file']} gave no entities")
            return
        # The spawn menu's Streets sub-folder is the output folder: Buildings, Furniture, Lighting, Signs or Yards.
        folder = entry['out'].split('/')[0]
        if folder in ("Buildings", "Furniture", "Lighting", "Signs", "Yards"):
            for doc in kept:
                if "categories" in doc:
                    doc["categories"] = doc["categories"] + [f"{self.config['category']}{folder}"]
        origin = f"{self.sources[source]['dir']} {entry['file']} ({self.sources[source]['licence']})"
        self.outputs.append((f"{PROTOTYPES}/{entry['out']}", HEADER.format(origin=origin), kept))

    def entity(self, doc: dict, source: str) -> dict:
        rules = self.config
        uid = doc["id"]
        out = {}
        for key, value in doc.items():
            if key == "parent":
                parents = [value] if isinstance(value, str) else list(value)
                parents = [rules["parents"].get(parent, parent) for parent in parents]
                out["parent"] = parents[0] if len(parents) == 1 else parents
            elif key == "components":
                out["categories"] = [rules["category"]]
                out["components"] = self.component_list(uid, value, source)
            else:
                out[key] = value
        if "components" not in out:
            out["categories"] = [rules["category"]]
        # Order as upstream writes it: type, parent, id, the texts, then the rest.
        ordered = {key: out[key] for key in ("type", "abstract", "parent", "id", "categories", "name", "suffix",
                                              "description") if key in out}
        ordered.update({key: value for key, value in out.items() if key not in ordered})
        ordered.update(rules.get("texts", {}).get(uid) or {})
        for name, fields in (rules.get("set", {}).get(uid) or {}).items():
            self.override(uid, ordered, name, fields)
        self.remember_sprite(ordered)
        self.docs[uid] = ordered
        return ordered

    def inherit_breaks(self) -> None:
        """A child named in break_into that inherits its Destructible gets a copy that spawns its own broken twin."""
        for uid, broken in self.config["break_into"].items():
            entity = self.docs.get(uid)
            if entity is None or any(comp["type"] == "Destructible" for comp in entity.get("components", [])):
                continue
            ancestor = entity
            found = None
            while found is None:
                parent = ancestor.get("parent")
                ancestor = self.docs.get(parent if isinstance(parent, str) else (parent or [None])[0])
                if ancestor is None:
                    break
                found = next((comp for comp in ancestor.get("components", []) if comp["type"] == "Destructible"), None)
            if found is None:
                self.problems.append(f"{uid}: break_into has no inherited Destructible to copy")
                continue
            copy = clone(found)
            for threshold in copy.get("thresholds") or []:
                for behavior in threshold.get("behaviors") or []:
                    if isinstance(behavior, Tagged) and behavior.tag == "type:SpawnEntitiesBehavior":
                        behavior.value["spawn"] = {broken: {"min": "1", "max": "1"}}
            entity.setdefault("components", []).append(copy)

    def finish_entities(self) -> None:
        self.inherit_breaks()
        for rule in ("set", "texts", "break_into"):
            for uid in self.config.get(rule) or {}:
                if uid not in self.docs:
                    self.problems.append(f"{rule} names {uid}, which is not ported")
        for uid, proto in sorted(self.spawned):
            if proto not in self.ids["entity"] and proto not in self.ported:
                self.problems.append(f"{uid}: spawns {proto}, which Wolfgate lacks; add a rename_entities rule")
        for path, header, kept in self.outputs:
            self.files[path] = dump(kept, header)

    def component_list(self, uid: str, components: list, source: str) -> list:
        rules = self.config
        kept = []
        fold = {}
        for comp in components:
            name = comp["type"]
            if name == "Injurable":
                fold = {key: value for key, value in comp.items() if key != "type"}
                continue
            if name in rules["drop_components"]:
                self.dropped[(name, rules["drop_components"][name])] += 1
                continue
            if name not in self.components:
                self.problems.append(f"{uid}: component {name} is unknown to Wolfgate and has no rule")
                continue
            comp = dict(comp)
            for field, reason in (rules.get("drop_fields", {}).get(name) or {}).items():
                if field in comp:
                    del comp[field]
                    self.dropped[(f"{name}.{field}", reason)] += 1
            if name == "Tag":
                comp["tags"] = [tag for tag in comp.get("tags", []) if self.known_tag(uid, tag)]
                if not comp["tags"]:
                    continue
            if name == "Occluder" and "boundingBox" in comp:
                # The engine now takes an occluder outline as a polygon.
                left, bottom, right, top = (float(part) for part in str(comp.pop("boundingBox")).split(","))
                if (left, bottom, right, top) != (-0.5, -0.5, 0.5, 0.5):
                    comp["polygon"] = [f"{left:g},{top:g}", f"{right:g},{top:g}", f"{right:g},{bottom:g}", f"{left:g},{bottom:g}"]
            if name == "Fixtures":
                self.fixtures(comp)
            if name == "Destructible":
                self.destructible(uid, comp)
            kept.append(self.walk_textures(comp, source))
            if name == "PointLight" and "mask" in kept[-1]:
                # The engine takes light masks as prototypes, not texture paths.
                path = kept[-1].pop("mask")
                kept[-1]["lightMask"] = self.config["light_masks"].get(path)
                if kept[-1]["lightMask"] is None:
                    self.problems.append(f"{uid}: light mask {path} has no light_masks entry")
        damageable = next((comp for comp in kept if comp["type"] == "Damageable"), None)
        if fold:
            if damageable is None:
                damageable = {"type": "Damageable"}
                kept.append(damageable)
            for key, value in fold.items():
                damageable.setdefault(key, value)
        for field in ("damageContainer", "damageModifierSet") if damageable else ():
            if damageable.get(field) in ("null", ""):
                del damageable[field]
            if field in damageable:
                damageable[field] = rules["rename_values"][field].get(damageable[field], damageable[field])
                if damageable[field] not in self.ids[field]:
                    self.problems.append(f"{uid}: {field} {damageable[field]} is unknown to Wolfgate and has no rename")
        return kept

    def known_tag(self, uid: str, tag: str) -> bool:
        if tag in self.ids["Tag"]:
            return True
        self.dropped[(f"tag {tag}", "no such tag")] += 1
        return False

    def fixtures(self, comp: dict) -> None:
        gone = self.config["drop_list_values"]
        for fixture in (comp.get("fixtures") or {}).values():
            for field in ("mask", "layer"):
                if field in fixture:
                    for value in fixture[field]:
                        if value in gone:
                            self.dropped[(f"collision bit {value}", gone[value])] += 1
                    fixture[field] = [value for value in fixture[field] if value not in gone]
            shape = fixture.get("shape")
            if isinstance(shape, Tagged) and shape.tag == "type:PhysShapeAabb" and "bounds" in shape.value:
                # The engine rejects a box whose corners are given out of order.
                left, bottom, right, top = (float(part) for part in str(shape.value["bounds"]).split(","))
                if left > right or bottom > top:
                    left, right = sorted((left, right))
                    bottom, top = sorted((bottom, top))
                    shape.value["bounds"] = f"{left:g},{bottom:g},{right:g},{top:g}"

    def destructible(self, uid: str, comp: dict) -> None:
        """A threshold that moved the entity to a construction node spawns the broken twin and destroys it instead."""
        broken = self.config["break_into"].get(uid)
        for threshold in comp.get("thresholds") or []:
            behaviors = []
            for behavior in threshold.get("behaviors") or []:
                if isinstance(behavior, Tagged) and behavior.tag == "type:ChangeConstructionNodeBehavior":
                    if broken:
                        behaviors.append(Tagged("type:SpawnEntitiesBehavior", {"spawn": {broken: {"min": "1", "max": "1"}},
                                                                             "offset": "0"}))
                    behaviors.append(Tagged("type:DoActsBehavior", {"acts": ["Destruction"]}))
                    continue
                if isinstance(behavior, Tagged) and behavior.tag == "type:SpawnEntitiesBehavior":
                    spawn = {}
                    for proto, amount in (behavior.value.get("spawn") or {}).items():
                        proto = self.config["rename_entities"].get(proto, proto)
                        self.spawned.add((uid, proto))
                        spawn[proto] = amount
                    behavior.value["spawn"] = spawn
                behaviors.append(behavior)
            if "behaviors" in threshold:
                threshold["behaviors"] = behaviors

    def override(self, uid: str, entity: dict, name: str, fields) -> None:
        """Applies a `set` rule: a component is replaced field by field, added when missing, or removed with null."""
        components = entity.setdefault("components", [])
        index = next((i for i, comp in enumerate(components) if comp["type"] == name), None)
        if fields is None:
            if index is not None:
                del components[index]
            return
        fields = stringify(fields)
        if index is None:
            components.append({"type": name, **fields})
        else:
            components[index].update(fields)

    def remember_sprite(self, entity: dict) -> None:
        sprite = next((comp for comp in entity.get("components", []) if comp["type"] == "Sprite"), {})
        states = []
        if "state" in sprite:
            states.append((sprite.get("sprite"), sprite["state"]))
        for layer in sprite.get("layers") or []:
            if isinstance(layer, dict) and "state" in layer:
                states.append((layer.get("sprite") or sprite.get("sprite"), layer["state"]))
        parent = entity.get("parent")
        self.sprites[entity["id"]] = {"rsi": sprite.get("sprite"), "states": states,
                                      "parents": [parent] if isinstance(parent, str) else list(parent or [])}

    def inherited_rsi(self, uid: str, seen=None):
        info = self.sprites.get(uid)
        if info is None:
            return None
        if info["rsi"]:
            return info["rsi"]
        for parent in info["parents"]:
            found = self.inherited_rsi(parent)
            if found:
                return found
        return None

    def check_states(self) -> None:
        """Every state an entity names exists in the RSI that will be copied for it."""
        cache = {}
        for uid, info in self.sprites.items():
            for rsi, state in info["states"]:
                rsi = rsi or self.inherited_rsi(uid)
                if not rsi or not rsi.startswith("_WF/Streets/"):
                    continue
                dest = f"Resources/Textures/{rsi}"
                if dest not in cache:
                    origin = self.rsis.get(dest)
                    cache[dest] = None if origin is None else {
                        item["name"] for item in json.loads((origin[1] / "meta.json").read_text(encoding="utf-8-sig"))["states"]}
                if cache[dest] is not None and state not in cache[dest]:
                    self.problems.append(f"{uid}: state {state} is not in {rsi}")

    # -- tiles and decals ----------------------------------------------------------------------------------------

    def flatten(self, kind: str, source: str, folder: str) -> dict:
        """Every prototype of a kind under a source folder, with its parents' fields merged in."""
        raw = {}
        for path in sorted((Path(self.sources[source]["path"]) / folder).rglob("*.yml")):
            for doc in load(path):
                if doc.get("type") == kind:
                    raw[doc["id"]] = doc
        flat = {}

        def resolve(uid: str) -> dict:
            if uid in flat:
                return flat[uid]
            doc = raw[uid]
            merged = {}
            parents = doc.get("parent") or []
            for parent in ([parents] if isinstance(parents, str) else parents):
                if parent in raw:
                    merged.update({key: value for key, value in resolve(parent).items() if key != "abstract"})
            merged.update({key: value for key, value in doc.items() if key != "parent"})
            flat[uid] = merged
            return merged

        for uid in raw:
            resolve(uid)
        return flat

    def tiles(self, entry: dict, flat: dict, names: dict) -> None:
        source = entry["source"]
        only = set(entry.get("only") or [])
        docs = []
        for doc in load(Path(self.sources[source]["path"]) / entry["file"]):
            uid = doc.get("id")
            if doc.get("type") != "tile" or doc.get("abstract") == "true" or (only and uid not in only):
                continue
            if uid in self.ids["tile"]:
                self.notes.append(f"tile {uid} is already in Wolfgate; its copy there is kept")
                continue
            full = flat[uid]
            if "sprite" not in full:
                continue
            outdoor = full.get("weather") == "true"
            tile = {"type": "tile", "parent": "WFStreetsOutdoorTile" if outdoor else "WFStreetsIndoorTile", "id": uid}
            for field in TILE_FIELDS:
                if field in full:
                    tile[field] = full[field]
            sounds = tile.get("footstepSounds", {}).get("collection")
            if sounds == "FootstepGrass" and full.get("name") not in self.config["grass_footsteps"]:
                # RMC's planet base gives every outdoor tile grass footsteps.
                del tile["footstepSounds"]
            elif sounds and sounds not in self.ids["soundCollection"]:
                self.dropped[(f"footstep collection {sounds}", "no such collection; the base tile's is used")] += 1
                del tile["footstepSounds"]
            if tile.get("barestepSounds", {}).get("collection") not in self.ids["soundCollection"]:
                tile.pop("barestepSounds", None)
            text = self.config["tile_names"].get(full.get("name", "floor"), full.get("name", "floor"))
            tile["name"] = "tiles-wf-streets-" + re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
            names[tile["name"]] = text
            docs.append(self.walk_textures(tile, source))
        origin = f"{self.sources[source]['dir']} {entry['file']} ({self.sources[source]['licence']})"
        self.files[f"{PROTOTYPES}/{entry['out']}"] = dump(docs, HEADER.format(origin=origin))

    def decals(self, entry: dict, flat: dict) -> None:
        source = entry["source"]
        docs = []
        for doc in load(Path(self.sources[source]["path"]) / entry["file"]):
            uid = doc.get("id")
            if doc.get("type") != "decal" or doc.get("abstract") == "true":
                continue
            if uid in self.ids["decal"]:
                self.notes.append(f"decal {uid} is already in Wolfgate; its copy there is kept")
                continue
            full = flat[uid]
            decal = {"type": "decal", "id": uid}
            for field in DECAL_FIELDS:
                if field in full:
                    decal[field] = full[field]
            docs.append(self.walk_textures(decal, source))
        origin = f"{self.sources[source]['dir']} {entry['file']} ({self.sources[source]['licence']})"
        self.files[f"{PROTOTYPES}/{entry['out']}"] = dump(docs, HEADER.format(origin=origin))

    def tile_names(self, names: dict) -> None:
        """The Fluent lines of the tile names; the sources write the name itself where Wolfgate wants a key."""
        lines = [f"{key} = {text}" for key, text in sorted(names.items())]
        self.files[f"{LOCALE}/tiles.ftl"] = "\n".join(lines) + "\n"

    # -- assets --------------------------------------------------------------------------------------------------

    def copy_assets(self, check: bool) -> list:
        """Copies the RSIs and loose textures; returns the rows of the asset table."""
        rows = []
        stale = []
        for dest, (key, origin) in sorted(self.rsis.items()):
            meta = json.loads((origin / "meta.json").read_text(encoding="utf-8-sig"))
            wanted = {"meta.json": (origin / "meta.json").read_bytes()}
            if dest in self.keep:
                missing = set(self.keep[dest]) - {state["name"] for state in meta["states"]}
                if missing:
                    self.problems.append(f"{dest} is trimmed to states it lacks: {sorted(missing)}")
                meta["states"] = [state for state in meta["states"] if state["name"] in self.keep[dest]]
                wanted["meta.json"] = (json.dumps(meta, indent=4, ensure_ascii=False) + "\n").encode("utf-8")
            for state in meta["states"]:
                png = origin / f"{state['name']}.png"
                if not png.exists():
                    self.problems.append(f"{origin} lists state {state['name']} but has no PNG for it")
                    continue
                wanted[png.name] = png.read_bytes()
            masked = self.mask_lamps(dest, meta, wanted)
            folder = REPO / dest
            for name, data in wanted.items():
                target = folder / name
                if not target.exists() or not (lamp_mask.same_pixels(target.read_bytes(), data) if name in masked
                                               else target.read_bytes() == data):
                    if check:
                        stale.append(str(target.relative_to(REPO)))
                    else:
                        target.parent.mkdir(parents=True, exist_ok=True)
                        target.write_bytes(data)
            if folder.exists() and not check:
                for extra in folder.iterdir():
                    if extra.name not in wanted:
                        extra.unlink()
            rows.append((dest, self.sources[key]["dir"], str(origin.relative_to(self.sources[key]["path"])).replace("\\", "/"),
                         meta.get("license", "?"), " ".join(str(meta.get("copyright", "?")).split())))
        attributed = defaultdict(list)
        for dest, (key, origin) in sorted(self.loose.items()):
            target = REPO / dest
            data = origin.read_bytes()
            if not target.exists() or target.read_bytes() != data:
                if check:
                    stale.append(dest)
                else:
                    target.parent.mkdir(parents=True, exist_ok=True)
                    target.write_bytes(data)
            relative = str(origin.relative_to(self.sources[key]["path"])).replace("\\", "/")
            attributed[key].append((dest, relative))
            rows.append((dest, self.sources[key]["dir"], relative, self.config["loose_licence"], self.config["loose_copyright"]))
        self.attributions(attributed)
        if stale:
            self.problems.append(f"{len(stale)} texture files differ from the sources, first {stale[0]}")
        return rows

    def mask_lamps(self, dest: str, meta: dict, wanted: dict) -> set:
        """Cuts the lit states port.yml names down to their lamps in `wanted`; returns the PNG names it changed."""
        pairs = self.config.get("lamp_masks", {}).get(dest.removeprefix(TEXTURES + "/"))
        if not pairs:
            return set()
        states = {state["name"]: state for state in meta["states"]}
        cell = (meta["size"]["x"], meta["size"]["y"])
        masked = set()
        for unlit, lit in pairs:
            state = states[lit]
            frame_count = len(state["delays"][0]) if state.get("delays") else 1
            wanted[f"{lit}.png"] = lamp_mask.mask(wanted[f"{unlit}.png"], wanted[f"{lit}.png"], cell,
                                                  state.get("directions", 1), frame_count)
            masked.add(f"{lit}.png")
        wanted["meta.json"] = lamp_mask.noted_meta(wanted["meta.json"])
        meta["copyright"] = json.loads(wanted["meta.json"].decode("utf-8"))["copyright"]
        return masked

    def attributions(self, attributed: dict) -> None:
        """attributions.yml beside the loose textures, in the form the Vehicles port uses."""
        root = f"{TEXTURES}/"
        lines = ["# Tile textures and light masks have no per-file record upstream; the licence is the source's stated default."]
        for key, items in sorted(attributed.items()):
            lines.append("- files:")
            lines.extend(f"  - {json.dumps(dest[len(root):])}" for dest, _ in items)
            lines.append(f"  license: {json.dumps(self.config['loose_licence'])}")
            lines.append(f"  copyright: {json.dumps(self.config['loose_copyright'])}")
            lines.append(f"  source: {json.dumps(self.config['loose_source'][key])}")
        self.files[f"{TEXTURES}/attributions.yml"] = "\n".join(lines) + "\n"

    def asset_table(self, rows: list) -> None:
        lines = ["# Streets assets", "",
                 "Every texture of the Streets module, where it came from and under what terms. Generated by",
                 "`Tools/_WF/Streets/port_streets.py`; the licence and copyright are each RSI's own `meta.json`.", "",
                 f"Sources: RMC-14 at `{self.sources['rmc']['commit'][:10]}`, Colonial Marines Universe at "
                 f"`{self.sources['cmu']['commit'][:10]}`.", "",
                 "| Wolfgate path | From | Source path | Licence | Copyright |", "|---|---|---|---|---|"]
        for dest, repo, origin, licence, copyright_text in rows:
            lines.append(f"| `{dest[len('Resources/Textures/'):]}` | {repo} | `{origin}` | {licence} | "
                         f"{copyright_text.replace('|', '/')} |")
        self.files[DOC] = "\n".join(lines) + "\n"


def clone(value):
    if isinstance(value, Tagged):
        return Tagged(value.tag, clone(value.value))
    if isinstance(value, dict):
        return {key: clone(item) for key, item in value.items()}
    if isinstance(value, list):
        return [clone(item) for item in value]
    return value


def stringify(value):
    """YAML rule values as the strings the emitter writes."""
    if isinstance(value, dict):
        if set(value) == {"!tag", "value"}:
            return Tagged(value["!tag"], stringify(value["value"]))
        return {str(key): stringify(item) for key, item in value.items()}
    if isinstance(value, list):
        return [stringify(item) for item in value]
    if isinstance(value, bool):
        return "true" if value else "false"
    return str(value)


def write(files: dict, check: bool) -> list:
    """Writes the generated text files, with the line endings Windows checkouts keep; returns the stale ones on a check."""
    stale = []
    for relative, text in sorted(files.items()):
        path = REPO / relative
        if check:
            if not path.exists() or path.read_text(encoding="utf-8").replace("\r\n", "\n") != text:
                stale.append(relative)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\r\n" if sys.platform == "win32" else "\n") as handle:
            handle.write(text)
    return stale


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail when a generated file is stale")
    parser.add_argument("--report", action="store_true", help="print what was dropped and write nothing")
    args = parser.parse_args(argv)

    config = yaml.safe_load(CONFIG.read_text(encoding="utf-8"))
    sources = source_paths.resolve(yaml.safe_load(SOURCES.read_text(encoding="utf-8"))["sources"], REPO)
    port = Port(config, sources, scan_wolfgate())

    for entry in config["entities"]:
        port.entities(entry)
    port.finish_entities()
    for extra in config.get("extra_rsis") or []:
        mapped = port.texture(extra["rsi"], "rmc")
        if "keep" in extra:
            port.keep[f"Resources/Textures/{mapped}"] = extra["keep"]
    names: dict = {}
    for entry in config["tiles"]:
        port.tiles(entry, port.flatten("tile", entry["source"], entry["root"]), names)
    for entry in config["decals"]:
        port.decals(entry, port.flatten("decal", entry["source"], entry["root"]))
    port.tile_names(names)
    port.check_states()

    quiet = args.check or args.report
    rows = port.copy_assets(check=quiet)
    port.asset_table(rows)

    if args.report:
        for (what, reason), count in sorted(port.dropped.items()):
            print(f"dropped {count:4d}  {what}: {reason}")
        for note in port.notes:
            print("note:", note)
    for problem in port.problems:
        print("PROBLEM:", problem, file=sys.stderr)
    if args.report:
        return 1 if port.problems else 0

    stale = write(port.files, args.check)
    if args.check and stale:
        print("Generated files differ:", ", ".join(stale[:8]), file=sys.stderr)
        return 1
    print(f"{'Checked' if args.check else 'Wrote'} {len(port.ported)} entities, {len(port.rsis)} RSIs, "
          f"{len(port.loose)} loose textures, {len(port.files)} files.")
    return 1 if port.problems else 0


if __name__ == "__main__":
    sys.exit(main())
