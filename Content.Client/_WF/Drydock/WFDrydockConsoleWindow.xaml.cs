/// <summary>
/// Drydock console: a live berth plot beside the hull survey, repair and refit keys, and on a dockmaster's booking
/// window, the booking.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class WFDrydockConsoleWindow : FancyWindow
{
    /// <summary>Width of the right-hand instrument column.</summary>
    private const float ColumnWidth = 370;

    /// <summary>Crane power ratio below which the cranes read as short of power.</summary>
    private const float FullPower = 0.95f;

    /// <summary>Height of the supplies list before it scrolls.</summary>
    private const float SupplyListHeight = 150;

    /// <summary>Side of a supply row's icon.</summary>
    private const float SupplyIconSize = 24;

    [Dependency] private IPrototypeManager _prototypeManager = default!;
    [Dependency] private IEntityManager _entMan = default!;

