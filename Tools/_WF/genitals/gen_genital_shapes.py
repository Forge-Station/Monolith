# Hand-written shapes (shapes_extra.yml) whose keys live in the generated locale file:
# (slot, id suffix, display name, examine word or None)
EXTRA_LOC = [
    ("Vagina", "Slit", "Slit (cloacal)", "slit-shaped"),
]


class Rsi:
    """State names and frame delays of one RSI."""

    def __init__(self, name):
        self.name = name
        path = os.path.join(TEXTURES, *RSI_DIR.split("/"), name, "meta.json")
        with open(path, encoding="utf-8-sig") as f:
            meta = json.load(f)
        self.delays = {s["name"]: s.get("delays") for s in meta["states"]}
        self.lower = {}
        for state in self.delays:
            self.lower.setdefault(state.lower(), state)

    @property
    def sprite(self):
        return f"{RSI_DIR}/{self.name}"

    def find(self, state):
        """The real state name (case-insensitive fallback for upstream typos), or None."""
        if state in self.delays:
            return state
        return self.lower.get(state.lower())

    def flickers(self, state):
        delays = self.delays.get(state)
        return bool(delays) and all(d <= FLICKER_DELAY for row in delays for d in row)


class Shape:
    """Collects one shape's lists while scanning the art."""

    def __init__(self, slot, suffix, rsi, template, legacy, sort, region="Groin"):
        self.slot = slot
        self.suffix = suffix
        self.rsi = rsi
        self.template = template
        self.legacy = legacy
        self.sort = sort
        self.region = region
        self.examine = False
        self.size_tokens = None
        self.sizes, self.aroused, self.behind, self.behind_aroused = [], [], [], []
        self.overrides = {}
        self.sheaths = None

    @property
    def id(self):
        return f"GenitalShape{self.slot}{self.suffix}"

    @property
    def loc(self):
        return loc_key(self.slot, self.suffix)

    def probe(self, target, step, formatted, behind=False):
        """Adds step to target if the state exists (and does not flicker when BEHIND); records case fixes."""
        real = self.rsi.find(formatted)
        if real is None or (behind and self.rsi.flickers(real)):
            return
        if real != formatted:
            self.overrides[formatted] = real
        target.append(step)

    def finish(self):
        # Without BEHIND art the template names FRONT directly.
        if not self.behind and not self.behind_aroused:
            self.template = self.template.replace("{layer}", "FRONT")

    def yaml(self):
        lines = [
            "- type: genitalShape",
            f"  id: {self.id}",
            f"  slot: {self.slot}",
            f"  name: {self.loc}",
        ]
        if self.examine:
            lines.append(f"  examineName: {self.loc}-examine")
        lines += [
            f"  sprite: {self.rsi.sprite}",
            f"  state: \"{self.template}\"",
        ]
        if self.size_tokens:
            lines.append(f"  sizeTokens: {flow(self.size_tokens)}")
        lines += [
            f"  sizes: {flow(self.sizes)}",
            f"  arousedSizes: {flow(self.aroused)}",
            f"  behindSizes: {flow(self.behind)}",
            f"  behindArousedSizes: {flow(self.behind_aroused)}",
        ]
        if self.overrides:
            lines.append("  stateOverrides:")
            for key in sorted(self.overrides):
                lines.append(f"    {key}: {self.overrides[key]}")
        if self.sheaths is not None:
            lines.append(f"  allowedSheaths: {flow(self.sheaths)}")
        lines += [
            f"  region: {self.region}",
            f"  sortOrder: {self.sort}",
            f"  legacyToken: {self.legacy}",
        ]
        return lines


def loc_key(slot, suffix):
    return f"wf-genitals-shape-{slot.lower()}-{suffix.lower()}"


def flow(items):
    return "[" + ", ".join(str(i) for i in items) + "]"


def penis_shapes(rsi):
    shapes, loc = [], []
    for suffix, token, name, examine, sheaths, sort in PENIS:
        s = Shape("Penis", suffix, rsi, f"penis_{token}_{{size}}_{{aroused}}_{{layer}}", token, sort)
        for n in STEPS:
            s.probe(s.sizes, n, f"penis_{token}_{n}_0_FRONT")
            s.probe(s.aroused, n, f"penis_{token}_{n}_1_FRONT")
            s.probe(s.behind, n, f"penis_{token}_{n}_0_BEHIND", behind=True)
            s.probe(s.behind_aroused, n, f"penis_{token}_{n}_1_BEHIND", behind=True)
        s.sheaths, s.examine = sheaths, examine is not None
        s.finish()
        shapes.append(s)
        loc.append((s.loc, name, examine))
    return shapes, loc


def testicle_shapes(rsi):
    shapes, loc = [], []
    for suffix, token, name, examine, sort in TESTICLES:
        s = Shape("Testicles", suffix, rsi, f"testicles_{token}_{{size}}_0_{{layer}}", token, sort)
        for n in STEPS:
            s.probe(s.sizes, n, f"testicles_{token}_{n}_0_FRONT")
            s.probe(s.behind, n, f"testicles_{token}_{n}_0_BEHIND", behind=True)
        s.examine = examine is not None
        s.finish()
