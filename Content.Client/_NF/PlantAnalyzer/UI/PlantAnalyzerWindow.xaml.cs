namespace Content.Client._NF.PlantAnalyzer.UI;

[GenerateTypedNameReferences]
public sealed partial class PlantAnalyzerWindow : BaseWindow
{
    [Dependency] private readonly IResourceCache _resCache = default!;

    private readonly BotanyUiStyles _styles;
    private readonly BotanyChipButton _printLabel;
    private PlantAnalyzerScannedSeedPlantInformation? _scan;
    private AnalyzerSection _section = AnalyzerSection.Overview;

    private enum AnalyzerSection
    {
        Overview,
        Tray,
        Genetics,
        Tolerances,
        Mutations
    }

    public event Action? OnPrintLabel;

    public PlantAnalyzerWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _styles = new BotanyUiStyles(_resCache);

        TitleLabel.Text = Loc.GetString("plant-analyzer-interface-title");
        DetailHeader.Text = Loc.GetString("plant-analyzer-detail-header");
        ListHeader.Text = Loc.GetString("plant-analyzer-list-header");
        OsLabel.Text = Loc.GetString("plant-analyzer-os");
        PlantNameLabel.Text = Loc.GetString("plant-analyzer-window-no-seed-information-text");
        StatusLabel.Text = string.Empty;

        CloseButton.OnPressed += _ => Close();
        _printLabel = _styles.Action(Loc.GetString("plant-analyzer-print-label"));
        _printLabel.Margin = new Thickness(0, 0, 0, 0);
        _printLabel.OnPressed += _ => OnPrintLabel?.Invoke();
        _printLabel.Disabled = true;
        PrintLabelHost.AddChild(_printLabel);
        ApplyChrome();
        RebuildSectionList();
        ShowNoData();
    }

    protected override DragMode GetDragModeFor(Vector2 relativeMousePos) => DragMode.Move;

    public void Populate(PlantAnalyzerScannedSeedPlantInformation msg)
    {
        if (string.IsNullOrEmpty(msg.SeedName) && !msg.IsTray)
        {
            _scan = null;
            PlantNameLabel.Text = Loc.GetString("plant-analyzer-window-no-seed-information-text");
            StatusLabel.Text = string.Empty;
            _printLabel.Disabled = true;
            RebuildSectionList();
            ShowNoData();
            return;
        }

        _scan = msg;
        _printLabel.Disabled = msg.IsTray || msg.TargetEntity == null;
        var seedName = Loc.GetString(string.IsNullOrEmpty(msg.SeedName) ? "plant-analyzer-unknown-plant" : msg.SeedName);
        PlantNameLabel.Text = msg.IsTray
            ? Loc.GetString("plant-analyzer-window-label-name-scanned-plant", ("seedName", seedName))
            : Loc.GetString("plant-analyzer-window-label-name-scanned-seed", ("seedName", seedName));

        if (msg.IsTray)
        {
            var status = msg.Dead
                ? Loc.GetString("plant-analyzer-tray-dead")
                : msg.HarvestReady
                    ? Loc.GetString("plant-analyzer-tray-harvest")
                    : Loc.GetString("plant-analyzer-tray-growing");
            StatusLabel.Text = status;
            StatusLabel.FontColorOverride = msg.Dead
                ? BotanyUiTheme.Danger
                : msg.HarvestReady
                    ? BotanyUiTheme.Harvest
                    : BotanyUiTheme.Ok;
        }
        else
        {
            StatusLabel.Text = Loc.GetString("plant-analyzer-window-tab-basics");
            StatusLabel.FontColorOverride = BotanyUiTheme.Text;
        }

        if (_section == AnalyzerSection.Tray && !msg.IsTray)
            _section = AnalyzerSection.Overview;

        RebuildSectionList();
        ShowSection();
    }

    private void RebuildSectionList()
    {
        ListContainer.DisposeAllChildren();

        AddSectionButton(AnalyzerSection.Overview, Loc.GetString("plant-analyzer-section-overview"), Loc.GetString("plant-analyzer-section-overview-sub"));
        if (_scan?.IsTray == true)
            AddSectionButton(AnalyzerSection.Tray, Loc.GetString("plant-analyzer-section-tray"), Loc.GetString("plant-analyzer-section-tray-sub"));
        AddSectionButton(AnalyzerSection.Genetics, Loc.GetString("plant-analyzer-section-genetics"), Loc.GetString("plant-analyzer-section-genetics-sub"));
        AddSectionButton(AnalyzerSection.Tolerances, Loc.GetString("plant-analyzer-section-tolerances"), Loc.GetString("plant-analyzer-section-tolerances-sub"));
        AddSectionButton(AnalyzerSection.Mutations, Loc.GetString("plant-analyzer-section-mutations"), Loc.GetString("plant-analyzer-section-mutations-sub"));
    }

    private void AddSectionButton(AnalyzerSection section, string title, string subtitle)
    {
        var button = new BotanyListButton(_styles) { Key = section };
        button.SetContent(title, subtitle);
        button.ApplySelected(_section == section);
        button.OnPressed += _ =>
        {
            _section = section;
            RebuildSectionList();
            ShowSection();
        };
        ListContainer.AddChild(button);
    }

    private void ShowSection()
    {
        DetailContainer.DisposeAllChildren();

        if (_scan == null)
        {
            ShowNoData();
            return;
        }

        switch (_section)
        {
            case AnalyzerSection.Overview:
                ShowOverview(_scan);
                break;
            case AnalyzerSection.Tray:
                ShowTray(_scan);
                break;
            case AnalyzerSection.Genetics:
                ShowGenetics(_scan);
                break;
            case AnalyzerSection.Tolerances:
                ShowTolerances(_scan);
                break;
            case AnalyzerSection.Mutations:
                ShowMutations(_scan);
                break;
        }
    }

    private void ShowOverview(PlantAnalyzerScannedSeedPlantInformation msg)
    {
        DetailHeader.Text = Loc.GetString("plant-analyzer-section-overview");
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("plant-analyzer-field-yield"), $"{msg.SeedYield:D0}"));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("plant-analyzer-field-potency"), $"{msg.SeedPotency:F0}%"));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("plant-analyzer-field-harvest"), Loc.GetString($"plant-analyzer-harvest-{msg.HarvestType}")));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("plant-analyzer-field-endurance"), $"{msg.Endurance:F0}"));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("plant-analyzer-field-lifespan"), $"{msg.Lifespan:F1}"));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("plant-analyzer-field-maturation"), $"{msg.Maturation:F1}"));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("plant-analyzer-field-production"), $"{msg.Production:F1}"));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("plant-analyzer-field-stages"), $"{msg.GrowthStages:D0}"));
    }

    private void ShowTray(PlantAnalyzerScannedSeedPlantInformation msg)
    {
        DetailHeader.Text = Loc.GetString("plant-analyzer-section-tray");
        if (!msg.IsTray)
        {
            DetailContainer.AddChild(_styles.Sub(Loc.GetString("plant-analyzer-section-tray-seed-only")));
            return;
        }

        var status = msg.Dead
            ? Loc.GetString("plant-analyzer-tray-dead")
            : msg.HarvestReady
                ? Loc.GetString("plant-analyzer-tray-harvest")
                : Loc.GetString("plant-analyzer-tray-growing");
        var statusColor = msg.Dead ? BotanyUiTheme.Danger : msg.HarvestReady ? BotanyUiTheme.Harvest : BotanyUiTheme.Ok;

        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("hydroponics-console-field-status"), status, statusColor));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("hydroponics-console-field-health"), $"{msg.TrayHealth:0} / {msg.TrayEndurance:0}", HealthColor(msg.TrayHealth, msg.TrayEndurance)));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("hydroponics-console-field-age"), msg.Age.ToString()));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("hydroponics-console-field-water"), $"{msg.WaterLevel:0}", msg.WaterLevel <= 15 ? BotanyUiTheme.Warning : BotanyUiTheme.Text));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("hydroponics-console-field-nutrition"), $"{msg.NutritionLevel:0}", msg.NutritionLevel <= 8 ? BotanyUiTheme.Warning : BotanyUiTheme.Text));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("hydroponics-console-field-toxins"), $"{msg.Toxins:0}", msg.Toxins >= 40 ? BotanyUiTheme.Danger : BotanyUiTheme.Text));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("hydroponics-console-field-weeds"), $"{msg.WeedLevel:0.#}", msg.WeedLevel >= 5 ? BotanyUiTheme.Warning : BotanyUiTheme.Text));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("hydroponics-console-field-pests"), $"{msg.PestLevel:0.#}", msg.PestLevel >= 5 ? BotanyUiTheme.Warning : BotanyUiTheme.Text));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("hydroponics-console-field-light-mode"),
            Loc.GetString($"plant-holder-light-{msg.LightMode.ToString().ToLowerInvariant()}"),
            msg.ImproperLight ? BotanyUiTheme.Warning : BotanyUiTheme.Text));

        DetailContainer.AddChild(_styles.Section(Loc.GetString("hydroponics-console-section-warnings")));
        var extra = new List<string>();
        if (msg.ImproperHeat)
            extra.Add(Loc.GetString("plant-analyzer-warning-heat"));
        if (msg.ImproperPressure)
            extra.Add(Loc.GetString("plant-analyzer-warning-pressure"));
        if (msg.ImproperLight)
            extra.Add(Loc.GetString("plant-analyzer-warning-light"));
        if (msg.MissingGas)
            extra.Add(Loc.GetString("plant-analyzer-warning-gas"));

        DetailContainer.AddChild(extra.Count == 0
            ? _styles.Body(Loc.GetString("plant-analyzer-extra-none"), 12, BotanyUiTheme.Ok)
            : _styles.Body(string.Join("\n", extra), 12, BotanyUiTheme.Warning));
    }

    private void ShowGenetics(PlantAnalyzerScannedSeedPlantInformation msg)
    {
        DetailHeader.Text = Loc.GetString("plant-analyzer-section-genetics");
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("plant-analyzer-field-consume"), FormatGases(msg.ConsumeGases)));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("plant-analyzer-field-exude"), FormatGases(msg.ExudeGases)));

        DetailContainer.AddChild(_styles.Section(Loc.GetString("hydroponics-console-field-chems")));
        if (msg.SeedChem == null || msg.SeedChem.Length == 0)
        {
            DetailContainer.AddChild(_styles.Body("—", 12, BotanyUiTheme.Empty));
        }
        else
        {
            foreach (var chem in msg.SeedChem)
                DetailContainer.AddChild(_styles.Body("·  " + chem, 12));
        }
    }

    private void ShowTolerances(PlantAnalyzerScannedSeedPlantInformation msg)
    {
        DetailHeader.Text = Loc.GetString("plant-analyzer-section-tolerances");
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("plant-analyzer-field-nutrient"), $"{msg.NutrientConsumption:F2}"));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("plant-analyzer-field-water-use"), $"{msg.WaterConsumption:F2}"));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("plant-analyzer-field-ideal-heat"), $"{msg.IdealHeat:F0} K"));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("plant-analyzer-field-heat-tol"), $"±{msg.HeatTolerance:F1} K"));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("plant-analyzer-field-ideal-light"), $"{msg.IdealLight:F1} cd"));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("plant-analyzer-field-light-tol"), $"±{msg.LightTolerance:F1} cd"));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("plant-analyzer-field-toxin-tol"), $"{msg.ToxinsTolerance:F1}"));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("plant-analyzer-field-low-p"), $"{msg.LowPressureTolerance:F1} kPa"));
        DetailContainer.AddChild(_styles.KeyValue(Loc.GetString("plant-analyzer-field-high-p"), $"{msg.HighPressureTolerance:F1} kPa"));
