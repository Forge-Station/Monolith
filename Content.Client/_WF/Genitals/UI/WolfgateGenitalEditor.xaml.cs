    /// <summary>The species' typical anatomy for one sex; null without a preset.</summary>
    private GenitalProfile? PresetEntry(bool male)
    {
        var preset = GenitalColorDefaults.FindPreset(_species, _proto);
        if (preset == null)
            return null;

        return male ? preset.Male : preset.Female;
    }

    /// <summary>The typical anatomy for one sex, coloured by the default colour policy; empty without a preset.</summary>
    private GenitalProfile Seed(bool male)
    {
        return PresetEntry(male) is { } entry
            ? GenitalColorDefaults.Apply(entry, _species, _proto)
            : GenitalProfile.Empty;
    }

    /// <summary>Applies a typical anatomy entry (null clears), asking first when anything is configured.</summary>
    private void RequestPreset(GenitalProfile? entry)
    {
        if (_profile.IsEmpty)
        {
            ApplyPreset(entry);
            return;
        }

        _pendingPreset = () => ApplyPreset(entry);
        PresetConfirm.Visible = true;
    }

    /// <summary>Replaces every organ with the entry's, coloured by the default colour policy. The reveal mode is kept.</summary>
    private void ApplyPreset(GenitalProfile? entry)
    {
        HidePresetConfirm();
        var organs = entry == null ? null : GenitalColorDefaults.Apply(entry, _species, _proto);
        var result = _profile
            .WithPenis(organs?.Penis)
            .WithTesticles(organs?.Testicles)
            .WithVagina(organs?.Vagina)
            .WithWomb(organs?.Womb ?? false)
            .WithBreasts(organs?.Breasts);

        _sheathChoice = result.Penis?.Sheath ?? SheathType.None;
        Commit(result);
    }

    private void HidePresetConfirm()
    {
        _pendingPreset = null;
        PresetConfirm.Visible = false;
    }

