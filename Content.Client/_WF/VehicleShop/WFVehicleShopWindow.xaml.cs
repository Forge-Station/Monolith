using System.Linq;
using System.Numerics;
using Content.Client.UserInterface.Controls;
using Content.Shared._NF.Bank;
using Content.Shared._WF.VehicleShop;
using Content.Shared.Item;
using Content.Shared.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._WF.VehicleShop;

/// <summary>A vehicle purchase terminal: each vehicle for sale with a picture and its price, and the pad's state with the repair and sale buttons.</summary>
[GenerateTypedNameReferences]
public sealed partial class WFVehicleShopWindow : FancyWindow
{
    [Dependency] private IPrototypeManager _proto = default!;

    public event Action<int>? OnBuy;
    public event Action? OnSell;
    public event Action? OnRepair;

    private readonly List<(WFVehicleListing Listing, bool Carried, Button Buy)> _rows = new();

    public WFVehicleShopWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        SellButton.OnPressed += _ => OnSell?.Invoke();
        RepairButton.OnPressed += _ => OnRepair?.Invoke();
    }

    public void UpdateState(WFVehicleShopState state)
    {
        if (!_rows.Select(row => (row.Listing.Vehicle, row.Listing.Price))
                .SequenceEqual(state.Listings.Select(listing => (listing.Vehicle, listing.Price))))
            BuildRows(state.Listings);

        BalanceLabel.Text = state.Balance is { } balance
            ? Loc.GetString("wf-vehicle-shop-balance", ("balance", BankSystemExtensions.ToSpesoString(balance)))
            : Loc.GetString("wf-vehicle-shop-no-account");

        foreach (var (listing, carried, buy) in _rows)
        {
            buy.Disabled = !carried && state.Pad != WFVehicleShopPad.Clear
                           || listing.Licence && !state.Licensed
                           || state.Balance is not { } funds
                           || funds < listing.Price;
        }

        // A counter that sells nothing but carried goods has no pad to show.
        PadPanel.Visible = _rows.Any(row => !row.Carried);

        PadLabel.Text = state.Pad switch
        {
            WFVehicleShopPad.Missing => Loc.GetString("wf-vehicle-shop-pad-missing"),
            WFVehicleShopPad.Blocked => Loc.GetString("wf-vehicle-shop-pad-blocked", ("thing", state.PadVehicle ?? string.Empty)),
            WFVehicleShopPad.Vehicle => Loc.GetString(state.Occupied ? "wf-vehicle-shop-pad-occupied" : "wf-vehicle-shop-pad-vehicle",
                ("vehicle", state.PadVehicle ?? string.Empty)),
            _ => Loc.GetString("wf-vehicle-shop-pad-clear"),
        };

        RepairButton.Visible = state.Pad == WFVehicleShopPad.Vehicle && state.RepairPrice > 0;
        RepairButton.Disabled = state.Balance is not { } repairFunds || repairFunds < state.RepairPrice;
        RepairButton.Text = Loc.GetString("wf-vehicle-shop-repair", ("price", BankSystemExtensions.ToSpesoString(state.RepairPrice)));

        SellButton.Visible = state.Pad == WFVehicleShopPad.Vehicle;
        SellButton.Disabled = state.Occupied;
        SellButton.Text = Loc.GetString("wf-vehicle-shop-sell", ("price", BankSystemExtensions.ToSpesoString(state.SellPrice)));
    }

    private void BuildRows(List<WFVehicleListing> listings)
    {
        Listings.RemoveAllChildren();
        _rows.Clear();

        for (var i = 0; i < listings.Count; i++)
        {
            var listing = listings[i];
            var index = i;

            var row = new PanelContainer { StyleClasses = { "AngleRect" }, HorizontalExpand = true };
            var contents = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                Margin = new Thickness(8, 6),
                SeparationOverride = 10,
            };

            var view = new EntityPrototypeView
            {
                SetSize = new Vector2(96, 96),
                Stretch = SpriteView.StretchMode.Fit,
                VerticalAlignment = VAlignment.Center,
            };
            view.SetPrototype(listing.Vehicle);
            contents.AddChild(view);

            var text = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                HorizontalExpand = true,
                VerticalAlignment = VAlignment.Center,
            };
            var proto = _proto.Index<EntityPrototype>(listing.Vehicle);
            text.AddChild(new Label { Text = proto.Name, StyleClasses = { "LabelHeading" }, ClipText = true });
            text.AddChild(new Label { Text = BankSystemExtensions.ToSpesoString(listing.Price) });
            if (listing.Licence)
                text.AddChild(new Label { Text = Loc.GetString("wf-vehicle-shop-licence-required"), StyleClasses = { "LabelSubText" } });
            contents.AddChild(text);

            var buy = new Button
            {
                Text = Loc.GetString("wf-vehicle-shop-buy"),
                VerticalAlignment = VAlignment.Center,
                MinWidth = 80,
            };
            buy.OnPressed += _ => OnBuy?.Invoke(index);
            contents.AddChild(buy);

            row.AddChild(contents);
            Listings.AddChild(row);
            _rows.Add((listing, proto.HasComponent<ItemComponent>(), buy));
        }
    }
}
