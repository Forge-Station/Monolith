# YAML in and out. Every scalar is kept as the text the source wrote, so `state: on` stays a state name.

class Tagged:
    """A value with a local tag, such as !type:PhysShapeAabb."""

    def __init__(self, tag: str, value):
        self.tag = tag
        self.value = value


class Loader(yaml.BaseLoader):
    pass


def _tagged(loader, suffix, node):
    if isinstance(node, yaml.MappingNode):
        return Tagged(suffix, loader.construct_mapping(node, deep=True))
    if isinstance(node, yaml.SequenceNode):
        return Tagged(suffix, loader.construct_sequence(node, deep=True))
    return Tagged(suffix, loader.construct_scalar(node))


Loader.add_multi_constructor("!", _tagged)


def load(path: Path) -> list:
    return yaml.load(path.read_text(encoding="utf-8-sig"), Loader=Loader) or []


def scalar(text: str) -> str:
    """The scalar as plain text where YAML allows it, double-quoted otherwise."""
    if text == "" or text != text.strip() or "\n" in text or text[0] in "!&*?|>'\"%@`#{}[]," or text.startswith("- ") \
            or text == "-" or ": " in text or text.endswith(":") or " #" in text or "," in text:
        return json.dumps(text, ensure_ascii=False)
    return text


def _is_scalar(value) -> bool:
    return isinstance(value, str)


def emit_map(mapping: dict, indent: str, out: list) -> None:
    for key, value in mapping.items():
        emit_entry(f"{indent}{scalar(key)}:", value, indent, out)


def emit_entry(lead: str, value, indent: str, out: list) -> None:
    """One `key:` or `-` line and whatever hangs under it."""
    if isinstance(value, Tagged):
        inner = value.value
        if isinstance(inner, dict) and inner:
            if lead.endswith("-"):
                out.append(f"{lead} !{value.tag}")
            else:
                out.append(lead)
                out.append(f"{indent}  !{value.tag}")
            emit_map(inner, indent + "  ", out)
        elif isinstance(inner, list) and inner:
            out.append(f"{lead} !{value.tag}")
            emit_list(inner, indent + "  ", out)
        else:
            tail = f" {scalar(inner)}" if _is_scalar(inner) and inner else ""
            out.append(f"{lead} !{value.tag}{tail}")
    elif isinstance(value, dict):
        if not value:
            out.append(f"{lead} {{}}")
        elif lead.endswith("-"):
            start = len(out)
            emit_map(value, indent + "  ", out)
            out[start] = f"{lead} {out[start].lstrip()}"
        else:
            out.append(lead)
            emit_map(value, indent + "  ", out)
    elif isinstance(value, list):
        if not value:
            out.append(f"{lead} []")
        elif all(_is_scalar(item) for item in value) and len(value) <= 6 and sum(len(item) for item in value) < 60 \
                and not lead.endswith("-"):
            out.append(f"{lead} [ {', '.join(scalar(item) for item in value)} ]")
        elif lead.endswith("-"):
            out.append(lead)
            emit_list(value, indent + "  ", out)
        else:
            out.append(lead)
            emit_list(value, indent, out)
    else:
        out.append(f"{lead} {scalar(value)}")


def emit_list(items: list, indent: str, out: list) -> None:
    for item in items:
        emit_entry(f"{indent}-", item, indent, out)


def dump(docs: list, header: str) -> str:
    out = [header, ""]
    for doc in docs:
        emit_entry("-", doc, "", out)
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


