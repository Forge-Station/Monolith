            Loc.GetString("sec-apartment-ui-unassigned-dead"),
            dead,
            squads,
            _showDeadUnassigned,
            expanded => _showDeadUnassigned = expanded);

        if (UsesRecoloredTheme)
            RecolorControl(UnassignedContainer);
    }

