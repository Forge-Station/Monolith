using System.Linq;
using Content.Client.Message;
using Content.Client.UserInterface.Controls;
using Content.Shared._WF.Xenobiology.Bounties;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;

namespace Content.Client._WF.Xenobiology.Bounties;

/// <summary>
/// Opens the bounty console window and sends its buttons.
/// </summary>
public sealed class XenobiologyBountyConsoleBoundUserInterface(EntityUid owner, Enum uiKey) : BoundUserInterface(owner, uiKey)
{
    [ViewVariables]
    private XenobiologyBountyMenu? _menu;

    protected override void Open()
    {
        base.Open();
        _menu = this.CreateWindow<XenobiologyBountyMenu>();
        _menu.OnFulfillButtonPressed += id => SendMessage(new XenobiologyBountyFulfillMessage(id));
        _menu.OnSkipButtonPressed += id => SendMessage(new XenobiologyBountySkipMessage(id));
    }

    protected override void UpdateState(BoundUserInterfaceState state)
    {
        base.UpdateState(state);
        if (state is XenobiologyBountyConsoleState bounty)
            _menu?.UpdateEntries(bounty.Bounties, bounty.History, bounty.UntilNextSkip, bounty.UntilNextRefresh);
    }
}
