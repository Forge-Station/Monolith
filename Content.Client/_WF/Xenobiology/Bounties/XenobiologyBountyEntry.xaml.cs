using System.Linq;
using Content.Client.Message;
using Content.Client.UserInterface.Controls;
using Content.Shared._WF.Xenobiology.Bounties;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;

namespace Content.Client._WF.Xenobiology.Bounties;

/// <summary>
/// One open bounty with its fulfil and skip buttons.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class XenobiologyBountyEntry : BoxContainer
{
    [Dependency] private IPrototypeManager _proto = default!;

    public event Action? OnFulfillButtonPressed;
    public event Action? OnSkipButtonPressed;

    private TimeSpan _untilNextSkip;

    public XenobiologyBountyEntry(XenobiologyBountyData bounty, TimeSpan untilNextSkip)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _untilNextSkip = untilNextSkip;

        FulfillButton.OnPressed += _ => OnFulfillButtonPressed?.Invoke();
        SkipButton.OnPressed += _ => OnSkipButtonPressed?.Invoke();
        IdLabel.SetMarkup(Loc.GetString("xenobiology-bounty-id-label", ("id", bounty.Id)));

        if (!_proto.TryIndex(bounty.Bounty, out var proto))
            return;

        ManifestLabel.SetMarkup(XenobiologyBountyMenu.Manifest(proto));
        RewardLabel.SetMarkup(Loc.GetString("xenobiology-bounty-reward-label", ("reward", (int) proto.PointsAwarded)));
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        _untilNextSkip -= TimeSpan.FromSeconds(args.DeltaSeconds);
        var waiting = _untilNextSkip > TimeSpan.Zero;
        SkipButton.Disabled = waiting;
        SkipButton.Text = waiting ? _untilNextSkip.ToString("mm\\:ss") : Loc.GetString("xenobiology-bounty-skip-button");
    }
}
