namespace Content.Client._WF.ShipAccess;

/// <summary>
/// Shuttle console tab where the deed holder sees and edits which ID cards may board: lock, allow list, nearby
/// people whose card can be added, each door's rule by clicking it on the door diagram, and the ship and door
/// codes. The server writes all of it into the doors' own access readers. Reads the networked grid and door
/// components straight; codes arrive by a directed event for the deed holder only and are forgotten when the tab
/// closes. Every change goes to the server as a message.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class ShipAccessScreen : BoxContainer
{
    [Dependency] private IEntityManager _entManager = default!;
    [Dependency] private IPlayerManager _player = default!;

    private const float RefreshInterval = 0.5f;
    private static readonly Color Readout = Color.FromHex("#00ff2a");
    private static readonly Color Muted = Color.FromHex("#9a9a9a");

    /// <summary>Rules in dropdown and legend order.</summary>
    private static readonly WFDoorAccessRule[] Rules =
    {
        WFDoorAccessRule.Default,
        WFDoorAccessRule.OwnerOnly,
        WFDoorAccessRule.Players,
        WFDoorAccessRule.Code,
        WFDoorAccessRule.PlayersOrCode,
        WFDoorAccessRule.Public,
        WFDoorAccessRule.Sealed,
    };

    private readonly WFShipAccessSystem _access;
    private readonly WFShipAccessClientSystem _client;
    private readonly EntityLookupSystem _lookup;
    private readonly SharedTransformSystem _transform;

    private EntityUid? _grid;
    private EntityUid? _console;
    private float _accumulator = RefreshInterval;
    private string? _listSnapshot;
    private string? _nearbySnapshot;
    private string? _doorSnapshot;
    private readonly Dictionary<WFShipAccessKey, CheckBox> _builderChecks = new();
    private readonly Dictionary<WFShipAccessKey, CheckBox> _doorPlayerChecks = new();

    /// <summary>The XAML hides the root while it loads, before the named controls exist.</summary>
    private readonly bool _loaded;

    // Codes, known only while the deed holder has the tab open.
    private bool _codesRequested;
    private bool _codesKnown;
    private string? _shipCode;
    private readonly Dictionary<NetEntity, string> _doorCodes = new();
    private int _misses;
    private int _lockedOut;

    /// <summary>The deed holder flipped the lock checkbox.</summary>
    public event Action<bool>? LockedChanged;

    /// <summary>The deed holder pressed Add on a nearby person.</summary>
    public event Action<NetEntity>? AddRequested;

    /// <summary>The deed holder pressed Remove on a listed card.</summary>
    public event Action<WFShipAccessKey>? RemoveRequested;

    /// <summary>The deed holder flipped a listed card's Builder checkbox.</summary>
    public event Action<WFShipAccessKey, bool>? BuilderChanged;

    /// <summary>The deed holder picked a rule for the selected door.</summary>
    public event Action<NetEntity, WFDoorAccessRule>? DoorRuleChanged;

    /// <summary>The deed holder confirmed one rule for every door on the ship.</summary>
    public event Action<WFDoorAccessRule>? AllDoorRulesChanged;

    /// <summary>The deed holder ticked or unticked a card on the selected door.</summary>
    public event Action<NetEntity, WFShipAccessKey, bool>? DoorPlayerChanged;

    /// <summary>The deed holder opened the tab and wants the codes.</summary>
    public event Action? CodesRequested;

    /// <summary>The deed holder set (4 digits) or cleared (null) the ship code.</summary>
    public event Action<string?>? ShipCodeChanged;

    /// <summary>The deed holder set (4 digits) or cleared (null) the selected door's code.</summary>
    public event Action<NetEntity, string?>? DoorCodeChanged;

    public ShipAccessScreen()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _loaded = true;

        _access = _entManager.System<WFShipAccessSystem>();
        _client = _entManager.System<WFShipAccessClientSystem>();
        _lookup = _entManager.System<EntityLookupSystem>();
        _transform = _entManager.System<SharedTransformSystem>();

        SetHint(DoorsEmptyLabel, Loc.GetString("ship-access-doors-empty"));
        SetHint(ShipCodeHint, Loc.GetString("ship-access-ship-code-hint"));
        SetHint(DoorCodeHint, Loc.GetString("ship-access-door-code-hint"));

        LockedCheck.OnToggled += args => LockedChanged?.Invoke(args.Pressed);
        DoorMap.DoorSelected += _ => Refresh();

        foreach (var rule in Rules)
            DoorRuleButton.AddItem(RuleName(rule), (int) rule);

        // The dropdown moves when the server's door state arrives, so a refused rule never shows.
        DoorRuleButton.OnItemSelected += args =>
        {
            if (DoorMap.Selected is { } door)
                DoorRuleChanged?.Invoke(_entManager.GetNetEntity(door), (WFDoorAccessRule) args.Id);
        };

        foreach (var rule in Rules)
            AllDoorsRuleButton.AddItem(RuleName(rule), (int) rule);

        AllDoorsRuleButton.OnItemSelected += args =>
        {
            AllDoorsRuleButton.SelectId(args.Id);
            RefreshAllDoorsHint();
        };
        AllDoorsApplyButton.OnPressed += _ => AllDoorRulesChanged?.Invoke((WFDoorAccessRule) AllDoorsRuleButton.SelectedId);
        RefreshAllDoorsHint();

        BuildLegend();

        _client.CodesReceived += OnCodes;
        _client.AlertReceived += OnAlert;
        ShipCodeEdit.IsValid = IsCodeInput;
        DoorCodeEdit.IsValid = IsCodeInput;
        ShipCodeEdit.OnTextChanged += args => ShipCodeSetButton.Disabled = !WFShipAccessSystem.IsValidCode(args.Text);
        DoorCodeEdit.OnTextChanged += args => DoorCodeSetButton.Disabled = !WFShipAccessSystem.IsValidCode(args.Text);
        ShipCodeEdit.OnTextEntered += _ => SetShipCode();
        DoorCodeEdit.OnTextEntered += _ => SetDoorCode();
        ShipCodeSetButton.OnPressed += _ => SetShipCode();
        DoorCodeSetButton.OnPressed += _ => SetDoorCode();
        ShipCodeClearButton.OnPressed += _ => ShipCodeChanged?.Invoke(null);
        DoorCodeClearButton.OnPressed += _ =>
        {
            if (DoorMap.Selected is { } door)
                DoorCodeChanged?.Invoke(_entManager.GetNetEntity(door), null);
        };
        ShipCodeRevealButton.OnToggled += _ => RefreshCodes();
        DoorCodeRevealButton.OnToggled += _ => RefreshCodes();
        WfRefitInstruments();
    }

    protected override void Dispose(bool disposing)
    {
        base.Dispose(disposing);
        if (!disposing)
            return;

        _client.CodesReceived -= OnCodes;
        _client.AlertReceived -= OnAlert;
    }

    /// <summary>Codes are only held while the tab is open.</summary>
    protected override void VisibilityChanged(bool newVisible)
    {
        base.VisibilityChanged(newVisible);
        if (_loaded && !newVisible)
            ForgetCodes();
    }

    /// <summary>The grid whose access is shown; null blanks the tab.</summary>
    public void SetShuttle(EntityUid? grid)
    {
        if (_grid != grid)
        {
            DoorMap.SetGrid(grid);
            ForgetCodes();
        }

        _grid = grid;
        _listSnapshot = null;
        _nearbySnapshot = null;
        _doorSnapshot = null;
        _accumulator = RefreshInterval;
    }

    /// <summary>The console the nearby list is measured from.</summary>
    public void SetConsole(EntityUid? console)
    {
        _console = console;
        DoorMap.SetConsole(console);
        _listSnapshot = null;
        _nearbySnapshot = null;
        _doorSnapshot = null;
    }

    /// <summary>Selects a door as a click on the diagram would.</summary>
    public void SelectDoor(EntityUid? door)
    {
        DoorMap.Selected = door;
        Refresh();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (!Visible)
            return;

        _accumulator += args.DeltaSeconds;
        if (_accumulator < RefreshInterval)
            return;

        _accumulator = 0f;
        Refresh();
    }

    /// <summary>
    /// Re-reads the grid and rebuilds the rows only when something shown has changed, so a checkbox is
    /// never rebuilt under the cursor. The nearby list and the selected door have their own snapshots, so
    /// people walking past the console leave the allow list rows alone. Checkbox states are re-synced every call.
    /// </summary>
    public void Refresh()
    {
        _entManager.TryGetComponent<WFShipAccessComponent>(_grid, out var comp);
        var local = _player.LocalEntity;
        // The deed, or the ship being registered to this player, decides who edits; a ship without the component yet
        // still lets its deed holder open the tab.
        var isOwner = _grid != null && local != null && _access.IsOwner(local.Value, _grid.Value);

        var sb = new StringBuilder();
        sb.Append(isOwner).Append('|');
        if (comp != null)
        {
            sb.Append(comp.OwnerName).Append('|').Append(comp.Mode.ToString()).Append('|').Append(comp.Locked).Append('|');
            foreach (var entry in comp.AllowList)
                sb.Append(entry.Key).Append(',').Append(entry.Name).Append(',').Append(entry.Label).Append(',').Append(entry.Builder).Append(';');
        }
        else if (_grid != null)
            sb.Append(_access.IsFactionGrid(_grid.Value, out _));

        var listSnapshot = sb.ToString();
        if (listSnapshot != _listSnapshot)
        {
            _listSnapshot = listSnapshot;
            RebuildList(comp, isOwner);
        }

        var nearby = isOwner ? FindNearby(comp) : new List<NearbyPerson>();
        sb.Clear();
        sb.Append(isOwner).Append('|');
        foreach (var person in nearby)
            sb.Append(person.Uid.Id).Append(',').Append(person.Name).Append(',').Append(person.HasCard).Append(',').Append(person.HasRecord).Append(';');

        var nearbySnapshot = sb.ToString();
        if (nearbySnapshot != _nearbySnapshot)
        {
            _nearbySnapshot = nearbySnapshot;
            RebuildNearby(isOwner, nearby);
        }

        DoorMap.RefreshDoors();
        DoorsEmptyLabel.Visible = _grid != null && DoorMap.Doors.Count == 0;
        var selected = DoorMap.Doors.FirstOrDefault(d => d.Uid == DoorMap.Selected);
        _entManager.TryGetComponent<WFDoorAccessRuleComponent>(selected?.Uid, out var rule);
        sb.Clear();
        sb.Append(isOwner).Append('|').Append(selected?.Uid.Id ?? 0).Append('|').Append(listSnapshot).Append('|');
        if (selected != null)
            sb.Append(selected.Name).Append('|').Append(selected.Rule).Append('|').Append(selected.HasOwnCode).Append('|');
        if (rule != null)
        {
            foreach (var key in rule.Players)
                sb.Append(key).Append(';');
        }

        var doorSnapshot = sb.ToString();
        if (doorSnapshot != _doorSnapshot)
        {
            _doorSnapshot = doorSnapshot;
            RebuildDoor(comp, selected, rule, isOwner);
        }

        SyncChecks(comp, rule);

        if (isOwner && !_codesRequested)
        {
            _codesRequested = true;
            CodesRequested?.Invoke();
        }

        RefreshCodes();
    }

    /// <summary>The codes and alert line, from what the server last sent. Labels only, so no rebuild.</summary>
    private void RefreshCodes()
    {
        var masked = Loc.GetString("ship-access-code-masked");
        var none = Loc.GetString("ship-access-code-none");
        ShipCodeLabel.Text = !_codesKnown ? "-" : _shipCode == null ? none : ShipCodeRevealButton.Pressed ? _shipCode : masked;
        ShipCodeClearButton.Disabled = _shipCode == null;

        var doorCode = DoorMap.Selected is { } door && _doorCodes.TryGetValue(_entManager.GetNetEntity(door), out var code) ? code : null;
        DoorCodeLabel.Text = !_codesKnown ? "-" : doorCode == null ? none : DoorCodeRevealButton.Pressed ? doorCode : masked;
        DoorCodeClearButton.Disabled = doorCode == null;

        CodeAlertLabel.Visible = _codesKnown && _misses > 0;
        CodeAlertLabel.Text = Loc.GetString("ship-access-code-alert", ("misses", _misses), ("locked", _lockedOut));
        CodeAlertLabel.ToolTip = CodeAlertLabel.Text;
    }

    private void OnCodes(WFShipAccessCodesEvent ev)
    {
        if (_grid == null || _entManager.GetEntity(ev.Grid) != _grid)
            return;

        _codesKnown = true;
        _shipCode = ev.ShipCode;
        _doorCodes.Clear();
        foreach (var (door, code) in ev.DoorCodes)
            _doorCodes[door] = code;

        _misses = ev.Misses;
        _lockedOut = ev.LockedOut;
        RefreshCodes();
    }

    private void OnAlert(WFShipAccessCodeAlertEvent ev)
    {
        if (_grid == null || _entManager.GetEntity(ev.Grid) != _grid)
            return;

        _misses = ev.Misses;
        _lockedOut = ev.LockedOut;
        RefreshCodes();
    }

    private void ForgetCodes()
    {
        _codesRequested = false;
        _codesKnown = false;
        _shipCode = null;
        _doorCodes.Clear();
        _misses = 0;
        _lockedOut = 0;
        ShipCodeRevealButton.Pressed = false;
        DoorCodeRevealButton.Pressed = false;
        ShipCodeEdit.Text = string.Empty;
        DoorCodeEdit.Text = string.Empty;
        RefreshCodes();
    }

    private void SetShipCode()
    {
        var code = ShipCodeEdit.Text;
        if (!WFShipAccessSystem.IsValidCode(code))
            return;

        ShipCodeChanged?.Invoke(code);
        ShipCodeEdit.Text = string.Empty;
    }

    private void SetDoorCode()
    {
        var code = DoorCodeEdit.Text;
        if (DoorMap.Selected is not { } door || !WFShipAccessSystem.IsValidCode(code))
            return;

        DoorCodeChanged?.Invoke(_entManager.GetNetEntity(door), code);
        DoorCodeEdit.Text = string.Empty;
    }

    /// <summary>Up to four digits while typing.</summary>
    private static bool IsCodeInput(string text)
    {
        if (text.Length > WFShipAccessSystem.CodeLength)
            return false;

        foreach (var c in text)
        {
            if (c < '0' || c > '9')
                return false;
        }

        return true;
    }

    private void RebuildList(WFShipAccessComponent? comp, bool isOwner)
    {
        ReadOnlyLabel.Visible = !isOwner;
        LockedCheck.Visible = isOwner;
        LockedLabel.Visible = !isOwner;
        CodeBox.Visible = isOwner;
        AllDoorsBox.Visible = isOwner;

        OwnerLabel.Text = comp != null && comp.OwnerName.Length > 0 ? comp.OwnerName : Loc.GetString("ship-access-owner-none");
        var faction = comp != null ? comp.Mode == WFShipAccessMode.Faction : _grid != null && _access.IsFactionGrid(_grid.Value, out _);
        ModeLabel.Text = Loc.GetString(faction ? "ship-access-mode-faction" : "ship-access-mode-private");
        OwnerLabel.ToolTip = OwnerLabel.Text;
        LockedLabel.Text = comp == null ? "-" : Loc.GetString(comp.Locked ? "ship-access-locked-yes" : "ship-access-locked-no");

        _builderChecks.Clear();
        AllowListContainer.DisposeAllChildren();
        if (comp != null)
        {
            foreach (var entry in comp.AllowList)
                AllowListContainer.AddChild(EntryRow(entry, isOwner));
        }

        AllowListEmptyLabel.Visible = AllowListContainer.ChildCount == 0;
    }

    private void RebuildNearby(bool isOwner, List<NearbyPerson> nearby)
    {
        NearbyBox.Visible = isOwner;
        NearbyContainer.DisposeAllChildren();
        foreach (var person in nearby)
            NearbyContainer.AddChild(NearbyRow(person));

        NearbyEmptyLabel.Visible = nearby.Count == 0;
    }

    /// <summary>The selected door's editor: name, rule, its cards and its code.</summary>
    private void RebuildDoor(WFShipAccessComponent? comp, ShipAccessDoorNode? selected, WFDoorAccessRuleComponent? rule, bool isOwner)
    {
        DoorNoneLabel.Visible = selected == null;
        DoorBox.Visible = selected != null;
        _doorPlayerChecks.Clear();
        DoorPlayersContainer.DisposeAllChildren();
        if (selected == null)
            return;

        DoorNameLabel.Text = DoorLabel(selected);
        DoorRuleLabel.Text = RuleName(selected.Rule);
        DoorRuleLabel.FontColorOverride = ShipAccessDoorMapControl.ColorFor(selected.Rule);
        DoorRuleButton.Visible = isOwner;
        DoorRuleButton.SelectId((int) selected.Rule);
        SetHint(DoorRuleHint, Loc.GetString(RuleKey(selected.Rule, "desc")));
        DoorRuleHint.Visible = !isOwner;
        DoorRuleButton.ToolTip = DoorRuleHint.ToolTip;
        DoorRuleLabel.ToolTip = DoorRuleHint.ToolTip;
        DoorNameLabel.ToolTip = DoorNameLabel.Text;

        DoorCodeBox.Visible = isOwner && WFShipAccessSystem.TakesCode(selected.Rule);
        var takesPlayers = WFShipAccessSystem.TakesPlayers(selected.Rule);
        DoorPlayersBox.Visible = takesPlayers;
        if (!takesPlayers)
            return;

        var netDoor = _entManager.GetNetEntity(selected.Uid);
        if (comp != null)
        {
            foreach (var entry in comp.AllowList)
            {
                var key = entry.Key;
                var check = new CheckBox
                {
                    Text = entry.Name,
                    Pressed = Picked(rule, key),
                    Disabled = !isOwner,
                    Margin = new Thickness(4, 0),
                };
                check.OnToggled += args => DoorPlayerChanged?.Invoke(netDoor, key, args.Pressed);
                _doorPlayerChecks[key] = check;
                WfStyleAccess(check);
                DoorPlayersContainer.AddChild(check);
            }
        }

        DoorPlayersEmptyLabel.Visible = DoorPlayersContainer.ChildCount == 0;
    }

    /// <summary>What the rule picked for every door does, under the set-all control.</summary>
    private void RefreshAllDoorsHint()
    {
        var rule = (WFDoorAccessRule) AllDoorsRuleButton.SelectedId;
        SetHint(AllDoorsHint, Loc.GetString("ship-access-all-doors-hint", ("desc", Loc.GetString(RuleKey(rule, "desc")))));
        AllDoorsRuleButton.ToolTip = AllDoorsHint.ToolTip;
    }

    /// <summary>Whether a listed card's key is on the door's own list.</summary>
    private static bool Picked(WFDoorAccessRuleComponent? rule, WFShipAccessKey key)
    {
        return rule != null && rule.Players.Contains(key);
    }

    /// <summary>Server state wins over a click the server refused.</summary>
    private void SyncChecks(WFShipAccessComponent? comp, WFDoorAccessRuleComponent? rule)
    {
        if (comp == null)
            return;

        LockedCheck.Pressed = comp.Locked;
        foreach (var entry in comp.AllowList)
        {
            if (_builderChecks.TryGetValue(entry.Key, out var check))
                check.Pressed = entry.Builder;

            if (_doorPlayerChecks.TryGetValue(entry.Key, out var doorCheck))
                doorCheck.Pressed = Picked(rule, entry.Key);
        }
    }

    private void BuildLegend()
    {
        foreach (var rule in Rules)
        {
            var row = new BoxContainer { Orientation = LayoutOrientation.Horizontal, Margin = new Thickness(6, 0), SeparationOverride = 6, HorizontalExpand = true };
            row.AddChild(Swatch(rule));
            row.AddChild(new Label { Text = RuleName(rule), HorizontalExpand = true, VerticalAlignment = VAlignment.Center, StyleClasses = { "LabelSecondaryColor" } });
            LegendContainer.AddChild(row);
        }
    }

    private static Control Swatch(WFDoorAccessRule rule)
    {
        return new PanelContainer
        {
            MinSize = new Vector2(12, 12),
            StyleClasses = { "WfNativeStyle" },
            VerticalAlignment = VAlignment.Center,
            Margin = new Thickness(0, 0, 4, 0),
            PanelOverride = new StyleBoxFlat { BackgroundColor = ShipAccessDoorMapControl.ColorFor(rule) },
        };
    }

    /// <summary>Plain text in the muted hint colour, wrapped to the column.</summary>
    private static void SetHint(RichTextLabel label, string text)
    {
        label.SetMessage(FormattedMessage.FromUnformatted(text), Muted);
        label.ToolTip = text;
    }

    private Control EntryRow(WFShipAccessEntry entry, bool editable)
    {
        var row = Row();
        row.AddChild(new Label { Text = entry.Name, HorizontalExpand = true, VerticalAlignment = VAlignment.Center, FontColorOverride = Readout });

        if (entry.Label.Length > 0)
        {
            row.AddChild(new Label
            {
                Text = entry.Label,
                StyleClasses = { "LabelSecondaryColor" },
                VerticalAlignment = VAlignment.Center,
                Margin = new Thickness(0, 0, 8, 0),
            });
        }

        if (!editable)
            return WfAccessPersonRow(row);

        var key = entry.Key;
        var builder = new CheckBox
        {
            Text = Loc.GetString("ship-access-builder"),
            Pressed = entry.Builder,
            VerticalAlignment = VAlignment.Center,
            Margin = new Thickness(0, 0, 8, 0),
        };
        builder.OnToggled += args => BuilderChanged?.Invoke(key, args.Pressed);
        _builderChecks[key] = builder;
        row.AddChild(builder);

        var remove = new Button { Text = Loc.GetString("ship-access-remove"), MinWidth = 80 };
        remove.AddStyleClass("ButtonSquare");
        remove.OnPressed += _ => RemoveRequested?.Invoke(key);
        row.AddChild(remove);
        return WfAccessPersonRow(row);
    }

    private Control NearbyRow(NearbyPerson person)
    {
        var row = Row();
        row.AddChild(new Label { Text = person.Name, HorizontalExpand = true, VerticalAlignment = VAlignment.Center, FontColorOverride = Readout });

        if (!person.HasRecord)
        {
            row.AddChild(new Label
            {
                Text = Loc.GetString(person.HasCard ? "ship-access-no-record" : "ship-access-no-card"),
                StyleClasses = { "LabelSecondaryColor" },
                VerticalAlignment = VAlignment.Center,
                Margin = new Thickness(0, 0, 8, 0),
            });
        }

        var add = new Button { Text = Loc.GetString("ship-access-add"), MinWidth = 80, Disabled = !person.HasRecord };
        add.AddStyleClass("ButtonSquare");
        var netEntity = _entManager.GetNetEntity(person.Uid);
        add.OnPressed += _ => AddRequested?.Invoke(netEntity);
        row.AddChild(add);
        return WfAccessPersonRow(row);
    }

    private static BoxContainer Row()
    {
        return new BoxContainer
        {
            Orientation = LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            Margin = new Thickness(4, 2),
        };
    }

    /// <summary>"shuttle airlock (3, -2)": many doors share a name, so the tile tells them apart.</summary>
    private static string DoorLabel(ShipAccessDoorNode door)
    {
        return Loc.GetString("ship-access-door-label",
            ("name", door.Name),
            ("x", (int) MathF.Floor(door.Position.X)),
            ("y", (int) MathF.Floor(door.Position.Y)));
    }

    /// <summary>The rule's name from Fluent.</summary>
    public static string RuleName(WFDoorAccessRule rule)
    {
        return Loc.GetString(RuleKey(rule, "name"));
    }

    private static string RuleKey(WFDoorAccessRule rule, string suffix)
    {
        var id = rule switch
        {
            WFDoorAccessRule.OwnerOnly => "owner-only",
            WFDoorAccessRule.Players => "players",
            WFDoorAccessRule.Code => "code",
            WFDoorAccessRule.PlayersOrCode => "players-or-code",
            WFDoorAccessRule.Public => "public",
            WFDoorAccessRule.Sealed => "sealed",
            _ => "default",
        };
        return $"ship-access-rule-{id}-{suffix}";
    }

    /// <summary>
    /// Humanoids within adding range of the console, minus the viewer, anyone carrying this ship's deed and
    /// anyone whose card is listed already. People without a card, or with a card that has no crew record, are
    /// shown but cannot be added: a door reader can only be given a record key.
    /// </summary>
    private List<NearbyPerson> FindNearby(WFShipAccessComponent? comp)
    {
        var result = new List<NearbyPerson>();
        if (_grid == null || !_entManager.TryGetComponent<TransformComponent>(_console, out var xform))
            return result;

        var local = _player.LocalEntity;
        foreach (var humanoid in _lookup.GetEntitiesInRange<HumanoidAppearanceComponent>(xform.Coordinates, WFShipAccessSystem.AddRange, LookupFlags.Uncontained))
        {
            var uid = humanoid.Owner;
            // The lookup goes by bounds; the server's Add check is centre to centre, so list only who it would take.
            if (uid == local || !_transform.InRange(xform.Coordinates, _entManager.GetComponent<TransformComponent>(uid).Coordinates, WFShipAccessSystem.AddRange))
                continue;

            if (_access.IsOwner(uid, _grid.Value))
                continue;

            var hasCard = _access.TryGetCard(uid, out var card);
            WFShipAccessKey key = default;
            var hasRecord = hasCard && _access.TryGetKey(card, out key);
            if (hasRecord && comp != null && _access.TryGetEntry(comp, key, out _))
                continue;

            result.Add(new NearbyPerson(uid, _entManager.GetComponent<MetaDataComponent>(uid).EntityName, hasCard, hasRecord));
        }

        result.Sort((a, b) => string.CompareOrdinal(a.Name, b.Name));
        return result;
    }

    /// <summary>Someone near the console, and whether they carry a card and whether it has a crew record.</summary>
    private sealed record NearbyPerson(EntityUid Uid, string Name, bool HasCard, bool HasRecord);
}
