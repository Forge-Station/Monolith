        if (color == Color.FromHex("#3a0f0f"))
            return Color.FromHex(mid);

        if (color == Color.FromHex("#330000"))
            return Color.FromHex(input);

        if (color == Color.FromHex("#2a0a0a"))
            return Color.FromHex(entry);

        if (color == Color.FromHex("#220000"))
            return Color.FromHex(panel);

        if (color == Color.FromHex("#1a0a0a"))
            return Color.FromHex(darkest);

        if (color == Color.FromHex("#110000"))
            return Color.FromHex(darkest);

        return color;
    }

