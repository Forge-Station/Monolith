using System.Linq;
using Content.Client.Message;
using Content.Client.UserInterface.Controls;
using Content.Shared._WF.Xenobiology.Bounties;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;

namespace Content.Client._WF.Xenobiology.Bounties;

/// <summary>
/// A completed or skipped bounty.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class XenobiologyBountyHistoryEntry : BoxContainer
{
    [Dependency] private IPrototypeManager _proto = default!;

    public XenobiologyBountyHistoryEntry(XenobiologyBountyHistoryData bounty)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        IdLabel.SetMarkup(Loc.GetString("xenobiology-bounty-id-label", ("id", bounty.Id)));
        TimestampLabel.SetMarkup(bounty.Timestamp.ToString(@"hh\:mm\:ss"));
        NoticeLabel.SetMarkup(bounty.Result == XenobiologyBountyResult.Completed
            ? Loc.GetString("xenobiology-bounty-history-completed")
            : Loc.GetString("xenobiology-bounty-history-skipped", ("id", bounty.ActorName ?? string.Empty)));

        if (!_proto.TryIndex(bounty.Bounty, out var proto))
            return;

        ManifestLabel.SetMarkup(XenobiologyBountyMenu.Manifest(proto));
        RewardLabel.SetMarkup(Loc.GetString("xenobiology-bounty-reward-label", ("reward", (int) proto.PointsAwarded)));
    }
}
