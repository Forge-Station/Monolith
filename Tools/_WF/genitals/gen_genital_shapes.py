def write_if_changed(path, lines):
    text = NEWLINE.join(lines) + NEWLINE
    data = text.encode("utf-8")
    if os.path.exists(path):
        with open(path, "rb") as f:
            if f.read() == data:
                return False
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as f:
        f.write(data)
    return True


def main():
    groups = [
        ("shapes_penis.yml", penis_shapes(Rsi("cocks.rsi"))),
        ("shapes_testicles.yml", testicle_shapes(Rsi("balls.rsi"))),
        ("shapes_vagina.yml", vagina_shapes(Rsi("vagina.rsi"))),
        ("shapes_breasts.yml", breast_shapes(Rsi("breasts.rsi"))),
    ]

    loc_lines = [HEADER]
    changed = []
    for file_name, (shapes, loc) in groups:
        lines = [HEADER]
        for shape in shapes:
            if not shape.sizes:
                sys.exit(f"{shape.id}: no FRONT art found in {shape.rsi.name}")
            lines.append("")
            lines += shape.yaml()
        if write_if_changed(os.path.join(PROTO_OUT, file_name), lines):
            changed.append(file_name)

        loc_lines += ["", f"## {shapes[0].slot}"]
        for key, name, examine in loc:
            loc_lines.append(f"{key} = {name}")
            if examine is not None:
                loc_lines.append(f"{key}-examine = {examine}")

    loc_lines += ["", "## Hand-written shapes (shapes_extra.yml)"]
    for slot, suffix, name, examine in EXTRA_LOC:
        key = loc_key(slot, suffix)
        loc_lines.append(f"{key} = {name}")
        if examine is not None:
            loc_lines.append(f"{key}-examine = {examine}")

    if write_if_changed(LOC_OUT, loc_lines):
        changed.append(os.path.basename(LOC_OUT))

    total = sum(len(shapes) for _, (shapes, _) in groups)
    print(f"{total} shapes; " + (f"updated {', '.join(changed)}" if changed else "no changes"))


if __name__ == "__main__":
    main()
