    /// <summary>Applies the organ rules, shows the result and hands it to the profile editor.</summary>
    private void Commit(GenitalProfile edited)
    {
        _issues.Clear();
        _profile = GenitalProfileValidator.ValidateOrgans(edited, _proto, _issues);
        Refresh();
        OnProfileChanged?.Invoke(_profile);
    }

    private void EditPenis(Func<PenisProfile, PenisProfile> edit)
    {
        if (_profile.Penis is { } penis)
            Commit(_profile.WithPenis(edit(penis)));
    }

    private void EditTesticles(Func<TesticlesProfile, TesticlesProfile> edit)
    {
        if (_profile.Testicles is { } testicles)
            Commit(_profile.WithTesticles(edit(testicles)));
    }

    private void EditVagina(Func<VaginaProfile, VaginaProfile> edit)
    {
        if (_profile.Vagina is { } vagina)
            Commit(_profile.WithVagina(edit(vagina)));
    }

    private void EditBreasts(Func<BreastsProfile, BreastsProfile> edit)
    {
        if (_profile.Breasts is { } breasts)
            Commit(_profile.WithBreasts(edit(breasts)));
    }

    /// <summary>A newly included penis comes from the species' typical male anatomy, with its testicles.</summary>
    private void SetPenisIncluded(bool included)
    {
        if (!included)
        {
            // Also removes the testicles, its linked option.
            Commit(_profile.WithPenis(null));
            return;
        }

        if (_profile.Penis != null)
            return;

        var seed = Seed(true);
        var settings = GenitalProfileValidator.GetSettings(_proto);
        var penis = seed.Penis ?? GenitalColorDefaults.ApplyPenis(
            new PenisProfile(FirstShape(GenitalSlot.Penis), settings.DefaultLengthCm),
            GenitalColorDefaults.TissueColorFor(_species, _proto));

        _sheathChoice = penis.Sheath;
        Commit(_profile.WithPenis(penis).WithTesticles(seed.Penis != null ? seed.Testicles : null));
    }

    /// <summary>A newly included vagina comes from the species' typical female anatomy, with a womb unless that says otherwise.</summary>
    private void SetVaginaIncluded(bool included)
    {
        if (!included)
        {
            // Also removes the womb.
            Commit(_profile.WithVagina(null));
            return;
        }

        if (_profile.Vagina != null)
            return;

        var seed = Seed(false);
        var vagina = seed.Vagina ?? GenitalColorDefaults.ApplyVagina(
            new VaginaProfile(FirstShape(GenitalSlot.Vagina)),
            GenitalColorDefaults.TissueColorFor(_species, _proto));

        Commit(_profile.WithVagina(vagina).WithWomb(seed.Vagina == null || seed.Womb));
    }

    /// <summary>Newly included breasts come from the species' typical female anatomy, or the first shape at the default cup.</summary>
    private void SetBreastsIncluded(bool included)
    {
        if (!included)
        {
            Commit(_profile.WithBreasts(null));
            return;
        }

        if (_profile.Breasts != null)
            return;

        var settings = GenitalProfileValidator.GetSettings(_proto);
        var breasts = Seed(false).Breasts ?? GenitalColorDefaults.ApplyBreasts(
            new BreastsProfile(FirstShape(GenitalSlot.Breasts), settings.DefaultCup));

        Commit(_profile.WithBreasts(breasts));
    }

    private void SetTesticleType(TesticleType type)
    {
        if (type == TesticleType.None)
        {
            Commit(_profile.WithTesticles(null));
            return;
        }

        var settings = GenitalProfileValidator.GetSettings(_proto);
        var testicles = _profile.Testicles?.With(type: type)
                        ?? GenitalColorDefaults.ApplyTesticles(new TesticlesProfile(type, settings.DefaultTesticleSize));
        Commit(_profile.WithTesticles(testicles));
    }

    /// <summary>The remembered sheath comes back with a shape that allows it; the validator removes it otherwise.</summary>
    private void OnPenisShapePicked(ProtoId<GenitalShapePrototype> shape)
    {
        EditPenis(p => p.With(shape: shape, sheath: _sheathChoice));
    }

    /// <summary>Custom colour when "match skin" is turned off: the stored one, or the skin colour instead of untinted white.</summary>
    private Color SeedColour(Color stored)
    {
        return stored.Equals(Color.White) ? _skin : stored;
    }

