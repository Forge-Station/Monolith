    private void RebuildRoles()
    {
        _rolesTab.RemoveAllChildren();
        if (_state is not { HasCompany: true } state)
            return;

        var canManage = state.IsOwner || (state.Permissions & CompanyPermission.ManageRoles) != 0;
        var grantable = state.IsOwner ? CompanyPermission.All : state.Permissions;
        if (_editingRoleId is { } selected && state.Roles.All(role => role.RoleId != selected))
            _editingRoleId = null;

        var header = new BoxContainer { Orientation = LayoutOrientation.Horizontal, Margin = new Thickness(0, 0, 0, 4) };
        header.AddChild(_styles.MakeSubHeading(Loc.GetString("company-pda-tab-roles")));
        header.AddChild(new Label
        {
            Text = state.Roles.Count.ToString(),
            FontColorOverride = _styles.Theme.Text,
            HorizontalExpand = true,
            Align = Label.AlignMode.Right,
        });
        _rolesTab.AddChild(header);

        var columns = new BoxContainer
        {
            Orientation = LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            VerticalExpand = true,
            SeparationOverride = 10,
        };

        var list = new BoxContainer { Orientation = LayoutOrientation.Vertical, SeparationOverride = 2, Margin = new Thickness(4) };
        if (canManage)
        {
            var create = _styles.MakeButton(Loc.GetString("company-pda-role-new"));
            create.OnPressed += _ =>
            {
                _editingRoleId = null;
                RebuildRoles();
            };
            list.AddChild(create);
        }

        if (state.Roles.Count == 0)
            list.AddChild(_styles.MakeText(Loc.GetString("company-pda-roles-empty")));

        foreach (var role in state.Roles)
        {
            var title = $"{RoleLabel(role.Name)} — {Loc.GetString($"company-pda-access-{role.AccessTier.ToString().ToLowerInvariant()}")}{(role.IsDefault ? " *" : "")}";
            if (!canManage)
            {
                var summary = new BoxContainer { Orientation = LayoutOrientation.Vertical, SeparationOverride = 2 };
                summary.AddChild(_styles.MakeHeading(title));
                summary.AddChild(_styles.MakeText(DescribePermissions(role.Permissions)));
                list.AddChild(_styles.MakeEntry(summary));
                continue;
            }

            var pick = _styles.MakeButton(title);
            pick.HorizontalExpand = true;
            var roleId = role.RoleId;
            pick.OnPressed += _ =>
            {
                _editingRoleId = roleId;
                RebuildRoles();
            };
            list.AddChild(pick);
        }

        columns.AddChild(_styles.MakeListPanel(list));

        if (canManage)
        {
            var editorHost = new BoxContainer
            {
                Orientation = LayoutOrientation.Vertical,
                SetWidth = 420,
                SeparationOverride = 6,
            };
            var editing = _editingRoleId is { } id
                ? state.Roles.FirstOrDefault(role => role.RoleId == id)
                : null;
            editorHost.AddChild(editing == null
                ? BuildCreateRole(grantable)
                : BuildEditRole(editing, grantable));
            columns.AddChild(editorHost);
        }

        _rolesTab.AddChild(columns);
    }

