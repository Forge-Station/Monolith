using System.Linq;
using Content.Client.Message;
using Content.Client.UserInterface.Controls;
using Content.Shared._WF.Xenobiology.Bounties;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;

namespace Content.Client._WF.Xenobiology.Bounties;

/// <summary>
/// The xenobiology bounty console: open bounties and their history.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class XenobiologyBountyMenu : FancyWindow
{
    public event Action<string>? OnFulfillButtonPressed;
    public event Action<string>? OnSkipButtonPressed;

    private TimeSpan _untilNextRefresh;

    public XenobiologyBountyMenu()
    {
        RobustXamlLoader.Load(this);
        MasterTabContainer.SetTabTitle(0, Loc.GetString("xenobiology-bounty-tab-available"));
        MasterTabContainer.SetTabTitle(1, Loc.GetString("xenobiology-bounty-tab-history"));
    }

    public void UpdateEntries(List<XenobiologyBountyData> bounties, List<XenobiologyBountyHistoryData> history,
        TimeSpan untilNextSkip, TimeSpan untilNextRefresh)
    {
        _untilNextRefresh = untilNextRefresh;

        BountyEntriesContainer.RemoveAllChildren();
        foreach (var bounty in bounties)
        {
            var entry = new XenobiologyBountyEntry(bounty, untilNextSkip);
            entry.OnFulfillButtonPressed += () => OnFulfillButtonPressed?.Invoke(bounty.Id);
            entry.OnSkipButtonPressed += () => OnSkipButtonPressed?.Invoke(bounty.Id);
            BountyEntriesContainer.AddChild(entry);
        }

        BountyEntriesContainer.AddChild(new Control { MinHeight = 10 });

        BountyHistoryContainer.RemoveAllChildren();
        NoHistoryLabel.Visible = history.Count == 0;
        for (var i = history.Count - 1; i >= 0; i--)
        {
            BountyHistoryContainer.AddChild(new XenobiologyBountyHistoryEntry(history[i]));
        }
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        _untilNextRefresh -= TimeSpan.FromSeconds(args.DeltaSeconds);
        if (_untilNextRefresh > TimeSpan.Zero)
            GlobalRefreshTimer.SetMarkup(Loc.GetString("xenobiology-bounty-refresh-label", ("time", _untilNextRefresh.ToString("mm\\:ss"))));
    }

    /// <summary>
    /// The manifest line for a bounty's entries.
    /// </summary>
    public static string Manifest(XenobiologyBountyPrototype bounty)
    {
        var items = bounty.Entries.Select(entry => Loc.GetString("xenobiology-bounty-manifest-entry",
            ("amount", entry.Amount), ("item", Loc.GetString(entry.Name))));
        return Loc.GetString("xenobiology-bounty-manifest-label", ("item", string.Join(", ", items)));
    }
}
