    private bool IsSponsor()
    {
        var user = _players.LocalSession?.UserId;
        return user != null && _sponsors.TryGetSponsor(user.Value, out var level) && level != SponsorLevel.None;
    }

    private CompanyUiPalettePrototype ResolvePalette(string? id)
    {
        if (!string.IsNullOrWhiteSpace(id) &&
            _proto.TryIndex<CompanyUiPalettePrototype>(id, out var palette))
        {
            if (!palette.RequiresSponsor || IsSponsor())
                return palette;
        }

        var fallback = _proto.Index<CompanyUiPalettePrototype>(CompanyManagementStyles.DefaultPaletteId);
        if (_cfg.GetCVar(ForgeVars.CompanyUiPalette) != fallback.ID)
            _cfg.SetCVar(ForgeVars.CompanyUiPalette, fallback.ID);
        return fallback;
    }

