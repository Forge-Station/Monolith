    private void AddBank(BoxContainer parent, CompanyManagementUiState state)
    {
        var balances = new BoxContainer { Orientation = LayoutOrientation.Vertical, SeparationOverride = 4 };
        balances.AddChild(_styles.MakeHeading(Loc.GetString("company-pda-bank-balance", ("balance", Money(state.BankBalance)))));
        balances.AddChild(_styles.MakeText(Loc.GetString("company-pda-personal-balance", ("balance", Money(state.PersonalBalance)))));
        if (state.AtWar)
            balances.AddChild(_styles.MakeText(WarFreezeText(state)));
        parent.AddChild(_styles.MakeCard(balances));

        var amount = _styles.MakeLineEdit(Loc.GetString("company-pda-amount"));
        var actions = new BoxContainer
        {
            Orientation = LayoutOrientation.Horizontal,
            SeparationOverride = 6,
            Margin = new Thickness(4),
        };
        actions.AddChild(amount);

        if (state.IsOwner || (state.Permissions & CompanyPermission.BankDeposit) != 0)
        {
            var deposit = _styles.MakeButton(Loc.GetString("company-pda-deposit"));
            deposit.OnPressed += _ =>
            {
                if (int.TryParse(amount.Text, out var value))
                    Send(new CompanyManagementUiMessageEvent { Action = CompanyManagementUiAction.BankDeposit, Amount = value });
            };
            actions.AddChild(deposit);
        }

        if (state.IsOwner || (state.Permissions & CompanyPermission.BankWithdraw) != 0)
        {
            var withdraw = _styles.MakeButton(Loc.GetString("company-pda-withdraw"));
            withdraw.Disabled = state.AtWar;
            withdraw.OnPressed += _ =>
            {
                if (int.TryParse(amount.Text, out var value))
                    Send(new CompanyManagementUiMessageEvent { Action = CompanyManagementUiAction.BankWithdraw, Amount = value });
            };
            actions.AddChild(withdraw);
        }

        if (actions.ChildCount > 1)
            parent.AddChild(_styles.MakeActionPanel(actions));
    }

    private void RebuildRelations()
    {
        _relationsTab.RemoveAllChildren();
        if (_state is not { HasCompany: true } state)
            return;

        var kindById = new Dictionary<string, CompanyRelationKind>();
        foreach (var rel in state.Relations)
            kindById[rel.OtherCompany.Id] = rel.Kind;

        var companies = state.InviteableCompanies
            .OrderBy(company => RelationRank(state, company.Id, kindById.GetValueOrDefault(company.Id)))
            .ThenBy(company => Display(company.Name))
            .ToList();

        _relationsTab.AddChild(BuildAllyWarToggle(state));

        if (companies.Count == 0)
        {
            _relationsTab.AddChild(_styles.MakeListPanel(_styles.MakeText(Loc.GetString("company-pda-relations-none")), verticalExpand: false));
            return;
        }

        if (_selectedRelationCompany == null || companies.All(company => company.Id != _selectedRelationCompany))
            _selectedRelationCompany = companies[0].Id;

        var wars = companies.Count(company => kindById.GetValueOrDefault(company.Id) == CompanyRelationKind.War);
        var allies = companies.Count(company => kindById.GetValueOrDefault(company.Id) == CompanyRelationKind.Alliance);
        var summary = new BoxContainer
        {
            Orientation = LayoutOrientation.Horizontal,
            SeparationOverride = 16,
            Margin = new Thickness(2, 0, 2, 6),
        };
        summary.AddChild(StanceLabel(Loc.GetString("company-pda-relations-war-count", ("count", wars)), CompanyRelationKind.War));
        summary.AddChild(StanceLabel(Loc.GetString("company-pda-relations-alliance-count", ("count", allies)), CompanyRelationKind.Alliance));
        _relationsTab.AddChild(summary);

        var columns = new BoxContainer
        {
            Orientation = LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            VerticalExpand = true,
            SeparationOverride = 10,
        };

        var list = new BoxContainer { Orientation = LayoutOrientation.Vertical, SeparationOverride = 4, Margin = new Thickness(4) };
        foreach (var company in companies)
        {
            var kind = kindById.GetValueOrDefault(company.Id);
            list.AddChild(BuildRelationRow(company, kind, company.Id == _selectedRelationCompany, state));
        }

        var listScroll = new ScrollContainer
        {
            VerticalExpand = true,
            HorizontalExpand = true,
            HScrollEnabled = false,
            MinHeight = 320,
        };
        listScroll.AddChild(list);
        columns.AddChild(_styles.MakeListPanel(listScroll));

        var selected = companies.First(company => company.Id == _selectedRelationCompany);
        columns.AddChild(BuildRelationDetail(selected, kindById.GetValueOrDefault(selected.Id), state));
        _relationsTab.AddChild(columns);
    }

    private Control BuildAllyWarToggle(CompanyManagementUiState state)
    {
        var canChange = state.IsOwner ||
                        (state.Permissions & (CompanyPermission.DeclareWar | CompanyPermission.DeclareAlliance)) != 0;
        var box = new CheckBox
        {
            Text = Loc.GetString("company-ally-war-toggle"),
            Pressed = state.AutoJoinAllyWars,
            Disabled = !canChange,
            HorizontalExpand = true,
        };
        _styles.StyleCheckBox(box);
        _styles.TintLabel(box.Label);
        box.OnToggled += args =>
        {
            Send(new CompanyManagementUiMessageEvent
            {
                Action = CompanyManagementUiAction.SetAutoJoinAllyWars,
                BoolValue = args.Pressed,
            });
        };

        var body = new BoxContainer
        {
            Orientation = LayoutOrientation.Vertical,
            SeparationOverride = 4,
        };
        body.AddChild(box);
        body.AddChild(_styles.MakeText(Loc.GetString("company-ally-war-purpose"), _styles.Theme.SubText));
        var card = _styles.MakeCard(body);
        card.Margin = new Thickness(0, 0, 0, 6);
        return card;
    }

    private Control BuildRelationRow(CompanyPickerEntry company, CompanyRelationKind kind, bool selected, CompanyManagementUiState state)
    {
        var pending = AlliancePending(state, company.Id, kind);
        var color = pending ? RelationColor(CompanyRelationKind.Alliance) : RelationColor(kind);
        var relationName = pending
            ? Loc.GetString("company-pda-relation-alliance-pending")
            : Loc.GetString($"company-pda-relation-{kind.ToString().ToLowerInvariant()}");
        var body = new BoxContainer { Orientation = LayoutOrientation.Horizontal, SeparationOverride = 8 };
        body.AddChild(new PanelContainer
        {
            MinSize = new System.Numerics.Vector2(4, 28),
            VerticalExpand = true,
            PanelOverride = _styles.MakePanelBox(color, color, 0, new Thickness(0)),
        });

        if (TryGetCompanyIcon(company.IconId, out var tex))
        {
            body.AddChild(new TextureRect
            {
                Texture = tex,
                SetSize = new System.Numerics.Vector2(28, 28),
                Stretch = TextureRect.StretchMode.KeepAspectCentered,
                VerticalAlignment = VAlignment.Center,
            });
        }

        var text = new BoxContainer { Orientation = LayoutOrientation.Vertical, HorizontalExpand = true };
        text.AddChild(_styles.MakeHeading(Display(company.Name)));
        text.AddChild(_styles.MakeText(relationName, color));
        body.AddChild(text);

        var card = new PanelContainer
        {
            HorizontalExpand = true,
            PanelOverride = _styles.MakePanelBox(
                selected ? _styles.Theme.CardBackground : _styles.Theme.EntryBackground,
                selected ? color : _styles.Theme.EntryBorder,
                selected ? 2 : 1,
                new Thickness(8, 6, 8, 6)),
        };
        card.AddChild(body);

        var button = new ContainerButton { HorizontalExpand = true, Margin = new Thickness(0, 0, 0, 2) };
        var id = company.Id;
        button.OnPressed += _ =>
        {
            _selectedRelationCompany = id;
            RebuildRelations();
        };
        button.AddChild(card);
        return button;
    }

    private Control BuildRelationDetail(CompanyPickerEntry company, CompanyRelationKind kind, CompanyManagementUiState state)
    {
        var color = RelationColor(kind);
        var pending = AlliancePending(state, company.Id, kind);
        var relationName = pending
            ? Loc.GetString("company-pda-relation-alliance-pending")
            : Loc.GetString($"company-pda-relation-{kind.ToString().ToLowerInvariant()}");
        var relationColor = pending ? RelationColor(CompanyRelationKind.Alliance) : color;
        var root = new BoxContainer
        {
            Orientation = LayoutOrientation.Vertical,
            SetWidth = 340,
            SeparationOverride = 8,
        };

        root.AddChild(new PanelContainer
        {
            MinHeight = 6,
            HorizontalExpand = true,
            PanelOverride = _styles.MakePanelBox(company.Color, company.Color, 0, new Thickness(0)),
        });

        var titleRow = new BoxContainer { Orientation = LayoutOrientation.Horizontal, SeparationOverride = 8 };
        if (TryGetCompanyIcon(company.IconId, out var tex))
        {
            titleRow.AddChild(new TextureRect
            {
                Texture = tex,
                SetSize = new System.Numerics.Vector2(48, 48),
                Stretch = TextureRect.StretchMode.KeepAspectCentered,
                VerticalAlignment = VAlignment.Center,
            });
        }

        var titleText = new BoxContainer { Orientation = LayoutOrientation.Vertical, HorizontalExpand = true };
        titleText.AddChild(_styles.MakeHeading(Display(company.Name)));
        titleText.AddChild(_styles.MakeText(relationName, relationColor));
        titleRow.AddChild(titleText);
        root.AddChild(titleRow);

        root.AddChild(_styles.MakeText(Loc.GetString($"company-pda-relation-blurb-{kind.ToString().ToLowerInvariant()}"), color));

        AddRichBlock(root, "company-pda-relation-dossier", Display(company.Description));
        AddRichBlock(root, "company-pda-relation-note", Display(company.Note));

        var canWar = state.IsOwner || (state.Permissions & CompanyPermission.DeclareWar) != 0;
        var canAlliance = state.IsOwner || (state.Permissions & CompanyPermission.DeclareAlliance) != 0;
        var actions = new BoxContainer { Orientation = LayoutOrientation.Vertical, SeparationOverride = 4 };
        if (state.AtWar)
            actions.AddChild(_styles.MakeText(WarFreezeText(state)));
        LineEdit? statement = null;
        if (canWar || canAlliance)
        {
            statement = _styles.MakeLineEdit(Loc.GetString("company-pda-relation-statement"));
            actions.AddChild(statement);
        }

        string? Words() => string.IsNullOrWhiteSpace(statement?.Text) ? null : statement.Text.Trim();

        if (canWar)
        {
            actions.AddChild(RelationButton(
                Loc.GetString("company-pda-declare-war-priced", ("cost", Money(state.WarCost))),
                kind == CompanyRelationKind.War || state.SpendableBalance < state.WarCost,
                () => Send(new CompanyManagementUiMessageEvent
                {
                    Action = CompanyManagementUiAction.SetRelation,
                    CompanyId = company.Id,
                    RelationKind = CompanyRelationKind.War,
                    Text = Words(),
                })));
            AddPriceNote(actions, state.WarCost, state.SpendableBalance, "company-diplomacy-war-purpose");
        }

        if (canAlliance && kind == CompanyRelationKind.War)
            actions.AddChild(_styles.MakeText(Loc.GetString("company-alliance-at-war")));
        else if (canAlliance && kind != CompanyRelationKind.Alliance)
            AddAlliancePanel(actions, company, RelationWith(state, company.Id), state, Words);

        if (kind == CompanyRelationKind.War)
            AddPeacePanel(actions, company, RelationWith(state, company.Id), state, Words);
        else if ((canWar || canAlliance) && kind == CompanyRelationKind.Alliance)
        {
            actions.AddChild(RelationButton(
                Loc.GetString("company-pda-break-alliance-priced", ("cost", Money(state.BreakAllianceCost))),
                state.SpendableBalance < state.BreakAllianceCost,
                () => Send(new CompanyManagementUiMessageEvent
                {
                    Action = CompanyManagementUiAction.ClearRelation,
                    CompanyId = company.Id,
                    Text = Words(),
                })));
            AddPriceNote(actions, state.BreakAllianceCost, state.SpendableBalance, "company-diplomacy-break-purpose");
        }

        if (actions.ChildCount > 0)
            root.AddChild(actions);

        return _styles.MakeCard(root);
    }

    private static CompanyRelationData? RelationWith(CompanyManagementUiState state, string companyId)
    {
        foreach (var rel in state.Relations)
        {
            if (rel.OtherCompany.Id == companyId)
                return rel;
        }

        return null;
    }

