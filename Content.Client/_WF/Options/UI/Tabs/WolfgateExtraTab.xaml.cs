using System.Linq;
using Content.Client._WF.Stylesheets;
using Content.Client.Options.UI;
using Content.Shared._DV.CCVars;
using Content.Shared._WF.Camera;
using Content.Shared._WF.CCVar;
using Content.Shared._WF.Newbie;
using Content.Shared._WF.Wolfmed.CCVar;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._WF.Options.UI.Tabs;

/// <summary>The Extra tab: every fork setting a player can change, on the shared Apply row.</summary>
[GenerateTypedNameReferences]
public sealed partial class WolfgateExtraTab : Control
{
    public WolfgateExtraTab()
    {
        RobustXamlLoader.Load(this);

        var styles = WolfgateSkins.All
            .Select(skin => new OptionDropDownCVar<string>.ValueOption(skin.Id, Loc.GetString(skin.Name)))
            .ToList();
        Control.AddOptionDropDown(WolfgateCVars.UiStyle, DropDownWolfgateStyle, styles);
        Control.AddOptionCheckBox(WolfgateCVars.WindowPopout, WindowPopoutCheckBox);
        Control.AddOptionCheckBox(WolfgateCVars.CockpitAutoEnter, CockpitAutoEnterCheckBox);
        Control.AddOptionCheckBox(WFCameraCVars.DefaultNorth, DefaultNorthCheckBox);
        Control.AddOptionCheckBox(WFNewbieCVars.ShowTag, ShowNewbieTagCheckBox);

        Control.AddOptionCheckBox(HeatHazeCVars.Enabled, HeatHazeCheckBox);
        Control.AddOptionPercentSlider(HeatHazeCVars.Strength, HeatHazeStrengthSlider, 0, 2);
        Control.AddOptionCheckBox(ShockwaveCVars.Enabled, ShockwaveCheckBox);
        Control.AddOptionPercentSlider(ShockwaveCVars.Strength, ShockwaveStrengthSlider, 0, 2);

        Control.AddOptionCheckBox(WolfmedCVars.CritHeartbeat, CritHeartbeatCheckBox);
        Control.AddOptionCheckBox(WolfmedCVars.DyingEffects, DyingEffectsCheckBox);
        Control.AddOptionCheckBox(WolfmedCVars.SyntheticHud, SyntheticHudCheckBox);
        Control.AddOptionPercentSlider(WolfmedCVars.SyntheticHudScale, SyntheticHudScaleSlider, 0.6f, 2.5f);

        Control.AddOptionPercentSlider(InternetSoundCVars.Volume, InternetSoundVolumeSlider);
        Control.AddOptionPercentSlider(JukeboxVolumeCVars.Volume, JukeboxVolumeSlider);
        Control.AddOptionCheckBox(SoundtrackMuteCVars.Enabled, SoundtrackMuteCheckBox);

        // The one setting of the Delta-V tab this one replaces.
        Control.AddOptionCheckBox(DCCVars.NoVisionFilters, DisableFiltersCheckBox);

        Control.Initialize();
    }
}
