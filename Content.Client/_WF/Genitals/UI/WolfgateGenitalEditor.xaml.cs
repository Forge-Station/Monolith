    /// <summary>Direction the shape tiles face; follows the preview doll.</summary>
    public Direction PreviewDirection
    {
        get => _direction;
        set
        {
            _direction = value;
            foreach (var grid in ShapeGrids())
            {
                foreach (var child in grid.Children)
                {
                    if (child is WolfgateGenitalShapeTile tile)
                        tile.SetDirection(value);
                }
            }
        }
    }

    /// <summary>Rebuilds gates, presets, notices and tile colours. Never raises OnProfileChanged.</summary>
    /// <remarks>Runs on every age keystroke and species change, so it must never write to the profile.</remarks>
    public void SetContext(string species, Sex sex, int age, Color skinColor, IReadOnlyCollection<Marking> markings)
    {
        // A confirmation asked for another species or sex no longer describes what would be applied.
        if (species != _species || sex != _sex)
            HidePresetConfirm();

        _species = species;
        _sex = sex;
        _age = GenitalProfileValidator.ClampAge(age, species, _proto);
        _skin = skinColor;
        _speciesHasUndergarments = SpeciesHasUndergarments(species);

        _wearsUndergarment = false;
        _pregnancyMarking = false;
        foreach (var marking in markings)
        {
            if (marking.MarkingId.StartsWith(PregnancyMarkingPrefix, StringComparison.Ordinal))
                _pregnancyMarking = true;

            if (_markingManager.TryGetMarking(marking, out var proto)
                && proto.MarkingCategory is MarkingCategories.UndergarmentTop or MarkingCategories.UndergarmentBottom)
                _wearsUndergarment = true;
        }

        Refresh();
    }

    /// <summary>Shows a profile's anatomy. Raises no events; organ-rule fixes are only written back after an edit.</summary>
    public void SetProfile(GenitalProfile profile)
    {
        _issues.Clear();
        _profile = GenitalProfileValidator.ValidateOrgans(profile, _proto, _issues);
        _sheathChoice = _profile.Penis?.Sheath ?? SheathType.None;
        HidePresetConfirm();
        Refresh();
    }

    /// <summary>Re-reads the local consent settings; called whenever the server sends them.</summary>
    public void RefreshConsent()
    {
        Refresh();
    }

    /// <summary>Preview back to As worn and resting arousal, including dolls already filled with the old settings.</summary>
    public void ResetPreview()
    {
        PreviewSystem?.ResetPreview();

        _syncing = true;
        try
        {
            _previewMode.Select(GenitalPreviewMode.AsWorn);
            _previewArousal.Select(ArousalState.None);
        }
        finally
        {
            _syncing = false;
        }
    }

    /// <summary>Markings the markings tab must not offer: the adult-only ones while the character is below the adult age.</summary>
    public static IReadOnlySet<string> HiddenMarkingsFor(string species, int age, IPrototypeManager proto)
    {
        var settings = GenitalProfileValidator.GetSettings(proto);
        return GenitalProfileValidator.ClampAge(age, species, proto) < settings.AdultAge
            ? new HashSet<string>(settings.AdultOnlyMarkings)
            : NoHiddenMarkings;
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();
        _consent.OnServerDataLoaded += RefreshConsent;
        _cfg.OnValueChanged(WolfgateCVars.AnatomyEnabled, OnAnatomyEnabledChanged);
        Refresh();
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();
        _consent.OnServerDataLoaded -= RefreshConsent;
        _cfg.UnsubValueChanged(WolfgateCVars.AnatomyEnabled, OnAnatomyEnabledChanged);
        ResetPreview();
    }

    protected override void Resized()
    {
        base.Resized();
        UpdateColumns();
    }

