        createEditor.NameEdit.PlaceHolder = Loc.GetString("company-pda-role-name");
        createBody.AddChild(createEditor.Root);

        var create = _styles.MakeButton(Loc.GetString("company-pda-create-role"));
        create.OnPressed += _ =>
        {
            if (string.IsNullOrWhiteSpace(createEditor.NameEdit.Text))
                return;
            Send(new CompanyManagementUiMessageEvent
            {
                Action = CompanyManagementUiAction.CreateRole,
                Text = createEditor.NameEdit.Text,
                AccessTier = createEditor.GetTier(),
                Permissions = createEditor.GetPermissions(),
            });
        };
        createBody.AddChild(create);
        _rolesTab.AddChild(_styles.MakeActionPanel(createBody));
    }

    private Control BuildRoleCard(CompanyRoleData role, bool canManage, CompanyPermission grantable)
    {
        var body = new BoxContainer { Orientation = LayoutOrientation.Vertical, SeparationOverride = 4 };

        var title = $"{role.Name} — {Loc.GetString($"company-pda-access-{role.AccessTier.ToString().ToLowerInvariant()}")}{(role.IsDefault ? " *" : "")}";
        body.AddChild(_styles.MakeHeading(title));

        var flagsLabel = string.Join(", ",
            EditablePermissions
                .Where(p => (role.Permissions & p) != 0)
                .Select(p => Loc.GetString($"company-pda-perm-{p.ToString().ToLowerInvariant()}")));
        body.AddChild(_styles.MakeText(string.IsNullOrEmpty(flagsLabel)
            ? Loc.GetString("company-pda-perm-none")
            : flagsLabel));

        if (!canManage)
            return _styles.MakeCard(body);

        body.AddChild(_styles.MakeDivider());
        var editor = BuildRoleEditor(role.Name, role.AccessTier, role.Permissions, grantable);
        body.AddChild(editor.Root);

        var actions = new BoxContainer { Orientation = LayoutOrientation.Horizontal, SeparationOverride = 4 };
        var save = _styles.MakeButton(Loc.GetString("company-pda-save-role"));
        var roleId = role.RoleId;
        save.OnPressed += _ =>
        {
            Send(new CompanyManagementUiMessageEvent
            {
                Action = CompanyManagementUiAction.UpdateRole,
                GuidValue = roleId,
                Text = editor.NameEdit.Text,
                AccessTier = editor.GetTier(),
                Permissions = editor.GetPermissions(),
            });
        };
        actions.AddChild(save);

        if (!role.IsDefault)
        {
            var del = _styles.MakeButton(Loc.GetString("company-pda-delete-role"));
            del.OnPressed += _ => Send(new CompanyManagementUiMessageEvent
            {
                Action = CompanyManagementUiAction.DeleteRole,
                GuidValue = roleId,
            });
            actions.AddChild(del);
        }

        body.AddChild(actions);
        return _styles.MakeCard(body);
    }

    private RoleEditor BuildRoleEditor(
        string name,
        CompanyAccessTier tier,
        CompanyPermission permissions,
        CompanyPermission grantable)
    {
        var root = new BoxContainer { Orientation = LayoutOrientation.Vertical, Margin = new Thickness(0, 0, 0, 2), SeparationOverride = 3 };
        var nameEdit = _styles.MakeLineEdit(text: name);
        root.AddChild(nameEdit);

        var tierBtn = new OptionButton();
        _styles.StyleOption(tierBtn);
        tierBtn.AddItem(Loc.GetString("company-pda-access-low"), (int)CompanyAccessTier.Low);
        tierBtn.AddItem(Loc.GetString("company-pda-access-medium"), (int)CompanyAccessTier.Medium);
        tierBtn.AddItem(Loc.GetString("company-pda-access-high"), (int)CompanyAccessTier.High);
        tierBtn.SelectId((int)tier);
        root.AddChild(tierBtn);

        var checks = new Dictionary<CompanyPermission, CheckBox>();
        foreach (var perm in EditablePermissions)
        {
            if ((grantable & perm) == 0)
                continue;

            var box = new CheckBox
            {
                Text = Loc.GetString($"company-pda-perm-{perm.ToString().ToLowerInvariant()}"),
                Pressed = (permissions & perm) != 0,
            };
            _styles.StyleCheckBox(box);
            checks[perm] = box;
            root.AddChild(box);
        }

        return new RoleEditor(root, nameEdit, tierBtn, checks);
    }

    private sealed class RoleEditor
    {
        public BoxContainer Root { get; }
        public LineEdit NameEdit { get; }
        private readonly OptionButton _tier;
        private readonly Dictionary<CompanyPermission, CheckBox> _checks;

        public RoleEditor(
            BoxContainer root,
            LineEdit nameEdit,
            OptionButton tier,
            Dictionary<CompanyPermission, CheckBox> checks)
        {
            Root = root;
            NameEdit = nameEdit;
            _tier = tier;
            _checks = checks;
        }

        public CompanyAccessTier GetTier() =>
            (CompanyAccessTier)Math.Max((int)CompanyAccessTier.Low, _tier.SelectedId);

        public CompanyPermission GetPermissions()
        {
            var result = CompanyPermission.None;
            foreach (var (perm, box) in _checks)
            {
                if (box.Pressed)
                    result |= perm;
            }

            return result;
        }
    }

