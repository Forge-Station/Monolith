    private void RecolorControl(Control control)
    {
        if (control is Label label)
        {
            if (label.FontColorOverride is { } fontColor)
                label.FontColorOverride = RecolorUiColor(fontColor);
        }

        control.Modulate = RecolorUiColor(control.Modulate);
        if (control.ModulateSelfOverride is { } selfModulate)
            control.ModulateSelfOverride = RecolorUiColor(selfModulate);

        if (control is PanelContainer { PanelOverride: StyleBoxFlat style })
            RecolorStyle(style);

        foreach (var child in control.Children)
            RecolorControl(child);
    }

    private void RecolorStyle(StyleBoxFlat style)
    {
        style.BackgroundColor = RecolorUiColor(style.BackgroundColor);
        style.BorderColor = RecolorUiColor(style.BorderColor);
    }

