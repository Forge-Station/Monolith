    {
        _rolesTab.RemoveAllChildren();
        if (_state is not { HasCompany: true } state)
            return;

        var canManage = state.IsOwner || (state.Permissions & CompanyPermission.ManageRoles) != 0;
        var grantable = state.IsOwner ? CompanyPermission.All : state.Permissions;

        var header = new BoxContainer { Orientation = LayoutOrientation.Horizontal, Margin = new Thickness(0, 0, 0, 4) };
        header.AddChild(_styles.MakeSubHeading(Loc.GetString("company-pda-tab-roles")));
